#include "../common/xl_common.h"

const char* xlStdSysFileModuleSource(void)
{
	return
		"import std.fs\n"
		"\n"
		"func exists(string path) as bool\n"
		"\treturn fs.exists(path)\n"
		"end\n"
		"func is_file(string path) as bool\n"
		"\treturn fs.is_file(path)\n"
		"end\n"
		"func is_dir(string path) as bool\n"
		"\treturn fs.is_dir(path)\n"
		"end\n"
		"func size(string path) as int\n"
		"\treturn fs.size(path)\n"
		"end\n"
		"func read_all(string path) as string\n"
		"\treturn fs.read_all(path)\n"
		"end\n"
		"func write_all(string path, string text) as bool\n"
		"\treturn fs.write_all(path, text)\n"
		"end\n"
		"func append_all(string path, string text) as bool\n"
		"\treturn fs.append_all(path, text)\n"
		"end\n"
		"func delete(string path) as bool\n"
		"\treturn fs.delete(path)\n"
		"end\n"
		"\n"
		"export exists\n"
		"export is_file\n"
		"export is_dir\n"
		"export size\n"
		"export read_all\n"
		"export write_all\n"
		"export append_all\n"
		"export delete\n";
}
