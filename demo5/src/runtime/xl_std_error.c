#include "../common/xl_common.h"

const char* xlStdErrorModuleSource(void)
{
	return
		"func kind(error value) as string\n"
		"\treturn value.type\n"
		"end\n"
		"func message(error value) as string\n"
		"\treturn value.message\n"
		"end\n"
		"func code(error value) as int\n"
		"\treturn value.code\n"
		"end\n"
		"func data(error value) as string\n"
		"\treturn value.data\n"
		"end\n"
		"func stack(error value) as string\n"
		"\treturn value.stack\n"
		"end\n"
		"func cause(error value) as error\n"
		"\treturn value.cause\n"
		"end\n"
		"func text(error value) as string\n"
		"\treturn value\n"
		"end\n"
		"func is_type(error value, string type_name) as bool\n"
		"\treturn value.type == type_name\n"
		"end\n"
		"func is_native(error value) as bool\n"
		"\treturn value.type == \"NativeError\"\n"
		"end\n"
		"\n"
		"export kind\n"
		"export message\n"
		"export code\n"
		"export data\n"
		"export stack\n"
		"export cause\n"
		"export text\n"
		"export is_type\n"
		"export is_native\n";
}
