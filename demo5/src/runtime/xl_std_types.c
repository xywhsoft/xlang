#include "../common/xl_common.h"

const char* xlStdTypesModuleSource(void)
{
	return
		"class DynamicTypeDesc extends object\n"
		"\tvar name as string\n"
		"\tvar base as type\n"
		"\tcreate(string type_name, type base_type)\n"
		"\t\tself.name = type_name\n"
		"\t\tself.base = base_type\n"
		"\tend\n"
		"end\n"
		"\n"
		"class DynamicObject extends object\n"
		"\tvar desc as DynamicTypeDesc\n"
		"\tcreate(DynamicTypeDesc descriptor)\n"
		"\t\tself.desc = descriptor\n"
		"\tend\n"
		"end\n"
		"\n"
		"func of(var value) as type\n"
		"\treturn Type(value)\n"
		"end\n"
		"func name(type value) as string\n"
		"\treturn value.name\n"
		"end\n"
		"func same(type left, type right) as bool\n"
		"\treturn left == right\n"
		"end\n"
		"func dynamic(string type_name, type base_type) as DynamicTypeDesc\n"
		"\treturn DynamicTypeDesc(type_name, base_type)\n"
		"end\n"
		"func is_dynamic(DynamicTypeDesc desc) as bool\n"
		"\treturn true\n"
		"end\n"
		"func dynamic_name(DynamicTypeDesc desc) as string\n"
		"\treturn desc.name\n"
		"end\n"
		"func dynamic_base(DynamicTypeDesc desc) as type\n"
		"\treturn desc.base\n"
		"end\n"
		"func add_field(DynamicTypeDesc desc, string field_name, type field_type) as DynamicTypeDesc\n"
		"\tif field_type == object then\n"
		"\t\tdesc.set(\"__field__:\" + field_name, \"object\")\n"
		"\telse\n"
		"\t\tdesc.set(\"__field__:\" + field_name, field_type.name)\n"
		"\tend\n"
		"\treturn desc\n"
		"end\n"
		"func add_method(DynamicTypeDesc desc, string method_name) as DynamicTypeDesc\n"
		"\tdesc.set(\"__method__:\" + method_name, true)\n"
		"\treturn desc\n"
		"end\n"
		"func bind_method(DynamicTypeDesc desc, string method_name, var method_value) as DynamicTypeDesc\n"
		"\tif has_declared_method(desc, method_name) then\n"
		"\t\tdesc[\"__method_fn__:\" + method_name] = method_value\n"
		"\tend\n"
		"\treturn desc\n"
		"end\n"
		"func method_impl(DynamicTypeDesc desc, string method_name, var default_value) as var\n"
		"\tif has_declared_method(desc, method_name) and desc.exists(\"__method_fn__:\" + method_name) then\n"
		"\t\treturn desc[\"__method_fn__:\" + method_name]\n"
		"\tend\n"
		"\treturn default_value\n"
		"end\n"
		"func has_bound_method(DynamicTypeDesc desc, string method_name) as bool\n"
		"\treturn has_declared_method(desc, method_name) and desc.exists(\"__method_fn__:\" + method_name)\n"
		"end\n"
		"func bound_method_names(DynamicTypeDesc desc) as array<string>\n"
		"\tvar array<string> names = []\n"
		"\tfor key in desc.keys()\n"
		"\t\tif key.starts_with(\"__method_fn__:\")\n"
		"\t\t\tnames.append(key.slice(14, key.length - 14))\n"
		"\t\tend\n"
		"\tend\n"
		"\treturn names\n"
		"end\n"
		"func bound_method_count(DynamicTypeDesc desc) as int\n"
		"\treturn bound_method_names(desc).length\n"
		"end\n"
		"func bound_method_name_at(DynamicTypeDesc desc, int index, string default_value) as string\n"
		"\tauto names = bound_method_names(desc)\n"
		"\tif index < 0 or index >= names.length\n"
		"\t\treturn default_value\n"
		"\tend\n"
		"\treturn names[index]\n"
		"end\n"
		"func has_declared_field(DynamicTypeDesc desc, string field_name) as bool\n"
		"\treturn desc.exists(\"__field__:\" + field_name)\n"
		"end\n"
		"func has_declared_method(DynamicTypeDesc desc, string method_name) as bool\n"
		"\treturn desc.exists(\"__method__:\" + method_name)\n"
		"end\n"
		"func field_names(DynamicTypeDesc desc) as array<string>\n"
		"\tvar array<string> names = []\n"
		"\tfor key in desc.keys()\n"
		"\t\tif key.starts_with(\"__field__:\")\n"
		"\t\t\tnames.append(key.slice(10, key.length - 10))\n"
		"\t\tend\n"
		"\tend\n"
		"\treturn names\n"
		"end\n"
		"func method_names(DynamicTypeDesc desc) as array<string>\n"
		"\tvar array<string> names = []\n"
		"\tfor key in desc.keys()\n"
		"\t\tif key.starts_with(\"__method__:\")\n"
		"\t\t\tnames.append(key.slice(11, key.length - 11))\n"
		"\t\tend\n"
		"\tend\n"
		"\treturn names\n"
		"end\n"
		"func field_count(DynamicTypeDesc desc) as int\n"
		"\treturn field_names(desc).length\n"
		"end\n"
		"func method_count(DynamicTypeDesc desc) as int\n"
		"\treturn method_names(desc).length\n"
		"end\n"
		"func field_name_at(DynamicTypeDesc desc, int index, string default_value) as string\n"
		"\tauto names = field_names(desc)\n"
		"\tif index < 0 or index >= names.length\n"
		"\t\treturn default_value\n"
		"\tend\n"
		"\treturn names[index]\n"
		"end\n"
		"func field_type_name(DynamicTypeDesc desc, string field_name, string default_value) as string\n"
		"\tif has_declared_field(desc, field_name) then\n"
		"\t\treturn string(desc[\"__field__:\" + field_name])\n"
		"\tend\n"
		"\treturn default_value\n"
		"end\n"
		"func field_type_name_at(DynamicTypeDesc desc, int index, string default_value) as string\n"
		"\tauto field_name = field_name_at(desc, index, \"\")\n"
		"\tif field_name == \"\"\n"
		"\t\treturn default_value\n"
		"\tend\n"
		"\treturn field_type_name(desc, field_name, default_value)\n"
		"end\n"
		"func method_name_at(DynamicTypeDesc desc, int index, string default_value) as string\n"
		"\tauto names = method_names(desc)\n"
		"\tif index < 0 or index >= names.length\n"
		"\t\treturn default_value\n"
		"\tend\n"
		"\treturn names[index]\n"
		"end\n"
		"func new_instance(DynamicTypeDesc desc) as DynamicObject\n"
		"\treturn DynamicObject(desc)\n"
		"end\n"
		"func is_instance(var value) as bool\n"
		"\treturn Type(value) == DynamicObject\n"
		"end\n"
		"func instance_name(DynamicObject value) as string\n"
		"\treturn value.desc.name\n"
		"end\n"
		"func instance_base(DynamicObject value) as type\n"
		"\treturn value.desc.base\n"
		"end\n"
		"func instance_desc(DynamicObject value) as DynamicTypeDesc\n"
		"\treturn value.desc\n"
		"end\n"
		"func instance_has_field(DynamicObject value, string field_name) as bool\n"
		"\treturn has_declared_field(value.desc, field_name)\n"
		"end\n"
		"func instance_field_names(DynamicObject value) as array<string>\n"
		"\treturn field_names(value.desc)\n"
		"end\n"
		"func instance_field_count(DynamicObject value) as int\n"
		"\treturn field_count(value.desc)\n"
		"end\n"
		"func instance_has_method(DynamicObject value, string method_name) as bool\n"
		"\treturn has_declared_method(value.desc, method_name)\n"
		"end\n"
		"func instance_method_names(DynamicObject value) as array<string>\n"
		"\treturn method_names(value.desc)\n"
		"end\n"
		"func instance_method_count(DynamicObject value) as int\n"
		"\treturn method_count(value.desc)\n"
		"end\n"
		"func instance_method_bound(DynamicObject value, string method_name) as bool\n"
		"\treturn has_bound_method(value.desc, method_name)\n"
		"end\n"
		"func instance_bound_method_names(DynamicObject value) as array<string>\n"
		"\treturn bound_method_names(value.desc)\n"
		"end\n"
		"func instance_bound_method_count(DynamicObject value) as int\n"
		"\treturn bound_method_count(value.desc)\n"
		"end\n"
		"func instance_bound_method_name_at(DynamicObject value, int index, string default_value) as string\n"
		"\treturn bound_method_name_at(value.desc, index, default_value)\n"
		"end\n"
		"func instance_method(DynamicObject value, string method_name, var default_value) as var\n"
		"\treturn method_impl(value.desc, method_name, default_value)\n"
		"end\n"
		"func instance_field_name_at(DynamicObject value, int index, string default_value) as string\n"
		"\treturn field_name_at(value.desc, index, default_value)\n"
		"end\n"
		"func instance_field_type_name(DynamicObject value, string field_name, string default_value) as string\n"
		"\treturn field_type_name(value.desc, field_name, default_value)\n"
		"end\n"
		"func instance_field_type_name_at(DynamicObject value, int index, string default_value) as string\n"
		"\treturn field_type_name_at(value.desc, index, default_value)\n"
		"end\n"
		"func instance_method_name_at(DynamicObject value, int index, string default_value) as string\n"
		"\treturn method_name_at(value.desc, index, default_value)\n"
		"end\n"
		"func set_field(DynamicObject value, string field_name, var field_value) as DynamicObject\n"
		"\tif has_declared_field(value.desc, field_name) then\n"
		"\t\tvalue[field_name] = field_value\n"
		"\tend\n"
		"\treturn value\n"
		"end\n"
		"func get_field(DynamicObject value, string field_name, var default_value) as var\n"
		"\tif has_declared_field(value.desc, field_name) then\n"
		"\t\treturn value[field_name]\n"
		"\tend\n"
		"\treturn default_value\n"
		"end\n"
		"\n"
		"export of\n"
		"export name\n"
		"export same\n"
		"export dynamic\n"
		"export is_dynamic\n"
		"export dynamic_name\n"
		"export dynamic_base\n"
		"export add_field\n"
		"export add_method\n"
		"export bind_method\n"
		"export has_bound_method\n"
		"export bound_method_names\n"
		"export bound_method_count\n"
		"export bound_method_name_at\n"
		"export has_declared_field\n"
		"export has_declared_method\n"
		"export method_impl\n"
		"export field_names\n"
		"export method_names\n"
		"export field_count\n"
		"export method_count\n"
		"export field_name_at\n"
		"export field_type_name\n"
		"export field_type_name_at\n"
		"export method_name_at\n"
		"export new_instance\n"
		"export is_instance\n"
		"export instance_name\n"
		"export instance_base\n"
		"export instance_desc\n"
		"export instance_has_field\n"
		"export instance_has_method\n"
		"export instance_method_names\n"
		"export instance_method_count\n"
		"export instance_method_bound\n"
		"export instance_bound_method_names\n"
		"export instance_bound_method_count\n"
		"export instance_bound_method_name_at\n"
		"export instance_method\n"
		"export instance_field_names\n"
		"export instance_field_count\n"
		"export instance_field_name_at\n"
		"export instance_field_type_name\n"
		"export instance_field_type_name_at\n"
		"export instance_method_name_at\n"
		"export set_field\n"
		"export get_field\n";
}
