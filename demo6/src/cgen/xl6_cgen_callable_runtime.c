    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    xrtcallable* callable = xrtValueGetCallable(value);\n", out);
    xl6OutputPuts("    XL6_Function fn;\n", out);
    xl6OutputPuts("    if ( callable == 0 || xl6XrtCallableSignatureId(callable) != signature ) {\n", out);
    xl6OutputPuts("        if ( release && value != 0 ) {\n", out);
    xl6OutputPuts("            xl6_temp_managed_release((void*)value, (XL6_TempManagedDrop)xrtValueRelease);\n", out);
    xl6OutputPuts("        }\n", out);
    xl6OutputPuts("        xl6_error_raise(\"TypeError\", \"function signature cast failed\", \"\", 0, 0);\n", out);
    xl6OutputPuts("        memset(&fn, 0, sizeof(fn));\n", out);
    xl6OutputPuts("        return fn;\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    fn = xl6_function_from_callable(callable);\n", out);
    xl6OutputPuts("    if ( release && value != 0 ) {\n", out);
    xl6OutputPuts("        xl6_temp_managed_release((void*)value, (XL6_TempManagedDrop)xrtValueRelease);\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    return fn;\n", out);
    xl6OutputPuts("}\n\n", out);

    xl6OutputPuts("static XL6_Function xl6_function_from_xvalue_release(xvalue* value)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    xrtcallable* callable = xrtValueGetCallable(value);\n", out);
    xl6OutputPuts("    unsigned long long signature = callable != 0 ? xl6XrtCallableSignatureId(callable) : 0;\n", out);
    xl6OutputPuts("    return xl6_function_from_xvalue_checked(value, signature, true);\n", out);
    xl6OutputPuts("}\n\n", out);

    xl6OutputPuts("static void xl6_xvalue_drop(xvalue* value)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    if ( value != 0 ) {\n", out);
