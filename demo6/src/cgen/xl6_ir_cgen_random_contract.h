#ifndef XL6_IR_CGEN_RANDOM_CONTRACT_H
#define XL6_IR_CGEN_RANDOM_CONTRACT_H

/* Exact native adapter identities.  The same bits select emitted C and XRT
 * module roots; no source-name prefix or generated-C scan is involved. */
enum {
    XL6_CGEN_RNG_CREATE = 1u << 0,
    XL6_CGEN_RNG_CREATE_DEFAULT = 1u << 1,
    XL6_CGEN_RNG_DESTROY = 1u << 2,
    XL6_CGEN_RNG_SEED = 1u << 3,
    XL6_CGEN_RNG_U32 = 1u << 4,
    XL6_CGEN_RNG_U64 = 1u << 5,
    XL6_CGEN_RNG_BELOW = 1u << 6,
    XL6_CGEN_RNG_RANGE = 1u << 7,
    XL6_CGEN_RNG_RANGE_CLOSED = 1u << 8,
    XL6_CGEN_RNG_REAL = 1u << 9,
    XL6_CGEN_RNG_BYTES = 1u << 10,
    XL6_CGEN_RNG_STRING = 1u << 11,
    XL6_CGEN_RNG_FILL_BUFFER = 1u << 12,
    XL6_CGEN_RNG_SHUFFLE_ARRAY = 1u << 13,
    XL6_CGEN_RNG_SHUFFLE_BUFFER = 1u << 14,
    XL6_CGEN_RAND_SEED = 1u << 15,
    XL6_CGEN_RAND_U32 = 1u << 16,
    XL6_CGEN_RAND_U64 = 1u << 17,
    XL6_CGEN_RAND_BELOW = 1u << 18,
    XL6_CGEN_RAND_RANGE = 1u << 19,
    XL6_CGEN_RAND_RANGE_CLOSED = 1u << 20,
    XL6_CGEN_RAND_REAL = 1u << 21,
    XL6_CGEN_RAND_BYTES = 1u << 22,
    XL6_CGEN_RAND_STRING = 1u << 23,
    XL6_CGEN_RAND_FILL_BUFFER = 1u << 24,
    XL6_CGEN_RAND_SHUFFLE_ARRAY = 1u << 25,
    XL6_CGEN_RAND_SHUFFLE_BUFFER = 1u << 26,
    XL6_CGEN_SECURE_BYTES = 1u << 27,
    XL6_CGEN_SECURE_FILL_BUFFER = 1u << 28,
    XL6_CGEN_SECURE_HEX = 1u << 29,
    XL6_CGEN_SECURE_STRING = 1u << 30
};

#define XL6_CGEN_RNG_EXPLICIT_MASK ((1u << 15) - 1u)
#define XL6_CGEN_RNG_DEFAULT_MASK (((1u << 27) - 1u) & ~XL6_CGEN_RNG_EXPLICIT_MASK)
#define XL6_CGEN_RNG_TEXT_MASK (XL6_CGEN_RNG_STRING | XL6_CGEN_RAND_STRING)
#define XL6_CGEN_RNG_SECURE_MASK (XL6_CGEN_SECURE_BYTES | XL6_CGEN_SECURE_FILL_BUFFER | XL6_CGEN_SECURE_HEX)
#define XL6_CGEN_RNG_BYTES_MASK (XL6_CGEN_RNG_BYTES | XL6_CGEN_RAND_BYTES | XL6_CGEN_SECURE_BYTES)
#define XL6_CGEN_RNG_ARRAY_MASK (XL6_CGEN_RNG_SHUFFLE_ARRAY | XL6_CGEN_RAND_SHUFFLE_ARRAY)
#define XL6_CGEN_RNG_BUFFER_MASK (XL6_CGEN_RNG_FILL_BUFFER | XL6_CGEN_RNG_SHUFFLE_BUFFER | XL6_CGEN_RAND_FILL_BUFFER | XL6_CGEN_RAND_SHUFFLE_BUFFER | XL6_CGEN_SECURE_FILL_BUFFER)

#endif
