static void xl6CgenEmitJsonRuntime(XL6_Output* out)
{
    if ( out == NULL ) {
        return;
    }

    xl6OutputPuts("#ifndef XL6_JSON_RUNTIME\n", out);
    xl6OutputPuts("#define XL6_JSON_RUNTIME\n", out);
    xl6OutputPuts("typedef enum {\n", out);
    xl6OutputPuts("    XRT_JSON_EVENT_NULL = 0, XRT_JSON_EVENT_BOOL, XRT_JSON_EVENT_INT,\n", out);
    xl6OutputPuts("    XRT_JSON_EVENT_UINT, XRT_JSON_EVENT_FLOAT, XRT_JSON_EVENT_STRING,\n", out);
    xl6OutputPuts("    XRT_JSON_EVENT_ARRAY_BEGIN, XRT_JSON_EVENT_ARRAY_END,\n", out);
    xl6OutputPuts("    XRT_JSON_EVENT_OBJECT_BEGIN, XRT_JSON_EVENT_OBJECT_END\n", out);
    xl6OutputPuts("} xrt_json_event_type;\n", out);
    xl6OutputPuts("typedef struct {\n", out);
    xl6OutputPuts("    xrt_json_event_type type; unsigned int depth; const char* key; size_t key_size;\n", out);
    xl6OutputPuts("    const char* text; size_t text_size; bool bool_value; long long int_value;\n", out);
    xl6OutputPuts("    unsigned long long uint_value; double float_value;\n", out);
    xl6OutputPuts("} xrt_json_event;\n", out);
    xl6OutputPuts("typedef bool (*xrt_json_event_proc)(const xrt_json_event*, void*);\n", out);
    xl6OutputPuts("typedef struct { bool pretty; bool ignore_unsupported_encode; bool ignore_unsupported_decode; } xson_options;\n", out);
    xl6OutputPuts("typedef struct xrt_json_writer_struct* xjsonwriter;\n", out);
    xl6OutputPuts("int xrtJsonVisit(const char* text, size_t size, xrt_json_event_proc proc, void* userdata);\n", out);
    xl6OutputPuts("xvalue xrtParseXSONWithOptions(const char* text, size_t size, const xson_options* options);\n", out);
    xl6OutputPuts("bool xrtXsonValidWithOptions(const char* text, size_t size, const xson_options* options);\n", out);
    xl6OutputPuts("xvalue xrtParseXSONFileWithOptions(const char* file, const xson_options* options);\n", out);
    xl6OutputPuts("char* xrtStringifyXSONWithOptions(xvalue value, const xson_options* options, size_t* size);\n", out);
    xl6OutputPuts("int xrtStringifyXSONFileWithOptions(const char* file, xvalue value, const xson_options* options);\n", out);
    xl6OutputPuts("xjsonwriter xrtJsonWriterCreate(bool pretty);\n", out);
    xl6OutputPuts("void xrtJsonWriterDestroy(xjsonwriter writer);\n", out);
    xl6OutputPuts("bool xrtJsonWriterBeginObject(xjsonwriter writer);\n", out);
    xl6OutputPuts("bool xrtJsonWriterBeginObjectKey(xjsonwriter writer, const char* key);\n", out);
    xl6OutputPuts("bool xrtJsonWriterEndObject(xjsonwriter writer);\n", out);
    xl6OutputPuts("bool xrtJsonWriterBeginArray(xjsonwriter writer);\n", out);
    xl6OutputPuts("bool xrtJsonWriterBeginArrayKey(xjsonwriter writer, const char* key);\n", out);
    xl6OutputPuts("bool xrtJsonWriterEndArray(xjsonwriter writer);\n", out);
    xl6OutputPuts("bool xrtJsonWriterNull(xjsonwriter writer);\n", out);
    xl6OutputPuts("bool xrtJsonWriterNullKey(xjsonwriter writer, const char* key);\n", out);
    xl6OutputPuts("bool xrtJsonWriterBool(xjsonwriter writer, bool value);\n", out);
    xl6OutputPuts("bool xrtJsonWriterBoolKey(xjsonwriter writer, const char* key, bool value);\n", out);
    xl6OutputPuts("bool xrtJsonWriterInt(xjsonwriter writer, long long value);\n", out);
    xl6OutputPuts("bool xrtJsonWriterIntKey(xjsonwriter writer, const char* key, long long value);\n", out);
    xl6OutputPuts("bool xrtJsonWriterFloat(xjsonwriter writer, double value);\n", out);
    xl6OutputPuts("bool xrtJsonWriterFloatKey(xjsonwriter writer, const char* key, double value);\n", out);
    xl6OutputPuts("bool xrtJsonWriterString(xjsonwriter writer, const char* value);\n", out);
    xl6OutputPuts("bool xrtJsonWriterStringKey(xjsonwriter writer, const char* key, const char* value);\n", out);
    xl6OutputPuts("bool xrtJsonWriterValue(xjsonwriter writer, xvalue value);\n", out);
    xl6OutputPuts("bool xrtJsonWriterValueKey(xjsonwriter writer, const char* key, xvalue value);\n", out);
    xl6OutputPuts("char* xrtJsonWriterFinish(xjsonwriter writer, size_t* size);\n", out);
    xl6OutputPuts("void* xrtMalloc(size_t size);\n", out);
    xl6OutputPuts("void xrtFree(void* value);\n", out);
    xl6OutputPuts("char* xrtCopyStr(const char* text, size_t size);\n", out);
    xl6OutputPuts("int xrtU64ToStr(unsigned long long value, char* buffer);\n", out);
    xl6OutputPuts("xvalue xvoCreateNull(void);\n", out);
    xl6OutputPuts("xvalue xvoCreateBool(bool value);\n", out);
    xl6OutputPuts("xvalue xvoCreateInt(long long value);\n", out);
    xl6OutputPuts("xvalue xvoCreateFloat(double value);\n", out);
    xl6OutputPuts("xvalue xvoCreateText(void* text, unsigned int size, bool colloc);\n", out);
    xl6OutputPuts("xvalue xvoCreateTable(void);\n", out);
    xl6OutputPuts("bool xvoTableSetValue(xvalue table, const void* key, unsigned int keySize, xvalue value, bool colloc);\n", out);
    xl6OutputPuts("bool xvoGetBool(xvalue value);\n", out);
    xl6OutputPuts("void xvoUnref(xvalue value);\n", out);
    xl6OutputPuts("static xvalue xl6_function_call_var(XL6_Function fn, int argc, ...);\n\n", out);

    xl6OutputPuts("typedef struct { XL6_Function visitor; } XL6_Json_Visit_Context;\n\n", out);

    xl6OutputPuts("static bool xl6_json_event_set(xvalue event, const char* key, xvalue value)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    if ( event == 0 || value == 0 ) { if ( value != 0 ) { xvoUnref(value); } return false; }\n", out);
    xl6OutputPuts("    if ( !xvoTableSetValue(event, key, 0u, value, true) ) { xvoUnref(value); return false; }\n", out);
    xl6OutputPuts("    return true;\n", out);
    xl6OutputPuts("}\n\n", out);

    xl6OutputPuts("static xvalue xl6_json_event_text(const char* text, size_t size, bool copy)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    char* owned; xvalue value;\n", out);
    xl6OutputPuts("    if ( text == 0 || size > 0xffffffffu ) { return xvoCreateNull(); }\n", out);
    xl6OutputPuts("    if ( !copy ) { return xvoCreateText((void*)text, (unsigned int)size, false); }\n", out);
    xl6OutputPuts("    owned = xrtCopyStr(text, size);\n", out);
    xl6OutputPuts("    if ( owned == 0 ) { return 0; }\n", out);
    xl6OutputPuts("    value = xvoCreateText(owned, (unsigned int)size, true);\n", out);
    xl6OutputPuts("    if ( value == 0 ) { xrtFree(owned); }\n", out);
    xl6OutputPuts("    return value;\n", out);
    xl6OutputPuts("}\n\n", out);

    xl6OutputPuts("static const char* xl6_json_event_type_name(xrt_json_event_type type)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    static const char* names[] = { \"null\", \"bool\", \"int\", \"uint\", \"float\", \"string\",\n", out);
    xl6OutputPuts("        \"arrayBegin\", \"arrayEnd\", \"objectBegin\", \"objectEnd\" };\n", out);
    xl6OutputPuts("    return (unsigned int)type < 10u ? names[(unsigned int)type] : \"unknown\";\n", out);
    xl6OutputPuts("}\n\n", out);

    xl6OutputPuts("static bool xl6_json_visit_proc(const xrt_json_event* source, void* userdata)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    XL6_Json_Visit_Context* context = (XL6_Json_Visit_Context*)userdata;\n", out);
    xl6OutputPuts("    xvalue event; xvalue value; xvalue result; bool keepGoing; char uintText[32]; int uintSize;\n", out);
    xl6OutputPuts("    if ( source == 0 || context == 0 ) { return false; }\n", out);
    xl6OutputPuts("    event = xvoCreateTable();\n", out);
    xl6OutputPuts("    if ( event == 0 ) { return false; }\n", out);
    xl6OutputPuts("    if ( !xl6_json_event_set(event, \"type\", xl6_json_event_text(xl6_json_event_type_name(source->type), 0u, false)) ||\n", out);
    xl6OutputPuts("         !xl6_json_event_set(event, \"depth\", xvoCreateInt((long long)source->depth)) ) { xvoUnref(event); return false; }\n", out);
    xl6OutputPuts("    if ( source->key != 0 ) { value = xl6_json_event_text(source->key, source->key_size, true); }\n", out);
    xl6OutputPuts("    else { value = xvoCreateNull(); }\n", out);
    xl6OutputPuts("    if ( !xl6_json_event_set(event, \"key\", value) ) { xvoUnref(event); return false; }\n", out);
    xl6OutputPuts("    switch ( source->type ) {\n", out);
    xl6OutputPuts("    case XRT_JSON_EVENT_BOOL: value = xvoCreateBool(source->bool_value); break;\n", out);
    xl6OutputPuts("    case XRT_JSON_EVENT_INT: value = xvoCreateInt(source->int_value); break;\n", out);
    xl6OutputPuts("    case XRT_JSON_EVENT_UINT:\n", out);
    xl6OutputPuts("        if ( source->uint_value <= 0x7fffffffffffffffULL ) { value = xvoCreateInt((long long)source->uint_value); }\n", out);
    xl6OutputPuts("        else { uintSize = xrtU64ToStr(source->uint_value, uintText); value = xl6_json_event_text(uintText, (size_t)uintSize, true); }\n", out);
    xl6OutputPuts("        break;\n", out);
    xl6OutputPuts("    case XRT_JSON_EVENT_FLOAT: value = xvoCreateFloat(source->float_value); break;\n", out);
    xl6OutputPuts("    case XRT_JSON_EVENT_STRING: value = xl6_json_event_text(source->text, source->text_size, true); break;\n", out);
    xl6OutputPuts("    default: value = xvoCreateNull(); break;\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    if ( !xl6_json_event_set(event, \"value\", value) ) { xvoUnref(event); return false; }\n", out);
    xl6OutputPuts("    result = xl6_function_call_var(context->visitor, 1, event);\n", out);
    xl6OutputPuts("    keepGoing = result != 0 && xvoGetBool(result);\n", out);
    xl6OutputPuts("    if ( result != 0 ) { xvoUnref(result); }\n", out);
    xl6OutputPuts("    return keepGoing;\n", out);
    xl6OutputPuts("}\n\n", out);

    xl6OutputPuts("int xl6_xrt_json_visit(const char* text, XL6_Function visitor)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    XL6_Json_Visit_Context context;\n", out);
    xl6OutputPuts("    if ( text == 0 || (visitor.invoke_var == 0 && visitor.invoke_xcall == 0) ) { return -1; }\n", out);
    xl6OutputPuts("    context.visitor = visitor;\n", out);
    xl6OutputPuts("    return xrtJsonVisit(text, 0u, xl6_json_visit_proc, &context);\n", out);
    xl6OutputPuts("}\n\n", out);

    xl6OutputPuts("static xson_options xl6_xson_options(bool pretty, bool ignoreEncode, bool ignoreDecode)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    xson_options options; options.pretty = pretty;\n", out);
    xl6OutputPuts("    options.ignore_unsupported_encode = ignoreEncode;\n", out);
    xl6OutputPuts("    options.ignore_unsupported_decode = ignoreDecode; return options;\n", out);
    xl6OutputPuts("}\n\n", out);

    xl6OutputPuts("xvalue xl6_xrt_xson_parse_options(const char* text, bool pretty, bool ignoreEncode, bool ignoreDecode)\n", out);
    xl6OutputPuts("{ xson_options options = xl6_xson_options(pretty, ignoreEncode, ignoreDecode); return xrtParseXSONWithOptions(text, 0u, &options); }\n", out);
    xl6OutputPuts("bool xl6_xrt_xson_valid_options(const char* text, bool pretty, bool ignoreEncode, bool ignoreDecode)\n", out);
    xl6OutputPuts("{ xson_options options = xl6_xson_options(pretty, ignoreEncode, ignoreDecode); return xrtXsonValidWithOptions(text, 0u, &options); }\n", out);
    xl6OutputPuts("xvalue xl6_xrt_xson_read_options(const char* file, bool pretty, bool ignoreEncode, bool ignoreDecode)\n", out);
    xl6OutputPuts("{ xson_options options = xl6_xson_options(pretty, ignoreEncode, ignoreDecode); return xrtParseXSONFileWithOptions(file, &options); }\n", out);
    xl6OutputPuts("void* xl6_xrt_xson_stringify_options(xvalue value, bool pretty, bool ignoreEncode, bool ignoreDecode)\n", out);
    xl6OutputPuts("{ xson_options options = xl6_xson_options(pretty, ignoreEncode, ignoreDecode); return xrtStringifyXSONWithOptions(value, &options, 0); }\n", out);
    xl6OutputPuts("bool xl6_xrt_xson_write_options(const char* file, xvalue value, bool pretty, bool ignoreEncode, bool ignoreDecode)\n", out);
    xl6OutputPuts("{ xson_options options = xl6_xson_options(pretty, ignoreEncode, ignoreDecode); return xrtStringifyXSONFileWithOptions(file, value, &options) != 0; }\n", out);

    xl6OutputPuts("void* xl6_xrt_json_writer_create_default(void) { return xrtJsonWriterCreate(false); }\n", out);
    xl6OutputPuts("void* xl6_xrt_json_writer_create_pretty(int pretty) { return xrtJsonWriterCreate(pretty != 0); }\n", out);
    xl6OutputPuts("long long xl6_xrt_json_writer_destroy(void* writer) { xrtJsonWriterDestroy((xjsonwriter)writer); return 0; }\n", out);
    xl6OutputPuts("int xl6_xrt_json_writer_begin_object(void* writer) { return xrtJsonWriterBeginObject((xjsonwriter)writer); }\n", out);
    xl6OutputPuts("int xl6_xrt_json_writer_begin_object_key(void* writer, const char* key) { return xrtJsonWriterBeginObjectKey((xjsonwriter)writer, key); }\n", out);
    xl6OutputPuts("int xl6_xrt_json_writer_end_object(void* writer) { return xrtJsonWriterEndObject((xjsonwriter)writer); }\n", out);
    xl6OutputPuts("int xl6_xrt_json_writer_begin_array(void* writer) { return xrtJsonWriterBeginArray((xjsonwriter)writer); }\n", out);
    xl6OutputPuts("int xl6_xrt_json_writer_begin_array_key(void* writer, const char* key) { return xrtJsonWriterBeginArrayKey((xjsonwriter)writer, key); }\n", out);
    xl6OutputPuts("int xl6_xrt_json_writer_end_array(void* writer) { return xrtJsonWriterEndArray((xjsonwriter)writer); }\n", out);
    xl6OutputPuts("int xl6_xrt_json_writer_null(void* writer) { return xrtJsonWriterNull((xjsonwriter)writer); }\n", out);
    xl6OutputPuts("int xl6_xrt_json_writer_null_key(void* writer, const char* key) { return xrtJsonWriterNullKey((xjsonwriter)writer, key); }\n", out);
    xl6OutputPuts("int xl6_xrt_json_writer_bool(void* writer, int value) { return xrtJsonWriterBool((xjsonwriter)writer, value != 0); }\n", out);
    xl6OutputPuts("int xl6_xrt_json_writer_bool_key(void* writer, const char* key, int value) { return xrtJsonWriterBoolKey((xjsonwriter)writer, key, value != 0); }\n", out);
    xl6OutputPuts("int xl6_xrt_json_writer_int(void* writer, long long value) { return xrtJsonWriterInt((xjsonwriter)writer, value); }\n", out);
    xl6OutputPuts("int xl6_xrt_json_writer_int_key(void* writer, const char* key, long long value) { return xrtJsonWriterIntKey((xjsonwriter)writer, key, value); }\n", out);
    xl6OutputPuts("int xl6_xrt_json_writer_float(void* writer, double value) { return xrtJsonWriterFloat((xjsonwriter)writer, value); }\n", out);
    xl6OutputPuts("int xl6_xrt_json_writer_float_key(void* writer, const char* key, double value) { return xrtJsonWriterFloatKey((xjsonwriter)writer, key, value); }\n", out);
    xl6OutputPuts("int xl6_xrt_json_writer_string(void* writer, const char* value) { return xrtJsonWriterString((xjsonwriter)writer, value); }\n", out);
    xl6OutputPuts("int xl6_xrt_json_writer_string_key(void* writer, const char* key, const char* value) { return xrtJsonWriterStringKey((xjsonwriter)writer, key, value); }\n", out);
    xl6OutputPuts("int xl6_xrt_json_writer_value(void* writer, xvalue value) { return xrtJsonWriterValue((xjsonwriter)writer, value); }\n", out);
    xl6OutputPuts("int xl6_xrt_json_writer_value_key(void* writer, const char* key, xvalue value) { return xrtJsonWriterValueKey((xjsonwriter)writer, key, value); }\n", out);
    xl6OutputPuts("void* xl6_xrt_json_writer_finish(void* writer) { return xrtJsonWriterFinish((xjsonwriter)writer, 0); }\n", out);
    xl6OutputPuts("#endif\n\n", out);
}
