/* Stable owned event records and exact XL6_Function callbacks, selected by XLIR. */
static void xl6IrCgenEmitFsWalkRuntime(XL6_Output* out, const XL6_IrCgenNeeds* needs)
{
    if (xl6IrCgenFsSelected(needs, XL6_IR_RUNTIME_BRIDGE_FS_WALK_VISIT) || xl6IrCgenFsSelected(needs, XL6_IR_RUNTIME_BRIDGE_FS_DIR_ENTRIES)) xl6OutputPuts(
        "static inline bool xlir_fs_walk_put(xvalue* object, const char* key, xvalue* value)\n"
        "{ if (value == NULL) { return false; }\n"
        "  return xrtValueObjectSetNew(object,(xstrview){key,strlen(key)},value); }\n"
        "static inline xvalue* xlir_fs_walk_text(xstrview text)\n"
        "{ return xrtUtf8Valid(text,NULL) ? xrtValueString(text) : xrtValueRetain(xrtValueNull()); }\n"
        "static xvalue* xlir_fs_walk_entry(const xwalkentry* entry)\n"
        "{ xvalue* object = xrtValueObject(); xstrview path = {entry->Path,strlen(entry->Path)};\n"
        "  if (object == NULL) { return NULL; }\n"
        "  if (!xlir_fs_walk_put(object,\"path\",xlir_fs_walk_text(path)) ||\n"
        "      !xlir_fs_walk_put(object,\"parent\",xlir_fs_walk_text(entry->Parent)) ||\n"
        "      !xlir_fs_walk_put(object,\"name\",xlir_fs_walk_text(entry->Name)) ||\n"
        "      !xlir_fs_walk_put(object,\"pathBytes\",xrtValueBytes((xbytesview){(const unsigned char*)path.Data,path.Size})) ||\n"
        "      !xlir_fs_walk_put(object,\"parentBytes\",xrtValueBytes((xbytesview){(const unsigned char*)entry->Parent.Data,entry->Parent.Size})) ||\n"
        "      !xlir_fs_walk_put(object,\"nameBytes\",xrtValueBytes((xbytesview){(const unsigned char*)entry->Name.Data,entry->Name.Size})) ||\n"
        "      !xlir_fs_walk_put(object,\"event\",xrtValueInt(entry->Event)) ||\n"
        "      !xlir_fs_walk_put(object,\"flags\",xrtValueInt(entry->Flags)) ||\n"
        "      !xlir_fs_walk_put(object,\"depth\",xrtValueUInt(entry->Depth)) ||\n"
        "      !xlir_fs_walk_put(object,\"validUtf8\",xrtValueBool(xrtUtf8Valid(path,NULL) &&\n"
        "          xrtUtf8Valid(entry->Parent,NULL) && xrtUtf8Valid(entry->Name,NULL))) ||\n"
        "      !xlir_fs_walk_put(object,\"type\",xrtValueInt(entry->Info.Type)) ||\n"
        "      !xlir_fs_walk_put(object,\"available\",xrtValueInt(entry->Info.Available)) ||\n"
        "      !xlir_fs_walk_put(object,\"mode\",xrtValueInt(entry->Info.Mode)) ||\n"
        "      !xlir_fs_walk_put(object,\"attributes\",xrtValueInt(entry->Info.Attributes)) ||\n"
        "      !xlir_fs_walk_put(object,\"size\",xrtValueUInt(entry->Info.Size)) ||\n"
        "      !xlir_fs_walk_put(object,\"device\",xrtValueUInt(entry->Info.Device)) ||\n"
        "      !xlir_fs_walk_put(object,\"identity\",xrtValueUInt(entry->Info.Identity)) ||\n"
        "      !xlir_fs_walk_put(object,\"linkCount\",xrtValueUInt(entry->Info.LinkCount)) ||\n"
        "      !xlir_fs_walk_put(object,\"accessed\",xrtValueInt(entry->Info.Accessed)) ||\n"
        "      !xlir_fs_walk_put(object,\"modified\",xrtValueInt(entry->Info.Modified)) ||\n"
        "      !xlir_fs_walk_put(object,\"created\",xrtValueInt(entry->Info.Created)) ||\n"
        "      !xlir_fs_walk_put(object,\"changed\",xrtValueInt(entry->Info.Changed))) { xrtValueRelease(object); return NULL; }\n"
        "  return object; }\n", out);
    if (xl6IrCgenFsSelected(needs, XL6_IR_RUNTIME_BRIDGE_FS_WALK_VISIT)) xl6OutputPuts(
        "typedef struct xlir_fs_walk_callbacks { XL6_Function visit, onError; xerror* failure; } xlir_fs_walk_callbacks;\n"
        "static bool xlir_fs_walk_call(xlir_fs_walk_callbacks* context, XL6_Function callback,\n"
        "    xvalue* event, int64_t* action, int64_t maximum)\n"
        "{ xvalue* result = NULL; xvalue* arguments[1] = {event}; bool ok = false;\n"
        "  xl6_foreign_error_scope invocation = {0}; xl6_foreign_error_result outcome = {false,NULL};\n"
        "  if (event != NULL && xl6ForeignCallBegin(&invocation)) {\n"
        "    result = callback.invoke_var(callback.env,1,arguments);\n"
        "    ok = result != NULL && xrtValueGetInt(result,action);\n"
        "    if (ok && (*action < 0 || *action > maximum)) { xrtSetErrorKind(XERR_RANGE); ok = false; }\n"
        "    if (!ok) { if (xrtGetError() == NULL) { xrtSetErrorKind(XERR_STATE); } xl6ErrorScopeCaptureFailure(&invocation); }\n"
        "    outcome = xl6ForeignCallEnd(&invocation); ok = ok && outcome.ok;\n"
        "    xrtSetErrorTake(outcome.error);\n"
        "  }\n"
        "  { xerror* error = xrtTakeError(); xrtValueRelease(result); xrtValueRelease(event);\n"
        "    xrtClearError(); xrtSetErrorTake(error); }\n"
        "  if (!ok) {\n"
        "    if (xrtGetError() == NULL) { xrtSetErrorKind(XERR_STATE); }\n"
        "    if (context->failure == NULL) { context->failure = xrtErrorRef(xrtGetError()); }\n"
        "  }\n"
        "  return ok; }\n"
        "static xwalkcontrol xlir_fs_walk_visit(const xwalkentry* entry, void* data)\n"
        "{ xlir_fs_walk_callbacks* context = (xlir_fs_walk_callbacks*)data; int64_t action = 0;\n"
        "  if (!xlir_fs_walk_call(context,context->visit,xlir_fs_walk_entry(entry),&action,3)) { return XWALK_ERROR; }\n"
        "  if (action == XWALK_ERROR) { xrtSetErrorKind(XERR_STATE); context->failure = xrtErrorRef(xrtGetError()); }\n"
        "  return (xwalkcontrol)action; }\n"
        "static xwalkerroraction xlir_fs_walk_error(const char* path, const xerror* error, void* data)\n"
        "{ xlir_fs_walk_callbacks* context = (xlir_fs_walk_callbacks*)data; int64_t action = 0;\n"
        "  xvalue* object = xrtValueObject(); xstrview pathText = {path,strlen(path)};\n"
        "  const char* domain = xrtErrorDomain(error); const char* operation = xrtErrorOperation(error);\n"
        "  const char* message = xrtErrorMessage(error);\n"
        "  if (object != NULL &&\n"
        "      (!xlir_fs_walk_put(object,\"path\",xlir_fs_walk_text(pathText)) ||\n"
        "       !xlir_fs_walk_put(object,\"pathBytes\",xrtValueBytes((xbytesview){(const unsigned char*)pathText.Data,pathText.Size})) ||\n"
        "       !xlir_fs_walk_put(object,\"kind\",xrtValueInt(xrtErrorKind(error))) ||\n"
        "       !xlir_fs_walk_put(object,\"code\",xrtValueInt(xrtErrorCode(error))) ||\n"
        "       !xlir_fs_walk_put(object,\"systemCode\",xrtValueInt(xrtErrorSystemCode(error))) ||\n"
        "       !xlir_fs_walk_put(object,\"domain\",xlir_fs_walk_text((xstrview){domain,domain != NULL ? strlen(domain) : 0})) ||\n"
        "       !xlir_fs_walk_put(object,\"operation\",xlir_fs_walk_text((xstrview){operation,operation != NULL ? strlen(operation) : 0})) ||\n"
        "       !xlir_fs_walk_put(object,\"message\",xlir_fs_walk_text((xstrview){message,message != NULL ? strlen(message) : 0})))) {\n"
        "    xrtValueRelease(object); object = NULL;\n"
        "  }\n"
        "  if (!xlir_fs_walk_call(context,context->onError,object,&action,2)) { return XWALK_ERROR_ABORT; }\n"
        "  return (xwalkerroraction)action; }\n"
        "void* xl6_xrt_fs_walk_visit(xlir_string path, XL6_Function visit, XL6_Function onError, int64_t flags, int64_t maxDepth)\n"
        "{ const char* name; xlir_fs_stats* stats; xwalkoptions options;\n"
        "  xlir_fs_walk_callbacks context = {visit,onError,NULL}; bool ok;\n"
        "  if (visit.invoke_var == NULL || onError.invoke_var == NULL) { xrtSetErrorKind(XERR_TYPE); return NULL; }\n"
        "  if (!xlir_fs_walk_options(flags,maxDepth,&options)) { return NULL; }\n"
        "  name = xlir_string_cstr(path); if (name == NULL) { return NULL; }\n"
        "  stats = xlir_fs_stats_alloc(); if (stats == NULL) { return NULL; }\n"
        "  options.OnError = xlir_fs_walk_error;\n"
        "  ok = xrtFileWalk(name,&options,xlir_fs_walk_visit,&context,&stats->value);\n"
        "  if (context.failure != NULL) { xrtClearError(); xrtSetErrorTake(context.failure); ok = false; }\n"
        "  if (!ok) { xrtFree(stats); return NULL; } return stats; }\n", out);
    if (xl6IrCgenFsSelected(needs, XL6_IR_RUNTIME_BRIDGE_FS_DIR_GLOB) || xl6IrCgenFsSelected(needs, XL6_IR_RUNTIME_BRIDGE_FS_DIR_ENTRIES)) {
        xl6OutputPuts(
        "typedef struct xlir_fs_walk_list { xvalue* result; xstrview pattern; size_t limit; bool leave, records; } xlir_fs_walk_list;\n"
        "static xwalkcontrol xlir_fs_walk_list_visit(const xwalkentry* entry, void* data)\n"
        "{ xlir_fs_walk_list* list = (xlir_fs_walk_list*)data; xvalue* value;\n"
        "  if (entry->Depth == 0 || (!list->leave && entry->Event == XWALK_LEAVE)) { return XWALK_CONTINUE; }\n"
        "  if (list->pattern.Size != 0 && !xrtStrGlob(entry->Name,list->pattern,0))\n"
        "    { return xrtGetError() != NULL ? XWALK_ERROR : XWALK_CONTINUE; }\n"
        "  if (xrtValueCount(list->result) >= list->limit) { xrtSetErrorKind(XERR_RANGE); return XWALK_ERROR; }\n"
        , out);
        if (xl6IrCgenFsSelected(needs, XL6_IR_RUNTIME_BRIDGE_FS_DIR_ENTRIES)) xl6OutputPuts(
            "  if (list->records) { value = xlir_fs_walk_entry(entry); }\n"
            "  else\n", out);
        xl6OutputPuts(
        "  {\n"
        "    xstrview path = {entry->Path,strlen(entry->Path)};\n"
        "    if (!xrtUtf8Valid(path,NULL)) { xrtSetErrorKind(XERR_VALUE); return XWALK_ERROR; }\n"
        "    value = xrtValueString(path);\n"
        "  }\n"
        "  if (value == NULL || !xrtValueArrayAppendNew(list->result,value)) { return XWALK_ERROR; }\n"
        "  return XWALK_CONTINUE; }\n"
        "static xvalue* xlir_fs_walk_list_read(xlir_string path, xlir_string pattern, bool recursive,\n"
        "    bool leave, int64_t maxEntries, bool records)\n"
        "{ const char* name; xfileinfo info; xwalkoptions options; xlir_fs_walk_list list = {0};\n"
        "  if (!xlir_fs_size(maxEntries,&list.limit)) { return NULL; }\n"
        "  name = xlir_string_cstr(path); if (name == NULL) { return NULL; }\n"
        "  if (!xrtPathStat(name,false,&info)) { return NULL; }\n"
        "  if (info.Type != XFILE_TYPE_DIRECTORY) { xrtSetErrorKind(XERR_TYPE); return NULL; }\n"
        "  xrtWalkOptionsInit(&options); options.MaxDepth = recursive ? XRT_NPOS : 1;\n"
        "  list.pattern = (xstrview){pattern.Data,pattern.Size}; list.leave = leave; list.records = records;\n"
        "  list.result = xrtValueArray(); if (list.result == NULL) { return NULL; }\n"
        "  if (!xrtFileWalk(name,&options,xlir_fs_walk_list_visit,&list,NULL)) {\n"
        "    xerror* error = xrtTakeError(); xrtValueRelease(list.result); xrtClearError(); xrtSetErrorTake(error); return NULL;\n"
        "  }\n"
        "  return list.result; }\n", out);
    }
    if (xl6IrCgenFsSelected(needs, XL6_IR_RUNTIME_BRIDGE_FS_DIR_GLOB)) xl6OutputPuts(
        "xvalue* xl6_xrt_fs_dir_glob(xlir_string path, xlir_string pattern, bool recursive, int64_t maxEntries)\n"
        "{ return xlir_fs_walk_list_read(path,pattern,recursive,false,maxEntries,false); }\n", out);
    if (xl6IrCgenFsSelected(needs, XL6_IR_RUNTIME_BRIDGE_FS_DIR_ENTRIES)) xl6OutputPuts(
        "xvalue* xl6_xrt_fs_dir_entries(xlir_string path, xlir_string pattern, bool recursive, bool leave, int64_t maxEntries)\n"
        "{ return xlir_fs_walk_list_read(path,pattern,recursive,leave,maxEntries,true); }\n", out);
}
