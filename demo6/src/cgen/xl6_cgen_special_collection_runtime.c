        "        case 2u: return xrtTypedMPSCQueueCapacity((xtypedmpscqueue*)value->Value);\n"
        "        default: return xrtTypedMPMCQueueCapacity((xtypedmpmcqueue*)value->Value);\n"
        "    }\n"
        "}\n\n"

        "static bool xl6_special_queue_closed_raw(xtqueue value)\n"
        "{\n"
        "    switch ( value->Kind ) {\n"
        "        case 1u: return xrtTypedSPSCQueueIsClosed((xtypedspscqueue*)value->Value);\n"
        "        case 2u: return xrtTypedMPSCQueueIsClosed((xtypedmpscqueue*)value->Value);\n"
        "        default: return xrtTypedMPMCQueueIsClosed((xtypedmpmcqueue*)value->Value);\n"
        "    }\n"
        "}\n\n"

        "static bool xl6_special_queue_drained_raw(xtqueue value)\n"
        "{\n"
        "    switch ( value->Kind ) {\n"
        "        case 1u: return xrtTypedSPSCQueueIsDrained((xtypedspscqueue*)value->Value);\n"
        "        case 2u: return xrtTypedMPSCQueueIsDrained((xtypedmpscqueue*)value->Value);\n"
        "        default: return xrtTypedMPMCQueueIsDrained((xtypedmpmcqueue*)value->Value);\n"
        "    }\n"
        "}\n\n"

        "static void xl6_special_queue_close_raw(xtqueue value)\n"
        "{\n"
        "    switch ( value->Kind ) {\n"
        "        case 1u: xrtTypedSPSCQueueClose((xtypedspscqueue*)value->Value); break;\n"
        "        case 2u: xrtTypedMPSCQueueClose((xtypedmpscqueue*)value->Value); break;\n"
        "        default: xrtTypedMPMCQueueClose((xtypedmpmcqueue*)value->Value); break;\n"
        "    }\n"
        "}\n\n"

        "static bool xl6_special_queue_reset_raw(xtqueue value)\n"
        "{\n"
        "    switch ( value->Kind ) {\n"
        "        case 1u: return xrtTypedSPSCQueueReset((xtypedspscqueue*)value->Value);\n"
        "        case 2u: return xrtTypedMPSCQueueReset((xtypedmpscqueue*)value->Value);\n"
        "        default: return xrtTypedMPMCQueueReset((xtypedmpmcqueue*)value->Value);\n"
        "    }\n"
        "}\n\n"

        "static void xl6_special_queue_destroy_raw(xtqueue value)\n"
        "{\n"
        "    switch ( value->Kind ) {\n"
        "        case 1u: xrtTypedSPSCQueueDestroy((xtypedspscqueue*)value->Value); break;\n"
        "        case 2u: xrtTypedMPSCQueueDestroy((xtypedmpscqueue*)value->Value); break;\n"
        "        default: xrtTypedMPMCQueueDestroy((xtypedmpmcqueue*)value->Value); break;\n"
        "    }\n"
        "}\n\n"

        "static xtqueue xl6SpecialQueueCreate(uint32_t kind, const xl6_type_desc* itemType, long long capacity)\n"
        "{\n"
        "    xtqueue result;\n"
        "    if ( kind < 1u || kind > 4u || capacity <= 0 ||\n"
        "         (uint64_t)capacity > (uint64_t)SIZE_MAX ) { return 0; }\n"
        "    result = (xtqueue)xrtCalloc(1u, sizeof(*result));\n"
        "    if ( result == 0 ) { return 0; }\n"
        "    result->RefCount = 1;\n"
        "    result->Kind = kind;\n"
        "    if ( !xl6_typed_bridge_acquire(itemType, &result->Bridge, &result->XrtType) ) { xrtFree(result); return 0; }\n"
        "    if ( kind == 1u ) { result->Value = xrtTypedSPSCQueueCreate(result->XrtType, (size_t)capacity); }\n"
        "    else if ( kind == 2u ) { result->Value = xrtTypedMPSCQueueCreate(result->XrtType, (size_t)capacity); }\n"
        "    else { result->Value = xrtTypedMPMCQueueCreate(result->XrtType, (size_t)capacity); }\n"
        "    if ( result->Value == 0 ) { xl6_typed_bridge_release(result->Bridge); xrtFree(result); return 0; }\n"
        "    if ( kind == 4u ) {\n"
        "        result->WaitMutex = xrtMutexCreate();\n"
        "        result->WaitCond = xrtCondCreate();\n"
        "        if ( result->WaitMutex == 0 || result->WaitCond == 0 ) {\n"
        "            if ( result->WaitCond != 0 ) { (void)xrtCondDestroy(result->WaitCond); }\n"
        "            if ( result->WaitMutex != 0 ) { (void)xrtMutexDestroy(result->WaitMutex); }\n"
        "            xl6_special_queue_destroy_raw(result);\n"
        "            xl6_typed_bridge_release(result->Bridge);\n"
        "            xrtFree(result);\n"
        "            return 0;\n"
        "        }\n"
        "    }\n"
        "    return result;\n"
        "}\n\n"

        "static xtqueue xl6SpecialQueueRetain(xtqueue value)\n"
        "{\n"
        "    return value != 0 && xrtRefRetain(&value->RefCount) >= 0 ? value : 0;\n"
        "}\n\n"

        "static void xl6SpecialQueueClose(xtqueue value)\n"
        "{\n"
        "    if ( value == 0 ) { return; }\n"
        "    if ( value->Kind == 4u ) {\n"
        "        if ( !xrtMutexLock(value->WaitMutex) ) { return; }\n"
        "        xl6_special_queue_close_raw(value);\n"
        "        (void)xrtCondBroadcast(value->WaitCond);\n"
        "        (void)xrtMutexUnlock(value->WaitMutex);\n"
        "        return;\n"
        "    }\n"
        "    xl6_special_queue_close_raw(value);\n"
        "}\n\n"

        "static void xl6SpecialQueueRelease(xtqueue value)\n"
        "{\n"
        "    if ( value == 0 || xrtRefRelease(&value->RefCount) != 0 ) { return; }\n"
        "    xl6SpecialQueueClose(value);\n"
        "    xl6_special_queue_destroy_raw(value);\n"
        "    if ( value->WaitCond != 0 ) { (void)xrtCondDestroy(value->WaitCond); }\n"
        "    if ( value->WaitMutex != 0 ) { (void)xrtMutexDestroy(value->WaitMutex); }\n"
        "    xl6_typed_bridge_release(value->Bridge);\n"
        "    xrtFree(value);\n"
        "}\n\n"

        "static int xl6SpecialQueueTryPush(xtqueue value, const void* item)\n"
        "{\n"
        "    int result;\n"
        "    if ( value == 0 ) { return -1; }\n"
        "    result = xl6_special_queue_try_push_raw(value, item);\n"
        "    if ( result == 0 && value->Kind == 4u && xrtMutexLock(value->WaitMutex) ) {\n"
        "        (void)xrtCondSignal(value->WaitCond);\n"
        "        (void)xrtMutexUnlock(value->WaitMutex);\n"
        "    }\n"
        "    return result;\n"
        "}\n\n"

        "static int xl6SpecialQueueTryPop(xtqueue value, void* output)\n"
        "{\n"
        "    return value != 0 ? xl6_special_queue_try_pop_raw(value, output) : -1;\n"
        "}\n\n"

        "static long long xl6SpecialQueuePushBatch(xtqueue value, xtarray items)\n"
        "{\n"
        "    xqueuebatchresult batch;\n"
        "    size_t count;\n"
        "    if ( value == 0 || value->Kind < 1u || value->Kind > 3u || items == 0 ||\n"
        "         items->Kind != XL6_TYPED_CONTAINER_ARRAY || value->XrtType != items->XrtType ) { return -1; }\n"
        "    count = xl6TypedArrayCount(items);\n"
        "    if ( count == 0u ) { return 0; }\n"
        "    batch = xl6_special_queue_push_batch_raw(value, xl6TypedArrayConstData(items), count);\n"
        "    return batch.Result < 0 && batch.Count == 0u ? -1 : (long long)batch.Count;\n"
        "}\n\n"

        "static long long xl6SpecialQueuePopBatchInto(xtqueue value, xtarray output, long long capacity)\n"
        "{\n"
        "    xqueuebatchresult batch;\n"
        "    if ( value == 0 || value->Kind < 1u || value->Kind > 3u || output == 0 ||\n"
        "         output->Kind != XL6_TYPED_CONTAINER_ARRAY || value->XrtType != output->XrtType ||\n"
        "         capacity < 0 || (uint64_t)capacity > (uint64_t)SIZE_MAX ) { return -1; }\n"
        "    if ( !xl6TypedArrayResize(output, capacity) ) { return -1; }\n"
        "    if ( capacity == 0 ) { return 0; }\n"
        "    batch = xl6_special_queue_pop_batch_raw(value, xl6TypedArrayData(output), (size_t)capacity);\n"
        "    if ( !xl6TypedArrayResize(output, (long long)batch.Count) ) { return -1; }\n"
        "    return batch.Result < 0 && batch.Count == 0u ? -1 : (long long)batch.Count;\n"
        "}\n\n"

        "static int xl6_special_queue_wait_pop(xtqueue value, void* output, uint64_t deadline)\n"
        "{\n"
        "    int result;\n"
        "    int waited;\n"
        "    if ( value == 0 || output == 0 || value->Kind != 4u || !xrtMutexLock(value->WaitMutex) ) { return -1; }\n"
        "    for ( ;; ) {\n"
        "        result = xl6_special_queue_try_pop_raw(value, output);\n"
        "        if ( result == 0 || result == 3 || result < 0 ) { break; }\n"
        "        waited = deadline == UINT64_MAX ? xrtCondWait(value->WaitCond, value->WaitMutex) : xrtCondWaitUntil(value->WaitCond, value->WaitMutex, deadline);\n"
        "        if ( waited != 0 ) { result = waited == 1 ? 1 : -1; break; }\n"
        "    }\n"
        "    (void)xrtMutexUnlock(value->WaitMutex);\n"
        "    return result;\n"
        "}\n\n"

        "static int xl6SpecialQueuePop(xtqueue value, void* output)\n"
        "{\n"
        "    return value != 0 && value->Kind == 4u ? xl6_special_queue_wait_pop(value, output, UINT64_MAX) : xl6SpecialQueueTryPop(value, output);\n"
        "}\n\n"

        "static int xl6SpecialQueuePopTimeout(xtqueue value, void* output, long long timeoutMs)\n"
        "{\n"
        "    uint64_t timeout;\n"
        "    if ( timeoutMs < 0 || (uint64_t)timeoutMs > (UINT64_MAX / 1000u) ) { return -1; }\n"
        "    timeout = (uint64_t)timeoutMs * 1000u;\n"
        "    return value != 0 && value->Kind == 4u ? xl6_special_queue_wait_pop(value, output, xrtDeadlineAfter(timeout)) : xl6SpecialQueueTryPop(value, output);\n"
        "}\n\n"

        "static size_t xl6SpecialQueueApproxCount(xtqueue value)\n"
        "{\n"
        "    return value != 0 ? xl6_special_queue_count_raw(value) : 0u;\n"
        "}\n\n"

        "static size_t xl6SpecialQueueCapacity(xtqueue value)\n"
        "{\n"
        "    return value != 0 ? xl6_special_queue_capacity_raw(value) : 0u;\n"
        "}\n\n"

        "static bool xl6SpecialQueueReset(xtqueue value)\n"
        "{\n"
        "    return value != 0 && value->Kind != 4u && xl6_special_queue_reset_raw(value);\n"
        "}\n\n"

        "static bool xl6SpecialQueueIsClosed(xtqueue value)\n"
        "{\n"
        "    return value != 0 && xl6_special_queue_closed_raw(value);\n"
        "}\n\n"

        "static bool xl6SpecialQueueIsDrained(xtqueue value)\n"
        "{\n"
        "    return value != 0 && xl6_special_queue_drained_raw(value);\n"
        "}\n\n"

        "static void* xl6_special_collection_require(void* handle, int line, int column)\n"
        "{\n"
        "    (void)line; (void)column;\n"
        "    if ( handle == 0 ) { xl6_runtime_fatal(3); }\n"
        "    return handle;\n"
        "}\n\n";

    xl6OutputPuts(Runtime, out);
