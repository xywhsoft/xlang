static void xl6CgenEmitProcessExtendedRuntime(XL6_Output* out)
{
    if ( out == NULL ) {
        return;
    }

    xl6OutputPuts(
        "typedef struct { uint64_t iBaseOffset; uint64_t iNextOffset; uint64_t iStreamEndOffset; bool bDone; } xprocessreadinfo;\n"
        "typedef struct { uint64_t iSeq; int iKind; int iStream; uint64_t iOffset; uint64_t iSize; uint64_t tTimeMs; xprocessexitinfo ExitInfo; } xprocessevent;\n"
        "typedef struct { uint64_t iBaseSeq; uint64_t iNextSeq; uint64_t iEventEndSeq; bool bDone; } xprocesseventreadinfo;\n"
        "typedef struct xrt_net_future xfuture;\n"
        "void* xrtRealloc(void* p, size_t size);\n"
        "int xrtProcessState(xprocess* pProcess);\n"
        "bool xrtProcessGetExitInfo(xprocess* pProcess, xprocessexitinfo* pInfo);\n"
        "bool xrtProcessTerminalSupported(void);\n"
        "bool xrtProcessInterrupt(xprocess* pProcess);\n"
        "bool xrtProcessResizeTerminal(xprocess* pProcess, uint32_t cols, uint32_t rows);\n"
        "void* xrtProcessReadStdoutSince(xprocess* pProcess, uint64_t offset, size_t maxBytes, size_t* size, xprocessreadinfo* info);\n"
        "void* xrtProcessReadStderrSince(xprocess* pProcess, uint64_t offset, size_t maxBytes, size_t* size, xprocessreadinfo* info);\n"
        "xprocessevent* xrtProcessReadEventsSince(xprocess* pProcess, uint64_t seq, uint32_t maxCount, uint32_t* count, xprocesseventreadinfo* info);\n"
        "xfuture* xrtProcessWaitFuture(xprocess* pProcess);\n"
        "xvalue xvoCreateNull(void);\n"
        "xvalue xvoCreateBool(bool value);\n"
        "xvalue xvoCreateInt(long long value);\n"
        "xvalue xvoCreateText(void* text, unsigned int size, bool colloc);\n"
        "xvalue xvoCreateArray(void);\n"
        "xvalue xvoCreateTable(void);\n"
        "bool xvoArrayAppendValue(xvalue array, xvalue value, bool colloc);\n"
        "bool xvoTableSetValue(xvalue table, const void* key, unsigned int keySize, xvalue value, bool colloc);\n"
        "void xvoUnref(xvalue value);\n\n",
        out);

    xl6OutputPuts(
        "static int xl6_process_table_take(xvalue table, const char* key, xvalue value)\n"
        "{\n"
        "    if ( table == 0 || value == 0 ) { if ( value != 0 ) { xvoUnref(value); } return 0; }\n"
        "    if ( !xvoTableSetValue(table, key, 0u, value, true) ) { xvoUnref(value); return 0; }\n"
        "    return 1;\n"
        "}\n\n"
        "static int xl6_process_array_take(xvalue array, xvalue value)\n"
        "{\n"
        "    if ( array == 0 || value == 0 ) { if ( value != 0 ) { xvoUnref(value); } return 0; }\n"
        "    if ( !xvoArrayAppendValue(array, value, true) ) { xvoUnref(value); return 0; }\n"
        "    return 1;\n"
        "}\n\n"
        "static xvalue xl6_process_exit_info_value(const xprocessexitinfo* info)\n"
        "{\n"
        "    xvalue value = xvoCreateTable();\n"
        "    if ( value == 0 ) { return 0; }\n"
        "    if ( !xl6_process_table_take(value, \"kind\", xvoCreateInt(info != 0 ? info->iKind : 0)) ||\n"
        "         !xl6_process_table_take(value, \"exitCode\", xvoCreateInt(info != 0 ? info->iExitCode : -1)) ||\n"
        "         !xl6_process_table_take(value, \"signal\", xvoCreateInt(info != 0 ? info->iSignal : 0)) ||\n"
        "         !xl6_process_table_take(value, \"stage\", xvoCreateInt(info != 0 ? info->iStage : 0)) ||\n"
        "         !xl6_process_table_take(value, \"osError\", xvoCreateInt(info != 0 ? info->iOsError : 0)) ||\n"
        "         !xl6_process_table_take(value, \"stopReason\", xvoCreateInt(info != 0 ? info->iStopReason : 0)) ||\n"
        "         !xl6_process_table_take(value, \"timedOut\", xvoCreateBool(info != 0 && info->bTimedOut)) ||\n"
        "         !xl6_process_table_take(value, \"cancelled\", xvoCreateBool(info != 0 && info->bCancelled)) ) {\n"
        "        xvoUnref(value); return 0;\n"
        "    }\n"
        "    return value;\n"
        "}\n\n",
        out);

    xl6OutputPuts(
        "int xl6_xrt_process_command_work_dir(void* value, const char* path)\n"
        "{\n"
        "    xl6_process_command* command = (xl6_process_command*)value;\n"
        "    char* copy;\n"
        "    if ( command == 0 ) { return 0; }\n"
        "    copy = xl6_process_copy_text(path);\n"
        "    if ( copy == 0 ) { return 0; }\n"
        "    if ( command->sWorkDir != 0 ) { xrtFree(command->sWorkDir); }\n"
        "    command->sWorkDir = copy;\n"
        "    command->Config.sWorkDir = copy;\n"
        "    return 1;\n"
        "}\n\n"
        "static int xl6_process_env_name_equals(const char* entry, const char* name, size_t nameSize)\n"
        "{\n"
        "    return entry != 0 && strncmp(entry, name, nameSize) == 0 && entry[nameSize] == '=';\n"
        "}\n\n"
        "int xl6_xrt_process_command_env(void* value, const char* name, const char* envValue)\n"
        "{\n"
        "    xl6_process_command* command = (xl6_process_command*)value;\n"
        "    size_t nameSize; size_t valueSize; char* entry; uint32_t i; char** resized;\n"
        "    if ( command == 0 || name == 0 || name[0] == '\\0' || strchr(name, '=') != 0 ) { return 0; }\n"
        "    if ( envValue == 0 ) { envValue = \"\"; }\n"
        "    nameSize = strlen(name); valueSize = strlen(envValue);\n"
        "    if ( nameSize > (size_t)-1 - valueSize - 2u ) { return 0; }\n"
        "    entry = (char*)xrtMalloc(nameSize + valueSize + 2u);\n"
        "    if ( entry == 0 ) { return 0; }\n"
        "    memcpy(entry, name, nameSize); entry[nameSize] = '='; memcpy(entry + nameSize + 1u, envValue, valueSize + 1u);\n"
        "    for ( i = 0u; i < command->iEnvCount; ++i ) {\n"
        "        if ( xl6_process_env_name_equals(command->arrEnv[i], name, nameSize) ) {\n"
        "            xrtFree(command->arrEnv[i]); command->arrEnv[i] = entry; return 1;\n"
        "        }\n"
        "    }\n"
        "    if ( command->iEnvCount == UINT32_MAX ) { xrtFree(entry); return 0; }\n"
        "    resized = (char**)xrtRealloc(command->arrEnv, ((size_t)command->iEnvCount + 1u) * sizeof(char*));\n"
        "    if ( resized == 0 ) { xrtFree(entry); return 0; }\n"
        "    command->arrEnv = resized; command->arrEnv[command->iEnvCount++] = entry;\n"
        "    command->Config.arrEnv = command->arrEnv; command->Config.iEnvCount = command->iEnvCount;\n"
        "    return 1;\n"
        "}\n\n"
        "int xl6_xrt_process_command_clear_env(void* value)\n"
        "{\n"
        "    xl6_process_command* command = (xl6_process_command*)value; uint32_t i;\n"
        "    if ( command == 0 ) { return 0; }\n"
        "    for ( i = 0u; i < command->iEnvCount; ++i ) { xrtFree(command->arrEnv[i]); }\n"
        "    xrtFree(command->arrEnv); command->arrEnv = 0; command->iEnvCount = 0u;\n"
        "    command->Config.arrEnv = 0; command->Config.iEnvCount = 0u; return 1;\n"
        "}\n\n",
        out);

    xl6OutputPuts(
        "int xl6_xrt_process_command_inherit_env(void* v, int b) { xl6_process_command* c=(xl6_process_command*)v; if(!c)return 0; c->Config.bInheritEnv=b!=0; return 1; }\n"
        "int xl6_xrt_process_command_use_terminal(void* v, int b) { xl6_process_command* c=(xl6_process_command*)v; if(!c)return 0; c->Config.bUseTerminal=b!=0; return 1; }\n"
        "int xl6_xrt_process_command_new_console(void* v, int b) { xl6_process_command* c=(xl6_process_command*)v; if(!c)return 0; c->Config.bNewConsole=b!=0; return 1; }\n"
        "int xl6_xrt_process_command_merge_stderr(void* v, int b) { xl6_process_command* c=(xl6_process_command*)v; if(!c)return 0; c->Config.bMergeStderr=b!=0; return 1; }\n"
        "int xl6_xrt_process_command_process_group(void* v, int b) { xl6_process_command* c=(xl6_process_command*)v; if(!c)return 0; c->Config.bCreateProcessGroup=b!=0; return 1; }\n"
        "int xl6_xrt_process_command_hide_window(void* v, int b) { xl6_process_command* c=(xl6_process_command*)v; if(!c)return 0; c->Config.bHideWindow=b!=0; return 1; }\n"
        "int xl6_xrt_process_command_terminal_size(void* v, long long cols, long long rows) { xl6_process_command* c=(xl6_process_command*)v; if(!c||cols<=0||rows<=0||cols>UINT32_MAX||rows>UINT32_MAX)return 0; c->Config.iTerminalCols=(uint32_t)cols; c->Config.iTerminalRows=(uint32_t)rows; return 1; }\n"
        "int xl6_xrt_process_command_read_chunk_size(void* v, long long n) { xl6_process_command* c=(xl6_process_command*)v; if(!c||n<=0||n>UINT32_MAX)return 0; c->Config.iReadChunkSize=(uint32_t)n; return 1; }\n"
        "int xl6_xrt_process_command_max_capture_bytes(void* v, long long n) { xl6_process_command* c=(xl6_process_command*)v; if(!c||n<0)return 0; c->Config.iMaxCaptureBytes=(size_t)n; return (long long)c->Config.iMaxCaptureBytes==n; }\n"
        "int xl6_xrt_process_command_max_event_count(void* v, long long n) { xl6_process_command* c=(xl6_process_command*)v; if(!c||n<0||n>UINT32_MAX)return 0; c->Config.iMaxEventCount=(uint32_t)n; return 1; }\n"
        "int xl6_xrt_process_command_stdio(void* v, long long stream, long long mode, int capture) { xl6_process_command* c=(xl6_process_command*)v; xprocessstdio* s; if(!c||stream<0||stream>2||mode<0||mode>2)return 0; s=stream==0?&c->Config.Stdin:(stream==1?&c->Config.Stdout:&c->Config.Stderr); s->iMode=(int)mode; s->bCapture=capture!=0; return 1; }\n\n",
        out);

    xl6OutputPuts(
        "void* xl6_xrt_process_wrap(void* value) { return value; }\n\n"
        "void* xl6_xrt_process_command_run(void* value, const char* input, size_t inputSize, long long timeoutMs)\n"
        "{\n"
        "    xl6_process_command* command = (xl6_process_command*)value; xprocessresult* result = xl6_process_result_alloc();\n"
        "    if ( result == 0 ) { return 0; }\n"
        "    if ( command == 0 || !xrtProcessRun(&command->Config, input, inputSize, result, xl6_process_timeout(timeoutMs > 2147483647LL ? 2147483647 : (int)timeoutMs)) ) {\n"
        "        if ( command == 0 ) { xl6_xrt_process_result_destroy(result); return 0; }\n"
        "    }\n"
        "    return result;\n"
        "}\n\n"
        "void* xl6_xrt_process_command_start(void* value)\n"
        "{\n"
        "    xl6_process_command* command = (xl6_process_command*)value;\n"
        "    return command != 0 ? xrtProcessSpawn(&command->Config) : 0;\n"
        "}\n\n"
        "bool xl6_xrt_process_terminal_supported(void) { return xrtProcessTerminalSupported(); }\n"
        "long long xl6_xrt_process_state(void* value) { return value != 0 ? xrtProcessState((xprocess*)value) : 0; }\n"
        "int xl6_xrt_process_interrupt(void* value) { return value != 0 && xrtProcessInterrupt((xprocess*)value); }\n"
        "int xl6_xrt_process_resize_terminal(void* value, long long cols, long long rows) { return value != 0 && cols > 0 && rows > 0 && cols <= UINT32_MAX && rows <= UINT32_MAX && xrtProcessResizeTerminal((xprocess*)value, (uint32_t)cols, (uint32_t)rows); }\n"
        "int xl6_xrt_process_write_bytes(void* value, void* data, size_t size) { return value != 0 && (size == 0u || data != 0) && xrtProcessWrite((xprocess*)value, data, size) == (int64_t)size; }\n"
        "xfuture* xl6_xrt_process_wait_future(void* value) { return value != 0 ? xrtProcessWaitFuture((xprocess*)value) : 0; }\n\n",
        out);

    xl6OutputPuts(
        "xvalue xl6_xrt_process_exit_info(void* value)\n"
        "{\n"
        "    xprocessexitinfo info; memset(&info, 0, sizeof(info));\n"
        "    if ( value == 0 || !xrtProcessGetExitInfo((xprocess*)value, &info) ) { return xl6_process_exit_info_value(0); }\n"
        "    return xl6_process_exit_info_value(&info);\n"
        "}\n\n"
        "xvalue xl6_xrt_process_result_exit_info(void* value)\n"
        "{\n"
        "    xprocessresult* result = (xprocessresult*)value;\n"
        "    return xl6_process_exit_info_value(result != 0 ? &result->ExitInfo : 0);\n"
        "}\n\n"
        "static xvalue xl6_process_read_since(void* value, uint64_t offset, size_t maxBytes, int stderrStream)\n"
        "{\n"
        "    xprocessreadinfo info; size_t size = 0u; void* data; xvalue result; xvalue text;\n"
        "    memset(&info, 0, sizeof(info));\n"
        "    data = value != 0 ? (stderrStream ? xrtProcessReadStderrSince((xprocess*)value, offset, maxBytes, &size, &info) : xrtProcessReadStdoutSince((xprocess*)value, offset, maxBytes, &size, &info)) : 0;\n"
        "    result = xvoCreateTable(); if ( result == 0 ) { xrtFree(data); return 0; }\n"
        "    if ( data != 0 && size <= UINT32_MAX ) { text = xvoCreateText(data, (unsigned int)size, true); data = 0; } else { text = xvoCreateText((void*)\"\", 0u, false); }\n"
        "    xrtFree(data);\n"
        "    if ( !xl6_process_table_take(result, \"data\", text) ||\n"
        "         !xl6_process_table_take(result, \"baseOffset\", xvoCreateInt((long long)info.iBaseOffset)) ||\n"
        "         !xl6_process_table_take(result, \"nextOffset\", xvoCreateInt((long long)info.iNextOffset)) ||\n"
        "         !xl6_process_table_take(result, \"streamEndOffset\", xvoCreateInt((long long)info.iStreamEndOffset)) ||\n"
        "         !xl6_process_table_take(result, \"done\", xvoCreateBool(info.bDone)) ) { xvoUnref(result); return 0; }\n"
        "    return result;\n"
        "}\n\n"
        "xvalue xl6_xrt_process_read_stdout(void* value, long long offset, long long maxBytes) { return xl6_process_read_since(value, offset > 0 ? (uint64_t)offset : 0u, maxBytes > 0 ? (size_t)maxBytes : 0u, 0); }\n"
        "xvalue xl6_xrt_process_read_stderr(void* value, long long offset, long long maxBytes) { return xl6_process_read_since(value, offset > 0 ? (uint64_t)offset : 0u, maxBytes > 0 ? (size_t)maxBytes : 0u, 1); }\n\n",
        out);

    xl6OutputPuts(
        "xvalue xl6_xrt_process_read_events(void* value, long long seq, long long maxCount)\n"
        "{\n"
        "    xprocesseventreadinfo info; xprocessevent* events; uint32_t count = 0u; uint32_t i; xvalue result; xvalue items;\n"
        "    memset(&info, 0, sizeof(info));\n"
        "    events = value != 0 ? xrtProcessReadEventsSince((xprocess*)value, seq > 0 ? (uint64_t)seq : 0u, maxCount > 0 && maxCount <= UINT32_MAX ? (uint32_t)maxCount : 0u, &count, &info) : 0;\n"
        "    result = xvoCreateTable(); items = xvoCreateArray();\n"
        "    if ( result == 0 || items == 0 ) { if(result)xvoUnref(result); if(items)xvoUnref(items); xrtFree(events); return 0; }\n"
        "    for ( i = 0u; i < count; ++i ) {\n"
        "        xvalue item = xvoCreateTable(); xvalue exitInfo;\n"
        "        if ( item == 0 || !xl6_process_table_take(item, \"seq\", xvoCreateInt((long long)events[i].iSeq)) ||\n"
        "             !xl6_process_table_take(item, \"kind\", xvoCreateInt(events[i].iKind)) ||\n"
        "             !xl6_process_table_take(item, \"stream\", xvoCreateInt(events[i].iStream)) ||\n"
        "             !xl6_process_table_take(item, \"offset\", xvoCreateInt((long long)events[i].iOffset)) ||\n"
        "             !xl6_process_table_take(item, \"size\", xvoCreateInt((long long)events[i].iSize)) ||\n"
        "             !xl6_process_table_take(item, \"timeMs\", xvoCreateInt((long long)events[i].tTimeMs)) ) { if(item)xvoUnref(item); break; }\n"
        "        exitInfo = xl6_process_exit_info_value(&events[i].ExitInfo);\n"
        "        if ( !xl6_process_table_take(item, \"exitInfo\", exitInfo) ) { xvoUnref(item); break; }\n"
        "        if ( !xl6_process_array_take(items, item) ) { break; }\n"
        "    }\n"
        "    xrtFree(events);\n"
        "    if ( !xl6_process_table_take(result, \"items\", items) ||\n"
        "         !xl6_process_table_take(result, \"baseSeq\", xvoCreateInt((long long)info.iBaseSeq)) ||\n"
        "         !xl6_process_table_take(result, \"nextSeq\", xvoCreateInt((long long)info.iNextSeq)) ||\n"
        "         !xl6_process_table_take(result, \"eventEndSeq\", xvoCreateInt((long long)info.iEventEndSeq)) ||\n"
        "         !xl6_process_table_take(result, \"done\", xvoCreateBool(info.bDone)) ) { xvoUnref(result); return 0; }\n"
        "    return result;\n"
        "}\n\n",
        out);
}
