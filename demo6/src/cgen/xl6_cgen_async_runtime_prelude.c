static void xl6CgenEmitAsyncRuntimePrelude(
	XL6_Output* out,
	int hasStringRuntime)
{
    xl6OutputPuts("#include <stddef.h>\n", out);
    xl6OutputPuts("#include <stdarg.h>\n", out);
    xl6OutputPuts("#include <string.h>\n", out);
    xl6OutputPuts("#ifndef XL6_XRT_ASYNC_TYPEDEF\n", out);
    xl6OutputPuts("#define XL6_XRT_ASYNC_TYPEDEF\n", out);
    xl6OutputPuts("typedef struct xl6_task_group xl6_task_group;\n", out);
    xl6OutputPuts("typedef void* xl6_channel;\n", out);
    xl6OutputPuts("typedef enum xl6_channel_result { XL6_CHANNEL_ERROR = -1, XL6_CHANNEL_OK = 0, XL6_CHANNEL_EMPTY = 1, XL6_CHANNEL_FULL = 2, XL6_CHANNEL_CLOSED = 3, XL6_CHANNEL_TIMEOUT = 4 } xl6_channel_result;\n", out);
    xl6OutputPuts("#ifndef XL6_FUTURE_RESULT_TYPEDEF\n", out);
    xl6OutputPuts("#define XL6_FUTURE_RESULT_TYPEDEF\n", out);
    xl6OutputPuts("typedef struct {\n", out);
    xl6OutputPuts("    int iStatus;\n", out);
    xl6OutputPuts("    void* pValue;\n", out);
    xl6OutputPuts("    xerror* Error;\n", out);
    xl6OutputPuts("    unsigned int iFlags;\n", out);
    xl6OutputPuts("    void (*pfnFreeValue)(void* pValue);\n", out);
    xl6OutputPuts("} xl6_future_result;\n", out);
    xl6OutputPuts("typedef int (*xl6_future_continue_proc)(const xl6_future_result* pIn, void* pArg, xl6_future_result* pOut);\n", out);
    xl6OutputPuts("typedef void (*xl6_future_arg_free_proc)(void* pArg);\n", out);
    xl6OutputPuts("#endif\n", out);
    xl6OutputPuts("typedef enum xl6_future_state { XL6_FUTURE_PENDING = 0, XL6_FUTURE_RESOLVED = 1, XL6_FUTURE_FAILED = 2, XL6_FUTURE_CANCELLED = 3, XL6_FUTURE_CLOSED = 4 } xl6_future_state;\n", out);
    xl6OutputPuts("typedef int (*xl6_task_thread_proc)(void* pArg, xl6_future_result* pOut);\n", out);
    xl6OutputPuts("typedef void (*xl6_future_finally_proc)(const xl6_future_result* pIn, void* pArg);\n", out);
    xl6OutputPuts("#endif\n", out);
    xl6OutputPuts("#ifndef XL6_FUTURE_OWN_VALUE\n", out);
    xl6OutputPuts("#define XL6_FUTURE_OWN_VALUE 0x00000001u\n", out);
    xl6OutputPuts("#endif\n", out);
    xl6OutputPuts("#ifndef XL6_FUTURE_STATUS_OK\n", out);
    xl6OutputPuts("#define XL6_FUTURE_STATUS_OK 0\n", out);
    xl6OutputPuts("#define XL6_FUTURE_STATUS_FAILED (-1)\n", out);
    xl6OutputPuts("#define XL6_FUTURE_STATUS_CANCELLED (-2)\n", out);
    xl6OutputPuts("#define XL6_FUTURE_STATUS_CLOSED (-3)\n", out);
    xl6OutputPuts("#endif\n", out);
	if ( hasStringRuntime ) {
		xl6OutputPuts("static inline char* xl6_xrt_string_dup(const char* sText, size_t iSize);\n", out);
		xl6OutputPuts("static void xl6_async_free_string_value(void* pValue)\n", out);
		xl6OutputPuts("{\n", out);
		xl6OutputPuts("    const char** value = (const char**)pValue;\n", out);
		xl6OutputPuts("    if ( value != 0 && *value != 0 ) {\n", out);
		xl6OutputPuts("        xrtFree((void*)*value);\n", out);
		xl6OutputPuts("        *value = 0;\n", out);
		xl6OutputPuts("    }\n", out);
		xl6OutputPuts("    xrtFree(pValue);\n", out);
		xl6OutputPuts("}\n\n", out);
	}
    xl6OutputPuts("xfuture* xl6FutureRunThread(xl6_task_thread_proc pfnTask, void* pArg, size_t iStackSize);\nxfuture* xl6FutureRef(xfuture* pFuture);\nbool xl6FutureWait(xfuture* pFuture);\nbool xl6FutureWaitFor(xfuture* pFuture, long long iTimeoutMs);\nbool xl6FutureWaitUntil(xfuture* pFuture, long long iDeadlineMs);\nbool xl6FutureSetName(xfuture* pFuture, const char* sDebugName);\nconst char* xl6FutureName(xfuture* pFuture);\nunsigned long long xl6FutureCreatedMs(xfuture* pFuture);\nunsigned long long xl6FutureCompletedMs(xfuture* pFuture);\nint xl6FuturePendingCount(xfuture* pFuture);\nxl6_future_state xl6FutureState(xfuture* pFuture);\nint xl6FutureStatus(xfuture* pFuture);\nvoid* xl6FutureValue(xfuture* pFuture);\nconst xerror* xl6FutureError(xfuture* pFuture);\nvoid xl6FutureDestroy(xfuture* pFuture);\n", out);
    xl6OutputPuts("bool xl6FutureCancel(xfuture* pFuture);\nbool xl6FutureLinkCancel(xfuture* pFuture, xfuture* pTarget);\nxfuture* xl6FutureAny(xfuture** arrFuture, int iCount);\nxfuture* xl6FutureAll(xfuture** arrFuture, int iCount);\nxfuture* xl6FutureRace(xfuture** arrFuture, int iCount);\nint xl6FuturePickIndex(xfuture* pFuture);\nint xl6FutureAllCount(xfuture* pFuture);\nvoid* xl6FutureAllValue(xfuture* pFuture, int iIndex);\n", out);
    xl6OutputPuts("static bool xl6_future_request_cancel(xfuture* future)\n{\n    return future != 0 && xl6FutureCancel(future);\n}\n", out);
    xl6OutputPuts("xfuture* xl6FutureThenOwned(xfuture* pFuture, xl6_future_continue_proc pfnCont, void* pArg, xl6_future_arg_free_proc pfnFreeArg);\n", out);
    xl6OutputPuts("xfuture* xl6FutureCatchOwned(xfuture* pFuture, xl6_future_continue_proc pfnCont, void* pArg, xl6_future_arg_free_proc pfnFreeArg);\n", out);
    xl6OutputPuts("xfuture* xl6FutureContinueOwned(xfuture* pFuture, xl6_future_continue_proc pfnCont, void* pArg, xl6_future_arg_free_proc pfnFreeArg);\n", out);
    xl6OutputPuts("xfuture* xl6FutureThen(xfuture* pFuture, xl6_future_continue_proc pfnCont, void* pArg);\n", out);
    xl6OutputPuts("xfuture* xl6FutureFinally(xfuture* pFuture, xl6_future_finally_proc pfnCont, void* pArg);\n", out);
    xl6OutputPuts("xl6_task_group* xl6TaskGroupCreate(void);\nvoid xl6TaskGroupDestroy(xl6_task_group* pGroup);\nbool xl6TaskGroupClose(xl6_task_group* pGroup);\nxl6_task_group* xl6TaskGroupChild(xl6_task_group* pParent);\nbool xl6TaskGroupBindParent(xl6_task_group* pGroup, xfuture* pParent);\nbool xl6TaskGroupAdd(xl6_task_group* pGroup, xfuture* pFuture);\nint xl6TaskGroupCount(xl6_task_group* pGroup);\nint xl6TaskGroupReap(xl6_task_group* pGroup);\nxfuture* xl6TaskGroupFuture(xl6_task_group* pGroup);\nbool xl6TaskGroupJoin(xl6_task_group* pGroup);\nbool xl6TaskGroupJoinFor(xl6_task_group* pGroup, long long iTimeoutMs);\nbool xl6TaskGroupJoinUntil(xl6_task_group* pGroup, long long iDeadlineMs);\nbool xl6TaskGroupCancel(xl6_task_group* pGroup);\n", out);
    xl6OutputPuts("xl6_channel xl6ChannelCreate(size_t iCapacity);\n", out);
    xl6OutputPuts("void xl6ChannelDestroy(xl6_channel pChannel);\n", out);
    xl6OutputPuts("xl6_channel_result xl6ChannelSend(xl6_channel pChannel, void* pItem, bool bWait);\n", out);
    xl6OutputPuts("xl6_channel_result xl6ChannelRecv(xl6_channel pChannel, void** ppItem, bool bWait);\n", out);
    xl6OutputPuts("xl6_channel_result xl6ChannelRecvFor(xl6_channel pChannel, void** ppItem, long long iTimeoutMs);\n", out);
    xl6OutputPuts("void xl6ChannelClose(xl6_channel pChannel);\n", out);
    xl6OutputPuts("size_t xl6ChannelCount(xl6_channel pChannel);\n", out);
    xl6OutputPuts("bool xl6ChannelIsClosed(xl6_channel pChannel);\n\n", out);

    /* TCC 模块卸载前等待本模块启动的任务退出。 */
    xl6OutputPuts("typedef struct XL6_TrackedTask { xl6_task_thread_proc fn; void* arg; } XL6_TrackedTask;\n", out);
    xl6OutputPuts("static xatomic32 xl6_async_active_tasks = XRT_ATOMIC32_INIT(0u);\n", out);
    xl6OutputPuts("static long xl6_async_active_add(long value)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    uint32 oldValue;\n", out);
    xl6OutputPuts("    uint32 delta;\n", out);
    xl6OutputPuts("    if ( value >= 0 ) {\n", out);
    xl6OutputPuts("        delta = (uint32)value;\n", out);
    xl6OutputPuts("        oldValue = xrtAtomic32FetchAdd(&xl6_async_active_tasks, delta, XMEMORY_SEQ_CST);\n", out);
    xl6OutputPuts("        return (long)(oldValue + delta);\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    delta = (uint32)(-value);\n", out);
    xl6OutputPuts("    oldValue = xrtAtomic32FetchSub(&xl6_async_active_tasks, delta, XMEMORY_SEQ_CST);\n", out);
    xl6OutputPuts("    return (long)(oldValue - delta);\n", out);
    xl6OutputPuts("}\n", out);
    xl6OutputPuts("static int xl6_tracked_task_entry(void* pArg, xl6_future_result* pOut)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    XL6_TrackedTask* task = (XL6_TrackedTask*)pArg;\n", out);
    xl6OutputPuts("    xl6_task_thread_proc fn = task != 0 ? task->fn : 0;\n", out);
    xl6OutputPuts("    void* arg = task != 0 ? task->arg : 0;\n", out);
    xl6OutputPuts("    int result = -1;\n", out);
    xl6OutputPuts("    xrtFree(task);\n", out);
    xl6OutputPuts("    if ( fn != 0 ) { result = fn(arg, pOut); }\n", out);
    xl6OutputPuts("    (void)xl6_async_active_add(-1);\n", out);
    xl6OutputPuts("    return result;\n", out);
    xl6OutputPuts("}\n", out);
    xl6OutputPuts("static xfuture* xl6_task_run_thread_tracked(xl6_task_thread_proc fn, void* arg, size_t stackSize)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    XL6_TrackedTask* task = (XL6_TrackedTask*)xrtMalloc(sizeof(XL6_TrackedTask));\n", out);
    xl6OutputPuts("    xfuture* future;\n", out);
    xl6OutputPuts("    if ( task == 0 || fn == 0 ) { xrtFree(task); return 0; }\n", out);
    xl6OutputPuts("    task->fn = fn; task->arg = arg;\n", out);
    xl6OutputPuts("    (void)xl6_async_active_add(1);\n", out);
    xl6OutputPuts("    future = xl6FutureRunThread(xl6_tracked_task_entry, task, stackSize);\n", out);
    xl6OutputPuts("    if ( future == 0 ) { (void)xl6_async_active_add(-1); xrtFree(task); }\n", out);
    xl6OutputPuts("    return future;\n", out);
    xl6OutputPuts("}\n", out);
    xl6OutputPuts("static void xl6_async_wait_idle(void)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    while ( xl6_async_active_add(0) != 0 ) { xrtSleep(1); }\n", out);
    xl6OutputPuts("}\n\n", out);
}
