/* 输出基于当前 XRT 字符串视图和 UTF-8 契约的标准库桥接。 */
static void xl6CgenEmitStdStringRuntime(XL6_Output* out)
{
    if ( out == NULL ) {
        return;
    }

    xl6OutputPuts(
        "#ifndef XL6_STD_STRING_RUNTIME\n"
        "#define XL6_STD_STRING_RUNTIME\n"
        "#ifndef XL_RUNTIME_H\n"
        "#ifndef XL6_XVALUE_TYPEDEF\n"
        "#define XL6_XVALUE_TYPEDEF\n"
        "typedef struct xvalue xvalue;\n"
        "#endif\n"
        "#ifndef XL6_XRT_STRLIST_TYPEDEF\n"
        "#define XL6_XRT_STRLIST_TYPEDEF\n"
        "typedef struct xstrlist { size_t Count; xstrview* Items; } xstrlist;\n"
        "#endif\n"
        "#ifndef XL6_XRT_UTF_STATUS_TYPEDEF\n"
        "#define XL6_XRT_UTF_STATUS_TYPEDEF\n"
        "typedef enum xutfstatus { XUTF_OK = 0, XUTF_MORE, XUTF_INVALID, XUTF_NO_SPACE, XUTF_OVERFLOW } xutfstatus;\n"
        "#endif\n"
        "#define XL6_XRT_NPOS ((size_t)-1)\n"
        "void* xrtMalloc(size_t size);\n"
        "void xrtFree(void* memory);\n"
        "xstrview xrtStrView(const char* text);\n"
        "xstrview xrtStrViewN(const char* text, size_t size);\n"
        "int xrtStrCompare(xstrview left, xstrview right);\n"
        "int xrtStrCaseCompare(xstrview left, xstrview right);\n"
        "bool xrtStrContains(xstrview text, xstrview part);\n"
        "bool xrtStrCaseContains(xstrview text, xstrview part);\n"
        "size_t xrtStrCount(xstrview text, xstrview part);\n"
        "size_t xrtStrCaseCount(xstrview text, xstrview part);\n"
        "xstrview xrtStrTrimLeft(xstrview text);\n"
        "xstrview xrtStrTrimRight(xstrview text);\n"
        "xstrview xrtStrTrim(xstrview text);\n"
        "bool xrtStrEmpty(xstrview text);\n"
        "bool xrtStrBlank(xstrview text);\n"
        "char* xrtStrDup(const char* text);\n"
        "char* xrtStrDupN(const char* text, size_t size);\n"
        "char* xrtStrLower(xstrview text);\n"
        "char* xrtStrUpper(xstrview text);\n"
        "char* xrtStrRepeat(xstrview text, size_t count);\n"
        "char* xrtStrReplace(xstrview text, xstrview part, xstrview replacement);\n"
        "char* xrtStrJoin(xstrview separator, const xstrview* texts, size_t count);\n"
        "bool xrtStrGlob(xstrview text, xstrview pattern, unsigned int flags);\n"
        "xstrlist* xrtStrSplit(xstrview text, xstrview separator);\n"
        "xstrlist* xrtStrSplitLines(xstrview text);\n"
        "void xrtStrListFree(xstrlist* list);\n"
        "xutfstatus xrtUtf8Decode(xstrview text, unsigned int* scalar, size_t* read);\n"
        "bool xrtUtf8Valid(xstrview text, size_t* error);\n"
        "size_t xrtUtf8Count(xstrview text);\n"
        "size_t xrtUtf8Find(xstrview text, xstrview part, size_t start);\n"
        "size_t xrtUtf8CaseFind(xstrview text, xstrview part, size_t start);\n"
        "size_t xrtUtf8RFind(xstrview text, xstrview part);\n"
        "size_t xrtUtf8CaseRFind(xstrview text, xstrview part);\n"
        "bool xrtUtf8ContainsAny(xstrview text, xstrview set);\n"
        "bool xrtUtf8TrimLeftSet(xstrview text, xstrview set, xstrview* result);\n"
        "bool xrtUtf8TrimRightSet(xstrview text, xstrview set, xstrview* result);\n"
        "bool xrtUtf8TrimSet(xstrview text, xstrview set, xstrview* result);\n"
        "char* xrtUtf8Substr(xstrview text, int64_t start, int64_t count);\n"
        "char* xrtUtf8Insert(xstrview text, int64_t position, xstrview part);\n"
        "char* xrtUtf8Remove(xstrview text, int64_t start, int64_t count);\n"
        "char* xrtUtf8PadLeft(xstrview text, size_t width, xstrview fill);\n"
        "char* xrtUtf8PadRight(xstrview text, size_t width, xstrview fill);\n"
        "char* xrtUtf8PadCenter(xstrview text, size_t width, xstrview fill);\n"
        "char* xrtUtf8Reverse(xstrview text);\n"
        "char* xrtUtf8Filter(xstrview text, xstrview set);\n"
        "double xrtUtf8Similarity(xstrview left, xstrview right);\n"
        "char* xrtIntFormat(int64_t value, xstrview format);\n"
        "char* xrtUIntFormat(uint64_t value, xstrview format);\n"
        "char* xrtNumFormat(double value, xstrview format);\n"
        "xvalue* xrtValueArray(void);\n"
        "xvalue* xrtValueString(xstrview text);\n"
        "xvalue* xrtValueInt(int64_t value);\n"
        "size_t xrtValueCount(const xvalue* value);\n"
        "xvalue* xrtValueArrayGet(const xvalue* array, size_t index);\n"
        "bool xrtValueArrayAppendNew(xvalue* array, xvalue* item);\n"
        "void xrtValueRelease(xvalue* value);\n"
        "#endif\n"
        "#ifndef XL6_XRT_NPOS\n"
        "#define XL6_XRT_NPOS ((size_t)-1)\n"
        "#endif\n"
        "static const char* xl6_xrt_value_to_string(xvalue* value);\n\n"

        "static char* xl6_xrt_string_copy_view(xstrview text)\n"
        "{\n"
        "    return xrtStrDupN(text.Data != 0 ? text.Data : \"\", text.Size);\n"
        "}\n\n"

        "static bool xl6_xrt_string_array_append(xvalue* array, xstrview text)\n"
        "{\n"
        "    xvalue* item = xrtValueString(text);\n\n"
        "    if ( item == 0 ) {\n"
        "        return false;\n"
        "    }\n"
        "    if ( !xrtValueArrayAppendNew(array, item) ) {\n"
        "        xrtValueRelease(item);\n"
        "        return false;\n"
        "    }\n"
        "    return true;\n"
        "}\n\n"

        "int xl6_xrt_string_compare(const char* left, const char* right, bool ignoreCase)\n"
        "{\n"
        "    xstrview leftView = xrtStrView(left);\n"
        "    xstrview rightView = xrtStrView(right);\n\n"
        "    return ignoreCase ? xrtStrCaseCompare(leftView, rightView) : xrtStrCompare(leftView, rightView);\n"
        "}\n\n"

        "size_t xl6_xrt_string_byte_len(const char* text)\n"
        "{\n"
        "    return xrtStrView(text).Size;\n"
        "}\n\n"

        "size_t xl6_xrt_string_char_len(const char* text)\n"
        "{\n"
        "    return xrtUtf8Count(xrtStrView(text));\n"
        "}\n\n"

        "bool xl6_xrt_string_contains(const char* text, const char* part, bool ignoreCase)\n"
        "{\n"
        "    xstrview textView = xrtStrView(text);\n"
        "    xstrview partView = xrtStrView(part);\n\n"
        "    return ignoreCase ? xrtStrCaseContains(textView, partView) : xrtStrContains(textView, partView);\n"
        "}\n\n"

        "int64_t xl6_xrt_string_index_of(const char* text, const char* part, bool ignoreCase)\n"
        "{\n"
        "    size_t index = ignoreCase\n"
        "        ? xrtUtf8CaseFind(xrtStrView(text), xrtStrView(part), 0)\n"
        "        : xrtUtf8Find(xrtStrView(text), xrtStrView(part), 0);\n\n"
        "    return index == XL6_XRT_NPOS ? -1 : (int64_t)index;\n"
        "}\n\n"

        "int64_t xl6_xrt_string_last_index_of(const char* text, const char* part, bool ignoreCase)\n"
        "{\n"
        "    size_t index = ignoreCase\n"
        "        ? xrtUtf8CaseRFind(xrtStrView(text), xrtStrView(part))\n"
        "        : xrtUtf8RFind(xrtStrView(text), xrtStrView(part));\n\n"
        "    return index == XL6_XRT_NPOS ? -1 : (int64_t)index;\n"
        "}\n\n"

        "int64_t xl6_xrt_string_count(const char* text, const char* part, bool ignoreCase)\n"
        "{\n"
        "    size_t count = ignoreCase\n"
        "        ? xrtStrCaseCount(xrtStrView(text), xrtStrView(part))\n"
        "        : xrtStrCount(xrtStrView(text), xrtStrView(part));\n\n"
        "    return count > INT64_MAX ? INT64_MAX : (int64_t)count;\n"
        "}\n\n"

        "bool xl6_xrt_string_has_any(const char* text, const char* chars)\n"
        "{\n"
        "    return xrtUtf8ContainsAny(xrtStrView(text), xrtStrView(chars));\n"
        "}\n\n"

        "bool xl6_xrt_string_like(const char* text, const char* pattern, bool ignoreCase)\n"
        "{\n"
        "    return xrtStrGlob(xrtStrView(text), xrtStrView(pattern), ignoreCase ? 1u : 0u);\n"
        "}\n\n"

        "bool xl6_xrt_string_approx(const char* left, const char* right)\n"
        "{\n"
        "    return xrtUtf8Similarity(xrtStrView(left), xrtStrView(right)) >= 0.95;\n"
        "}\n\n"

        "double xl6_xrt_string_similarity(const char* left, const char* right)\n"
        "{\n"
        "    return xrtUtf8Similarity(xrtStrView(left), xrtStrView(right));\n"
        "}\n\n"

        "bool xl6_xrt_string_is_utf8(const char* text)\n"
        "{\n"
        "    return xrtUtf8Valid(xrtStrView(text), 0);\n"
        "}\n\n"

        "void* xl6_xrt_string_int_format(int64_t value, const char* format)\n"
        "{\n"
        "    return xrtIntFormat(value, xrtStrView(format));\n"
        "}\n\n"

        "void* xl6_xrt_string_uint_format(uint64_t value, const char* format)\n"
        "{\n"
        "    return xrtUIntFormat(value, xrtStrView(format));\n"
        "}\n\n"

        "void* xl6_xrt_string_num_format(double value, const char* format)\n"
        "{\n"
        "    return xrtNumFormat(value, xrtStrView(format));\n"
        "}\n\n"

        "void* xl6_xrt_string_lower(const char* text)\n"
        "{\n"
        "    return xrtStrLower(xrtStrView(text));\n"
        "}\n\n"

        "void* xl6_xrt_string_upper(const char* text)\n"
        "{\n"
        "    return xrtStrUpper(xrtStrView(text));\n"
        "}\n\n"

        "static void* xl6_xrt_string_trim_impl(const char* text, const char* chars, int side)\n"
        "{\n"
        "    xstrview textView = xrtStrView(text);\n"
        "    xstrview charsView = xrtStrView(chars);\n"
        "    xstrview result;\n"
        "    bool ok = true;\n\n"
        "    if ( charsView.Size == 0 ) {\n"
        "        result = side < 0 ? xrtStrTrimLeft(textView) : (side > 0 ? xrtStrTrimRight(textView) : xrtStrTrim(textView));\n"
        "    } else if ( side < 0 ) {\n"
        "        ok = xrtUtf8TrimLeftSet(textView, charsView, &result);\n"
        "    } else if ( side > 0 ) {\n"
        "        ok = xrtUtf8TrimRightSet(textView, charsView, &result);\n"
        "    } else {\n"
        "        ok = xrtUtf8TrimSet(textView, charsView, &result);\n"
        "    }\n"
        "    return ok ? xl6_xrt_string_copy_view(result) : 0;\n"
        "}\n\n"

        "void* xl6_xrt_string_trim(const char* text, const char* chars)\n"
        "{\n"
        "    return xl6_xrt_string_trim_impl(text, chars, 0);\n"
        "}\n\n"

        "void* xl6_xrt_string_ltrim(const char* text, const char* chars)\n"
        "{\n"
        "    return xl6_xrt_string_trim_impl(text, chars, -1);\n"
        "}\n\n"

        "void* xl6_xrt_string_rtrim(const char* text, const char* chars)\n"
        "{\n"
        "    return xl6_xrt_string_trim_impl(text, chars, 1);\n"
        "}\n\n"

        "void* xl6_xrt_string_filter(const char* text, const char* chars)\n"
        "{\n"
        "    return xrtUtf8Filter(xrtStrView(text), xrtStrView(chars));\n"
        "}\n\n"

        "void* xl6_xrt_string_replace(const char* text, const char* oldText, const char* newText)\n"
        "{\n"
        "    return xrtStrReplace(xrtStrView(text), xrtStrView(oldText), xrtStrView(newText));\n"
        "}\n\n"

        "void* xl6_xrt_string_slice(const char* text, int64_t start, int64_t count)\n"
        "{\n"
        "    return xrtUtf8Substr(xrtStrView(text), start, count);\n"
        "}\n\n"

        "void* xl6_xrt_string_left(const char* text, int64_t count)\n"
        "{\n"
        "    return count > 0 ? xrtUtf8Substr(xrtStrView(text), 0, count) : xrtStrDup(\"\");\n"
        "}\n\n"

        "void* xl6_xrt_string_right(const char* text, int64_t count)\n"
        "{\n"
        "    return count > 0 ? xrtUtf8Substr(xrtStrView(text), -count, count) : xrtStrDup(\"\");\n"
        "}\n\n"

        "void* xl6_xrt_string_char_at(const char* text, int64_t index)\n"
        "{\n"
        "    return xrtUtf8Substr(xrtStrView(text), index, 1);\n"
        "}\n\n"

        "int xl6_xrt_string_byte_at(const char* text, int64_t index)\n"
        "{\n"
        "    xstrview view = xrtStrView(text);\n"
        "    int64_t position = index < 0 ? (int64_t)view.Size + index : index;\n\n"
        "    if ( position < 0 || (uint64_t)position >= (uint64_t)view.Size ) {\n"
        "        return -1;\n"
        "    }\n"
        "    return (int)(unsigned char)view.Data[position];\n"
        "}\n\n"

        "void* xl6_xrt_string_repeat(const char* text, int64_t count)\n"
        "{\n"
        "    return count > 0 ? xrtStrRepeat(xrtStrView(text), (size_t)count) : xrtStrDup(\"\");\n"
        "}\n\n"

        "bool xl6_xrt_string_is_empty(const char* text)\n"
        "{\n"
        "    return xrtStrEmpty(xrtStrView(text));\n"
        "}\n\n"

        "bool xl6_xrt_string_is_blank(const char* text)\n"
        "{\n"
        "    return xrtStrBlank(xrtStrView(text));\n"
        "}\n\n"

        "void* xl6_xrt_string_remove(const char* text, const char* part, bool ignoreCase)\n"
        "{\n"
        "    xstrview textView = xrtStrView(text);\n"
        "    xstrview partView = xrtStrView(part);\n"
        "    xstrview empty = { \"\", 0 };\n"
        "    size_t count;\n"
        "    size_t read = 0;\n"
        "    size_t write = 0;\n"
        "    char* result;\n\n"
        "    if ( !ignoreCase ) {\n"
        "        return xrtStrReplace(textView, partView, empty);\n"
        "    }\n"
        "    if ( partView.Size == 0 ) {\n"
        "        return xl6_xrt_string_copy_view(textView);\n"
        "    }\n"
        "    count = xrtStrCaseCount(textView, partView);\n"
        "    if ( count == 0 ) {\n"
        "        return xl6_xrt_string_copy_view(textView);\n"
        "    }\n"
        "    result = (char*)xrtMalloc(textView.Size - (count * partView.Size) + 1);\n"
        "    if ( result == 0 ) {\n"
        "        return 0;\n"
        "    }\n"
        "    while ( read < textView.Size ) {\n"
        "        size_t found = xrtUtf8CaseFind(xrtStrViewN(textView.Data + read, textView.Size - read), partView, 0);\n"
        "        size_t foundByte;\n\n"
        "        if ( found == XL6_XRT_NPOS ) {\n"
        "            size_t tail = textView.Size - read;\n"
        "            if ( tail > 0 ) { memcpy(result + write, textView.Data + read, tail); write += tail; }\n"
        "            break;\n"
        "        }\n"
        "        foundByte = read;\n"
        "        while ( found > 0 ) {\n"
        "            size_t step = 0;\n"
        "            unsigned int scalar = 0;\n"
        "            xutfstatus status = xrtUtf8Decode(xrtStrViewN(textView.Data + foundByte, textView.Size - foundByte), &scalar, &step);\n"
        "            if ( status != XUTF_OK || step == 0 ) { step = 1; }\n"
        "            foundByte += step;\n"
        "            found--;\n"
        "        }\n"
        "        if ( foundByte > read ) { memcpy(result + write, textView.Data + read, foundByte - read); write += foundByte - read; }\n"
        "        read = foundByte + partView.Size;\n"
        "    }\n"
        "    result[write] = '\\0';\n"
        "    return result;\n"
        "}\n\n"

        "void* xl6_xrt_string_remove_at(const char* text, int64_t start, int64_t count)\n"
        "{\n"
        "    return xrtUtf8Remove(xrtStrView(text), start, count);\n"
        "}\n\n"

        "void* xl6_xrt_string_insert(const char* text, int64_t start, const char* part)\n"
        "{\n"
        "    return xrtUtf8Insert(xrtStrView(text), start, xrtStrView(part));\n"
        "}\n\n"

        "void* xl6_xrt_string_pad_left(const char* text, int64_t width, const char* pad)\n"
        "{\n"
        "    return width > 0 ? xrtUtf8PadLeft(xrtStrView(text), (size_t)width, xrtStrView(pad)) : xrtStrDup(text);\n"
        "}\n\n"

        "void* xl6_xrt_string_pad_right(const char* text, int64_t width, const char* pad)\n"
        "{\n"
        "    return width > 0 ? xrtUtf8PadRight(xrtStrView(text), (size_t)width, xrtStrView(pad)) : xrtStrDup(text);\n"
        "}\n\n"

        "void* xl6_xrt_string_pad_center(const char* text, int64_t width, const char* pad)\n"
        "{\n"
        "    return width > 0 ? xrtUtf8PadCenter(xrtStrView(text), (size_t)width, xrtStrView(pad)) : xrtStrDup(text);\n"
        "}\n\n"

        "void* xl6_xrt_string_reverse(const char* text)\n"
        "{\n"
        "    return xrtUtf8Reverse(xrtStrView(text));\n"
        "}\n\n"

        "xvalue* xl6_xrt_string_split(const char* text, const char* sep)\n"
        "{\n"
        "    xvalue* result = xrtValueArray();\n"
        "    xstrlist* parts;\n"
        "    size_t i;\n\n"
        "    if ( result == 0 ) {\n"
        "        return 0;\n"
        "    }\n"
        "    parts = xrtStrSplit(xrtStrView(text), xrtStrView(sep));\n"
        "    if ( parts == 0 ) {\n"
        "        xrtValueRelease(result);\n"
        "        return 0;\n"
        "    }\n"
        "    for ( i = 0; i < parts->Count; ++i ) {\n"
        "        if ( !xl6_xrt_string_array_append(result, parts->Items[i]) ) {\n"
        "            xrtStrListFree(parts);\n"
        "            xrtValueRelease(result);\n"
        "            return 0;\n"
        "        }\n"
        "    }\n"
        "    xrtStrListFree(parts);\n"
        "    return result;\n"
        "}\n\n"

        "xvalue* xl6_xrt_string_chars(const char* text)\n"
        "{\n"
        "    xstrview view = xrtStrView(text);\n"
        "    xvalue* result = xrtValueArray();\n"
        "    size_t position = 0;\n\n"
        "    if ( result == 0 ) {\n"
        "        return 0;\n"
        "    }\n"
        "    while ( position < view.Size ) {\n"
        "        size_t read = 0;\n"
        "        unsigned int scalar = 0;\n"
        "        xutfstatus status = xrtUtf8Decode(xrtStrViewN(view.Data + position, view.Size - position), &scalar, &read);\n\n"
        "        if ( status != XUTF_OK || read == 0 ) { read = 1; }\n"
        "        if ( !xl6_xrt_string_array_append(result, xrtStrViewN(view.Data + position, read)) ) {\n"
        "            xrtValueRelease(result);\n"
        "            return 0;\n"
        "        }\n"
        "        position += read;\n"
        "    }\n"
        "    return result;\n"
        "}\n\n"

        "xvalue* xl6_xrt_string_bytes(const char* text)\n"
        "{\n"
        "    xstrview view = xrtStrView(text);\n"
        "    xvalue* result = xrtValueArray();\n"
        "    size_t i;\n\n"
        "    if ( result == 0 ) {\n"
        "        return 0;\n"
        "    }\n"
        "    for ( i = 0; i < view.Size; ++i ) {\n"
        "        xvalue* item = xrtValueInt((int64_t)(unsigned char)view.Data[i]);\n\n"
        "        if ( item == 0 || !xrtValueArrayAppendNew(result, item) ) {\n"
        "            if ( item != 0 ) { xrtValueRelease(item); }\n"
        "            xrtValueRelease(result);\n"
        "            return 0;\n"
        "        }\n"
        "    }\n"
        "    return result;\n"
        "}\n\n"

        "void* xl6_xrt_string_join(xvalue* values, const char* sep)\n"
        "{\n"
        "    size_t count = values != 0 ? xrtValueCount(values) : 0;\n"
        "    xstrview* texts;\n"
        "    char* result;\n"
        "    size_t i;\n\n"
        "    if ( count == 0 ) {\n"
        "        return xrtStrDup(\"\");\n"
        "    }\n"
        "    texts = (xstrview*)xrtMalloc(sizeof(xstrview) * count);\n"
        "    if ( texts == 0 ) {\n"
        "        return 0;\n"
        "    }\n"
        "    for ( i = 0; i < count; ++i ) {\n"
        "        texts[i] = xrtStrView(xl6_xrt_value_to_string(xrtValueArrayGet(values, i)));\n"
        "    }\n"
        "    result = xrtStrJoin(xrtStrView(sep), texts, count);\n"
        "    xrtFree(texts);\n"
        "    return result;\n"
        "}\n\n"

        "xvalue* xl6_xrt_string_split_lines(const char* text)\n"
        "{\n"
        "    xvalue* result = xrtValueArray();\n"
        "    xstrlist* lines;\n"
        "    size_t i;\n\n"
        "    if ( result == 0 ) {\n"
        "        return 0;\n"
        "    }\n"
        "    lines = xrtStrSplitLines(xrtStrView(text));\n"
        "    if ( lines == 0 ) {\n"
        "        xrtValueRelease(result);\n"
        "        return 0;\n"
        "    }\n"
        "    for ( i = 0; i < lines->Count; ++i ) {\n"
        "        if ( !xl6_xrt_string_array_append(result, lines->Items[i]) ) {\n"
        "            xrtStrListFree(lines);\n"
        "            xrtValueRelease(result);\n"
        "            return 0;\n"
        "        }\n"
        "    }\n"
        "    xrtStrListFree(lines);\n"
        "    return result;\n"
        "}\n\n"

        "#undef XL6_XRT_NPOS\n"
        "#endif\n\n",
        out);
}
