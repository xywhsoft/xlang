static void xl6CgenEmitStdStringRuntime(XL6_Output* out)
{
    if ( out == NULL ) {
        return;
    }

    xl6OutputPuts("#ifndef XL6_STD_STRING_RUNTIME\n", out);
    xl6OutputPuts("#define XL6_STD_STRING_RUNTIME\n", out);
    xl6OutputPuts("#ifndef XL6_XVALUE_TYPEDEF\n", out);
    xl6OutputPuts("#define XL6_XVALUE_TYPEDEF\n", out);
    xl6OutputPuts("typedef struct xvalue_struct* xvalue;\n", out);
    xl6OutputPuts("#endif\n", out);
    xl6OutputPuts("void xrtFree(void* p);\n", out);
    xl6OutputPuts("void* xrtMalloc(size_t iSize);\n", out);
    xl6OutputPuts("char* xrtCopyStr(const char* sText, size_t iSize);\n", out);
    xl6OutputPuts("size_t xrtStrUtf8CharSize(const char* sText, size_t iSize, size_t iPos);\n", out);
    xl6OutputPuts("char** xrtSplit(const char* sText, size_t iSize, const char* sSepText, size_t iSepSize, bool bSrcRevise, size_t* iRetSize);\n", out);
    xl6OutputPuts("char** xrtStrSplitLines(const char* sText, size_t iSize, size_t* iRetSize);\n", out);
    xl6OutputPuts("xvalue xvoCreateArray(void);\n", out);
    xl6OutputPuts("xvalue xvoCreateInt(long long iVal);\n", out);
    xl6OutputPuts("xvalue xvoCreateText(void* sVal, unsigned int iSize, bool bColloc);\n", out);
    xl6OutputPuts("bool xvoArrayAppendValue(xvalue pArr, xvalue pVal, bool bColloc);\n", out);
    xl6OutputPuts("unsigned int xvoArrayItemCount(xvalue pArr);\n", out);
    xl6OutputPuts("xvalue xvoArrayGetValue(xvalue pArr, unsigned int index);\n", out);
    xl6OutputPuts("unsigned char* xvoToString(xvalue pVal, unsigned int* pSize);\n", out);
    xl6OutputPuts("void xvoUnref(xvalue pVal);\n\n", out);

    xl6OutputPuts("xvalue xl6_xrt_string_split(const char* text, const char* sep)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    size_t count = 0;\n", out);
    xl6OutputPuts("    size_t i;\n", out);
    xl6OutputPuts("    char** parts;\n", out);
    xl6OutputPuts("    xvalue result = xvoCreateArray();\n\n", out);
    xl6OutputPuts("    if ( result == 0 ) {\n", out);
    xl6OutputPuts("        return 0;\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    parts = xrtSplit(text, 0, sep, 0, false, &count);\n", out);
    xl6OutputPuts("    if ( parts == 0 ) {\n", out);
    xl6OutputPuts("        return result;\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    if ( count == 0 ) {\n", out);
    xl6OutputPuts("        xrtFree(parts);\n", out);
    xl6OutputPuts("        return result;\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    for ( i = 0; i < count; ++i ) {\n", out);
    xl6OutputPuts("        xvalue item = xvoCreateText(parts[i], 0, false);\n", out);
    xl6OutputPuts("        if ( item != 0 && !xvoArrayAppendValue(result, item, true) ) {\n", out);
    xl6OutputPuts("            xvoUnref(item);\n", out);
    xl6OutputPuts("        }\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    xrtFree(parts);\n", out);
    xl6OutputPuts("    return result;\n", out);
    xl6OutputPuts("}\n\n", out);

    xl6OutputPuts("xvalue xl6_xrt_string_chars(const char* text)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    size_t len = text != 0 ? strlen(text) : 0;\n", out);
    xl6OutputPuts("    size_t pos = 0;\n", out);
    xl6OutputPuts("    xvalue result = xvoCreateArray();\n\n", out);
    xl6OutputPuts("    if ( result == 0 ) {\n", out);
    xl6OutputPuts("        return 0;\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    while ( pos < len ) {\n", out);
    xl6OutputPuts("        size_t charLen = xrtStrUtf8CharSize(text, len, pos);\n", out);
    xl6OutputPuts("        char* copy;\n", out);
    xl6OutputPuts("        xvalue item;\n", out);
    xl6OutputPuts("        if ( charLen == 0 ) {\n", out);
    xl6OutputPuts("            break;\n", out);
    xl6OutputPuts("        }\n", out);
    xl6OutputPuts("        copy = xrtCopyStr(text + pos, charLen);\n", out);
    xl6OutputPuts("        item = xvoCreateText(copy, (unsigned int)charLen, true);\n", out);
    xl6OutputPuts("        if ( item == 0 ) {\n", out);
    xl6OutputPuts("            xrtFree(copy);\n", out);
    xl6OutputPuts("        } else if ( !xvoArrayAppendValue(result, item, true) ) {\n", out);
    xl6OutputPuts("            xvoUnref(item);\n", out);
    xl6OutputPuts("        }\n", out);
    xl6OutputPuts("        pos += charLen;\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    return result;\n", out);
    xl6OutputPuts("}\n\n", out);

    xl6OutputPuts("xvalue xl6_xrt_string_bytes(const char* text)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    size_t len = text != 0 ? strlen(text) : 0;\n", out);
    xl6OutputPuts("    size_t i;\n", out);
    xl6OutputPuts("    xvalue result = xvoCreateArray();\n\n", out);
    xl6OutputPuts("    if ( result == 0 ) {\n", out);
    xl6OutputPuts("        return 0;\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    for ( i = 0; i < len; ++i ) {\n", out);
    xl6OutputPuts("        xvalue item = xvoCreateInt((long long)(unsigned char)text[i]);\n", out);
    xl6OutputPuts("        if ( item != 0 && !xvoArrayAppendValue(result, item, true) ) {\n", out);
    xl6OutputPuts("            xvoUnref(item);\n", out);
    xl6OutputPuts("        }\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    return result;\n", out);
    xl6OutputPuts("}\n\n", out);

    xl6OutputPuts("void* xl6_xrt_string_join(xvalue values, const char* sep)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    unsigned int count = values != 0 ? xvoArrayItemCount(values) : 0;\n", out);
    xl6OutputPuts("    size_t sepLen = sep != 0 ? strlen(sep) : 0;\n", out);
    xl6OutputPuts("    char** texts;\n", out);
    xl6OutputPuts("    unsigned int* lens;\n", out);
    xl6OutputPuts("    size_t total = 0;\n", out);
    xl6OutputPuts("    size_t pos = 0;\n", out);
    xl6OutputPuts("    unsigned int i;\n", out);
    xl6OutputPuts("    char* result;\n\n", out);
    xl6OutputPuts("    if ( count == 0 ) {\n", out);
    xl6OutputPuts("        result = (char*)xrtMalloc(1);\n", out);
    xl6OutputPuts("        if ( result != 0 ) { result[0] = '\\0'; }\n", out);
    xl6OutputPuts("        return result;\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    texts = (char**)xrtMalloc(sizeof(char*) * count);\n", out);
    xl6OutputPuts("    lens = (unsigned int*)xrtMalloc(sizeof(unsigned int) * count);\n", out);
    xl6OutputPuts("    if ( texts == 0 || lens == 0 ) {\n", out);
    xl6OutputPuts("        xrtFree(texts);\n", out);
    xl6OutputPuts("        xrtFree(lens);\n", out);
    xl6OutputPuts("        return 0;\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    for ( i = 0; i < count; ++i ) {\n", out);
    xl6OutputPuts("        unsigned int itemLen = 0;\n", out);
    xl6OutputPuts("        texts[i] = (char*)xvoToString(xvoArrayGetValue(values, i), &itemLen);\n", out);
    xl6OutputPuts("        if ( texts[i] == 0 ) {\n", out);
    xl6OutputPuts("            texts[i] = (char*)xrtMalloc(1);\n", out);
    xl6OutputPuts("            if ( texts[i] != 0 ) { texts[i][0] = '\\0'; }\n", out);
    xl6OutputPuts("            itemLen = 0;\n", out);
    xl6OutputPuts("        }\n", out);
    xl6OutputPuts("        lens[i] = itemLen;\n", out);
    xl6OutputPuts("        total += (size_t)itemLen;\n", out);
    xl6OutputPuts("        if ( i > 0 ) { total += sepLen; }\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    result = (char*)xrtMalloc(total + 1);\n", out);
    xl6OutputPuts("    if ( result == 0 ) {\n", out);
    xl6OutputPuts("        for ( i = 0; i < count; ++i ) { xrtFree(texts[i]); }\n", out);
    xl6OutputPuts("        xrtFree(texts);\n", out);
    xl6OutputPuts("        xrtFree(lens);\n", out);
    xl6OutputPuts("        return 0;\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    for ( i = 0; i < count; ++i ) {\n", out);
    xl6OutputPuts("        if ( i > 0 && sepLen > 0 ) {\n", out);
    xl6OutputPuts("            memcpy(result + pos, sep, sepLen);\n", out);
    xl6OutputPuts("            pos += sepLen;\n", out);
    xl6OutputPuts("        }\n", out);
    xl6OutputPuts("        if ( lens[i] > 0 ) {\n", out);
    xl6OutputPuts("            memcpy(result + pos, texts[i], lens[i]);\n", out);
    xl6OutputPuts("            pos += lens[i];\n", out);
    xl6OutputPuts("        }\n", out);
    xl6OutputPuts("        xrtFree(texts[i]);\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    result[pos] = '\\0';\n", out);
    xl6OutputPuts("    xrtFree(texts);\n", out);
    xl6OutputPuts("    xrtFree(lens);\n", out);
    xl6OutputPuts("    return result;\n", out);
    xl6OutputPuts("}\n\n", out);

    xl6OutputPuts("xvalue xl6_xrt_string_split_lines(const char* text)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    size_t count = 0;\n", out);
    xl6OutputPuts("    size_t i;\n", out);
    xl6OutputPuts("    char** parts;\n", out);
    xl6OutputPuts("    xvalue result = xvoCreateArray();\n\n", out);
    xl6OutputPuts("    if ( result == 0 ) {\n", out);
    xl6OutputPuts("        return 0;\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    parts = xrtStrSplitLines(text, 0, &count);\n", out);
    xl6OutputPuts("    if ( parts == 0 ) {\n", out);
    xl6OutputPuts("        return result;\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    for ( i = 0; i < count; ++i ) {\n", out);
    xl6OutputPuts("        xvalue item = xvoCreateText(parts[i], 0, false);\n", out);
    xl6OutputPuts("        if ( item != 0 && !xvoArrayAppendValue(result, item, true) ) {\n", out);
    xl6OutputPuts("            xvoUnref(item);\n", out);
    xl6OutputPuts("        }\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    xrtFree(parts);\n", out);
    xl6OutputPuts("    return result;\n", out);
    xl6OutputPuts("}\n\n", out);
    xl6OutputPuts("#endif\n\n", out);
}
