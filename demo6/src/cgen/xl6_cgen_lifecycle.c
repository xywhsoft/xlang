#include "src/cgen/xl6_cgen_lifecycle.h"

void xl6CgenHeaderLifecycleDecls(XL6_Output* out)
{
    xl6OutputPuts("#ifndef XL6_INIT_OPTIONS_DEFINED\n", out);
    xl6OutputPuts("#define XL6_INIT_OPTIONS_DEFINED\n", out);
    xl6OutputPuts("#ifndef XL_INIT_OPTIONS_VERSION\n", out);
    xl6OutputPuts("#define XL_INIT_OPTIONS_VERSION 1u\n", out);
    xl6OutputPuts("#endif\n", out);
    xl6OutputPuts("typedef struct XL_InitOptions {\n", out);
    xl6OutputPuts("    unsigned int size;\n", out);
    xl6OutputPuts("    unsigned int version;\n", out);
    xl6OutputPuts("    int argc;\n", out);
    xl6OutputPuts("    char** argv;\n", out);
    xl6OutputPuts("    void* reserved;\n", out);
    xl6OutputPuts("} XL_InitOptions;\n", out);
    xl6OutputPuts("#endif\n\n", out);
    xl6OutputPuts("XL6_C_API XL_InitOptions xlInitOptions(int argc, char** argv);\n", out);
	xl6OutputPuts("XL6_C_API int xlInit(const XL_InitOptions* options);\n", out);
	xl6OutputPuts("XL6_C_API void xlUnit(void);\n", out);
	xl6OutputPuts("XL6_C_API void xlDllAttach(void* module);\n", out);
	xl6OutputPuts("XL6_C_API void xlDllDetach(int processTerminating);\n", out);
	xl6OutputPuts("XL6_C_API xvalue* xlValueRetain(const xvalue* value);\n", out);
	xl6OutputPuts("XL6_C_API void xlValueRelease(xvalue* value);\n", out);
	xl6OutputPuts("XL6_C_API xvalue* xlValueClone(const xvalue* value, bool deep);\n", out);
	xl6OutputPuts("XL6_C_API bool xlValueIsNull(const xvalue* value);\n", out);
	xl6OutputPuts("XL6_C_API void* xlValueData(xvalue* value);\n\n", out);
}

void xl6CgenEmitLifecycleRuntime(XL6_Output* out)
{
    xl6OutputPuts("#ifndef XL6_INIT_OPTIONS_DEFINED\n", out);
    xl6OutputPuts("#define XL6_INIT_OPTIONS_DEFINED\n", out);
    xl6OutputPuts("#ifndef XL_INIT_OPTIONS_VERSION\n", out);
    xl6OutputPuts("#define XL_INIT_OPTIONS_VERSION 1u\n", out);
    xl6OutputPuts("#endif\n", out);
    xl6OutputPuts("typedef struct XL_InitOptions {\n", out);
    xl6OutputPuts("    unsigned int size;\n", out);
    xl6OutputPuts("    unsigned int version;\n", out);
    xl6OutputPuts("    int argc;\n", out);
    xl6OutputPuts("    char** argv;\n", out);
    xl6OutputPuts("    void* reserved;\n", out);
    xl6OutputPuts("} XL_InitOptions;\n", out);
    xl6OutputPuts("#endif\n\n", out);
	xl6OutputPuts("static int xl__runtime_init_count = 0;\n\n", out);
    xl6OutputPuts("XL6_C_API XL_InitOptions xlInitOptions(int argc, char** argv)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    XL_InitOptions options;\n", out);
    xl6OutputPuts("    options.size = (unsigned int)sizeof(options);\n", out);
    xl6OutputPuts("    options.version = XL_INIT_OPTIONS_VERSION;\n", out);
    xl6OutputPuts("    options.argc = argc;\n", out);
    xl6OutputPuts("    options.argv = argv;\n", out);
    xl6OutputPuts("    options.reserved = 0;\n", out);
    xl6OutputPuts("    return options;\n", out);
    xl6OutputPuts("}\n\n", out);
    xl6OutputPuts("XL6_C_API int xlInit(const XL_InitOptions* options)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    if ( options != 0 ) {\n", out);
    xl6OutputPuts("        if ( options->size < (unsigned int)sizeof(XL_InitOptions) ) {\n", out);
    xl6OutputPuts("            return 0;\n", out);
    xl6OutputPuts("        }\n", out);
    xl6OutputPuts("        if ( options->version != XL_INIT_OPTIONS_VERSION ) {\n", out);
    xl6OutputPuts("            return 0;\n", out);
    xl6OutputPuts("        }\n", out);
    xl6OutputPuts("    }\n", out);
	xl6OutputPuts("    xl__runtime_init_count += 1;\n", out);
    xl6OutputPuts("    return 1;\n", out);
    xl6OutputPuts("}\n\n", out);
    xl6OutputPuts("XL6_C_API void xlUnit(void)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    if ( xl__runtime_init_count <= 0 ) {\n", out);
    xl6OutputPuts("        return;\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    xl__runtime_init_count -= 1;\n", out);
	xl6OutputPuts("}\n\n", out);
    xl6OutputPuts("XL6_C_API void xlDllAttach(void* module)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    (void)module;\n", out);
    xl6OutputPuts("}\n\n", out);
	xl6OutputPuts("XL6_C_API void xlDllDetach(int processTerminating)\n", out);
	xl6OutputPuts("{\n", out);
	xl6OutputPuts("    (void)processTerminating;\n", out);
	xl6OutputPuts("}\n\n", out);
	xl6OutputPuts("XL6_C_API xvalue* xlValueRetain(const xvalue* value)\n", out);
	xl6OutputPuts("{\n", out);
	xl6OutputPuts("    return xrtValueRetain(value);\n", out);
	xl6OutputPuts("}\n\n", out);
	xl6OutputPuts("XL6_C_API void xlValueRelease(xvalue* value)\n", out);
	xl6OutputPuts("{\n", out);
	xl6OutputPuts("    xrtValueRelease(value);\n", out);
	xl6OutputPuts("}\n\n", out);
	xl6OutputPuts("XL6_C_API xvalue* xlValueClone(const xvalue* value, bool deep)\n", out);
	xl6OutputPuts("{\n", out);
	xl6OutputPuts("    xvalue* result = xl6ValueRecordClone(value, deep);\n\n", out);
	xl6OutputPuts("    return result != 0 ? result : xrtValueClone(value);\n", out);
	xl6OutputPuts("}\n\n", out);
	xl6OutputPuts("XL6_C_API bool xlValueIsNull(const xvalue* value)\n", out);
	xl6OutputPuts("{\n", out);
	xl6OutputPuts("    return xl6_xrt_value_is_null(value);\n", out);
	xl6OutputPuts("}\n\n", out);
	xl6OutputPuts("XL6_C_API void* xlValueData(xvalue* value)\n", out);
	xl6OutputPuts("{\n", out);
	xl6OutputPuts("    void* data = xl6ValueRecordData(value);\n\n", out);
	xl6OutputPuts("    return data != 0 ? data : xl6ValueHandleData(value);\n", out);
	xl6OutputPuts("}\n\n", out);
	xl6OutputPuts("#ifdef XL6_BUILD_SHARED\n", out);
    xl6OutputPuts("#if defined(_WIN32) || defined(_WIN64)\n", out);
    xl6OutputPuts("int __stdcall DllMain(void* module, unsigned long reason, void* reserved)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    if ( reason == 1ul ) {\n", out);
    xl6OutputPuts("        xlDllAttach(module);\n", out);
    xl6OutputPuts("    } else if ( reason == 0ul ) {\n", out);
    xl6OutputPuts("        xlDllDetach(reserved != 0);\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    return 1;\n", out);
    xl6OutputPuts("}\n", out);
    xl6OutputPuts("#else\n", out);
    xl6OutputPuts("static void __attribute__((constructor)) xl__shared_attach(void)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    xlDllAttach(0);\n", out);
    xl6OutputPuts("}\n", out);
    xl6OutputPuts("static void __attribute__((destructor)) xl__shared_detach(void)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    xlDllDetach(0);\n", out);
    xl6OutputPuts("}\n", out);
    xl6OutputPuts("#endif\n", out);
    xl6OutputPuts("#endif\n\n", out);
}
