// Independent test oracle; not a package/runtime dependency.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const sha256 = data => createHash('sha256').update(data).digest('hex');
const pattern = Buffer.alloc(65537);
for (let i = 0; i < pattern.length; ++i) pattern[i] = (i * 37 + 11) & 255;
const lengths = new Set(Array.from({length: 34}, (_, i) => i));
for (const rate of [72, 104, 136, 144, 168]) {
    for (const n of [rate - 1, rate, rate + 1, rate * 2 - 1, rate * 2, rate * 2 + 1]) lengths.add(n);
}
for (const n of [65535, 65536, 65537]) lengths.add(n);
const vectors = [];
function add(shake, bits, size, output) {
    const algorithm = shake ? `shake${bits}` : `sha3-${bits}`;
    const hash = createHash(algorithm, shake ? {outputLength: output} : undefined);
    vectors.push({shake, bits, size, output, hex: hash.update(pattern.subarray(0, size)).digest('hex')});
}
for (const bits of [224, 256, 384, 512]) {
    for (const size of [...lengths].sort((a, b) => a - b)) add(false, bits, size, bits / 8);
}
for (const bits of [128, 256]) {
    for (const size of [0, 1, 135, 136, 137, 167, 168, 169, 335, 336, 337, 65537]) {
        for (const output of [0, 1, 7, 8, 31, 32, 64, 128, 129, 136, 168, 257]) add(true, bits, size, output);
    }
    add(true, bits, 65537, 1024);
}
const known = [];
for (const [name, input] of [['abc', Buffer.from('abc')], ['utf8', Buffer.from('你好\0世界')], ['million_a', Buffer.alloc(1000000, 97)]]) {
    for (const bits of [224, 256, 384, 512]) known.push({name, bits, hex:createHash(`sha3-${bits}`).update(input).digest('hex')});
}
const metadata = {oracle:'Node.js crypto / OpenSSL', node:process.version, openssl:process.versions.openssl,
    standard:'https://csrc.nist.gov/pubs/fips/202/final',
    generatorSha256:sha256(readFileSync(fileURLToPath(import.meta.url))), pattern:'(i * 37 + 11) & 255', vectors, known};
const header = '/* Generated by generate_vectors.mjs, independently using OpenSSL. */\n' +
    'static const struct { int shake, bits; size_t size, output; const char* hex; } sha3_vectors[] = {\n' +
    vectors.map(v => `    {${Number(v.shake)}, ${v.bits}, ${v.size}, ${v.output}, "${v.hex}"},`).join('\n') +
    '\n};\nstatic const struct { const char* name; int bits; const char* hex; } sha3_known[] = {\n' +
    known.map(v => `    {"${v.name}", ${v.bits}, "${v.hex}"},`).join('\n') + '\n};\n';
const hash = (algorithm, text, length) => createHash(algorithm, length === undefined ? undefined : {outputLength:length}).update(text).digest('hex');
const basic = [
    ...[224,256,384,512].map(bits => `sha3-${bits}=${hash(`sha3-${bits}`, 'abc')}`),
    `shake128=${hash('shake128', 'abc', 32)}`, `shake256=${hash('shake256', 'abc', 64)}`,
    `binary=${hash('sha3-256', '你好\0世界')}`, `stream=${hash('sha3-256', 'abc')}`,
    `branch=${hash('sha3-256', 'ax')}`, 'input=3', 'reset=true', 'empty-xof=0', 'long-xof=257', ''
].join('\n');
const files = [`file=${hash('sha3-256', 'abc')}`, 'callbacks=2', 'bytes=32', 'cancelled=true', 'callback-error=true', 'budget=true', ''].join('\n');
for (const [name, data] of [['vectors.json', JSON.stringify(metadata, null, 2) + '\n'], ['vectors.h', header],
    ['../../../examples/extlibs/sha3_basic.expected.txt', basic], ['../../../examples/extlibs/sha3.expected.txt', files]]) {
    const path = new URL(name, import.meta.url);
    if (process.argv.includes('--check')) {
        // Toolchain version is provenance, not part of the algorithm's expected result.
        if (name.endsWith('.json')) {
            const previous = JSON.parse(readFileSync(path, 'utf8'));
            if (JSON.stringify(previous.vectors) !== JSON.stringify(vectors) || JSON.stringify(previous.known) !== JSON.stringify(known) || previous.generatorSha256 !== metadata.generatorSha256) throw new Error(`${name} mismatch`);
        } else if (readFileSync(path, 'utf8') !== data) throw new Error(`${name} mismatch`);
    } else writeFileSync(path, data);
}
console.log(`sha3 independent vectors: ${vectors.length} boundary + ${known.length} known-answer records`);
