/*
	此文件保留旧版 query 语言桥接实现，等待 xhttp 语言扩展接入时迁移。
	它不属于 xlang 核心构建，也不得重新依赖裁剪后的 XRT 核心。
*/
static void xl6CgenEmitQueryRuntime(XL6_Output* out)
{
    if ( out == NULL ) {
        return;
    }

    xl6OutputPuts("#ifndef XL6_QUERY_RUNTIME\n", out);
    xl6OutputPuts("#define XL6_QUERY_RUNTIME\n", out);
    xl6OutputPuts("#include <string.h>\n", out);
    xl6OutputPuts("#ifndef XL_RUNTIME_H\n", out);
    xl6OutputPuts("void* xrtMalloc(size_t iSize);\n", out);
    xl6OutputPuts("void xrtFree(void* p);\n", out);
    xl6OutputPuts("#endif\n", out);
    xl6OutputPuts("#ifndef XL6_XVALUE_TYPEDEF\n", out);
    xl6OutputPuts("#define XL6_XVALUE_TYPEDEF\n", out);
    xl6OutputPuts("typedef struct xvalue xvalue;\n", out);
    xl6OutputPuts("#endif\n", out);
    xl6OutputPuts("#ifndef XL_RUNTIME_H\n", out);
    xl6OutputPuts("#ifndef XL6_XRT_STRVIEW_TYPEDEF\n", out);
    xl6OutputPuts("#define XL6_XRT_STRVIEW_TYPEDEF\n", out);
    xl6OutputPuts("typedef struct xstrview { const char* Data; size_t Size; } xstrview;\n", out);
    xl6OutputPuts("#endif\n", out);
    xl6OutputPuts("#endif\n", out);
    xl6OutputPuts("typedef xstrview xl6_query_view;\n", out);
    xl6OutputPuts("#ifndef XL_RUNTIME_H\n", out);
    xl6OutputPuts("typedef struct { uint32_t Flags; xl6_query_view Key; xl6_query_view Value; } xl6_query_pair;\n", out);
    xl6OutputPuts("#else\n", out);
    xl6OutputPuts("typedef xquerypair xl6_query_pair;\n", out);
    xl6OutputPuts("#endif\n", out);
    xl6OutputPuts("#define XL6_QUERY_F_HAS_VALUE 0x00000001u\n", out);
    xl6OutputPuts("#define XL6_QUERY_NEXT_ERROR (-1)\n", out);
    xl6OutputPuts("#define XL6_QUERY_NEXT_END 0\n", out);
    xl6OutputPuts("#define XL6_QUERY_NEXT_ITEM 1\n", out);
    xl6OutputPuts("#ifndef XL_RUNTIME_H\n", out);
    xl6OutputPuts("bool xrtFormEncode(const void* data, size_t size, char* output, size_t capacity, size_t* outputSize);\n", out);
    xl6OutputPuts("bool xrtFormDecode(xl6_query_view text, void* output, size_t capacity, size_t* outputSize);\n", out);
    xl6OutputPuts("void* xrtFormEncodeNew(const void* data, size_t size, size_t* outputSize);\n", out);
    xl6OutputPuts("void* xrtFormDecodeNew(xl6_query_view text, size_t* outputSize);\n\n", out);
    xl6OutputPuts("int xrtQueryNext(xl6_query_view query, size_t* offset, xl6_query_pair* pair);\n", out);
    xl6OutputPuts("bool xrtQueryCount(xl6_query_view query, size_t* count);\n", out);
    xl6OutputPuts("int xrtQueryFind(xl6_query_view query, xl6_query_view key, size_t* offset, xl6_query_pair* pair);\n", out);
    xl6OutputPuts("xvalue* xrtValueArray(void);\n", out);
    xl6OutputPuts("void xrtValueRelease(xvalue* pVal);\n", out);
    xl6OutputPuts("#endif\n\n", out);

    xl6OutputPuts("static void* xl6_query_empty_string(void)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    char* text = (char*)xrtMalloc(1);\n", out);
    xl6OutputPuts("    if ( text != 0 ) { text[0] = '\\0'; }\n", out);
    xl6OutputPuts("    return text;\n", out);
    xl6OutputPuts("}\n\n", out);

    xl6OutputPuts("static int xl6_query_mul3_add(size_t a, size_t b, size_t extra, size_t* out)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    size_t max = (size_t)-1;\n", out);
    xl6OutputPuts("    if ( out == 0 ) { return 0; }\n", out);
    xl6OutputPuts("    if ( a > (max - extra) / 3u ) { return 0; }\n", out);
    xl6OutputPuts("    *out = a * 3u + extra;\n", out);
    xl6OutputPuts("    if ( b > (max - *out) / 3u ) { return 0; }\n", out);
    xl6OutputPuts("    *out += b * 3u;\n", out);
    xl6OutputPuts("    return 1;\n", out);
    xl6OutputPuts("}\n\n", out);

    xl6OutputPuts("static xvalue* xl6_query_decode_xvalue(xl6_query_view view)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    char* decoded;\n", out);
    xl6OutputPuts("    size_t decodedSize = 0u;\n", out);
    xl6OutputPuts("    xvalue* value;\n", out);
    xl6OutputPuts("    decoded = (char*)xrtFormDecodeNew(view, &decodedSize);\n", out);
    xl6OutputPuts("    if ( decoded == 0 ) { return 0; }\n", out);
    xl6OutputPuts("    value = xl6_xrt_value_text_create(decoded, (unsigned int)decodedSize, true);\n", out);
    xl6OutputPuts("    if ( value == 0 ) { xrtFree(decoded); }\n", out);
    xl6OutputPuts("    return value;\n", out);
    xl6OutputPuts("}\n\n", out);

    xl6OutputPuts("void* xl6_xrt_query_encode(const char* text, size_t size)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    void* outText;\n", out);
    xl6OutputPuts("    size_t outLen = 0u;\n", out);
    xl6OutputPuts("    if ( text == 0 ) { text = \"\"; size = 0; }\n", out);
    xl6OutputPuts("    outText = xrtFormEncodeNew(text, size, &outLen);\n", out);
    xl6OutputPuts("    return outText != 0 ? outText : xl6_query_empty_string();\n", out);
    xl6OutputPuts("}\n\n", out);

    xl6OutputPuts("void* xl6_xrt_query_decode(const char* text, size_t size)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    void* outText;\n", out);
    xl6OutputPuts("    size_t outLen = 0u;\n", out);
    xl6OutputPuts("    if ( text == 0 ) { text = \"\"; size = 0; }\n", out);
    xl6OutputPuts("    outText = xrtFormDecodeNew((xl6_query_view){ text, size }, &outLen);\n", out);
    xl6OutputPuts("    return outText != 0 ? outText : xl6_query_empty_string();\n", out);
    xl6OutputPuts("}\n\n", out);

    xl6OutputPuts("bool xl6_xrt_query_valid(const char* text, size_t size)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    xl6_query_view query;\n", out);
    xl6OutputPuts("    xl6_query_pair pair;\n", out);
    xl6OutputPuts("    size_t offset = 0u;\n", out);
    xl6OutputPuts("    size_t decodedSize;\n", out);
    xl6OutputPuts("    int next;\n", out);
    xl6OutputPuts("    if ( text == 0 ) { text = \"\"; size = 0; }\n", out);
    xl6OutputPuts("    query = (xl6_query_view){ text, size };\n", out);
    xl6OutputPuts("    while ( (next = xrtQueryNext(query, &offset, &pair)) == XL6_QUERY_NEXT_ITEM ) {\n", out);
    xl6OutputPuts("        if ( pair.Key.Size == 0u || !xrtFormDecode(pair.Key, 0, 0u, &decodedSize) ) { return false; }\n", out);
    xl6OutputPuts("        if ( (pair.Flags & XL6_QUERY_F_HAS_VALUE) != 0u && !xrtFormDecode(pair.Value, 0, 0u, &decodedSize) ) { return false; }\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    return next == XL6_QUERY_NEXT_END;\n", out);
    xl6OutputPuts("}\n\n", out);

    xl6OutputPuts("long long xl6_xrt_query_count(const char* text, size_t size)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    size_t count = 0u;\n", out);
    xl6OutputPuts("    if ( text == 0 ) { text = \"\"; size = 0; }\n", out);
    xl6OutputPuts("    return xrtQueryCount((xl6_query_view){ text, size }, &count) ? (long long)count : 0LL;\n", out);
    xl6OutputPuts("}\n\n", out);

    xl6OutputPuts("xvalue* xl6_xrt_query_find(const char* text, size_t size, const char* key, size_t keySize)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    xl6_query_pair pair;\n", out);
    xl6OutputPuts("    char* encodedKey;\n", out);
    xl6OutputPuts("    size_t encodedSize = 0u;\n", out);
    xl6OutputPuts("    size_t offset = 0u;\n", out);
    xl6OutputPuts("    xvalue* result;\n", out);
    xl6OutputPuts("    if ( text == 0 ) { text = \"\"; size = 0; }\n", out);
    xl6OutputPuts("    if ( key == 0 ) { key = \"\"; keySize = 0; }\n", out);
    xl6OutputPuts("    encodedKey = (char*)xrtFormEncodeNew(key, keySize, &encodedSize);\n", out);
    xl6OutputPuts("    if ( encodedKey == 0 ) { return xrtValueNull(); }\n", out);
    xl6OutputPuts("    if ( xrtQueryFind((xl6_query_view){ text, size }, (xl6_query_view){ encodedKey, encodedSize }, &offset, &pair) != XL6_QUERY_NEXT_ITEM ||\n", out);
    xl6OutputPuts("         (pair.Flags & XL6_QUERY_F_HAS_VALUE) == 0u ) {\n", out);
    xl6OutputPuts("        xrtFree(encodedKey);\n", out);
    xl6OutputPuts("        return xrtValueNull();\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    xrtFree(encodedKey);\n", out);
    xl6OutputPuts("    result = xl6_query_decode_xvalue(pair.Value);\n", out);
    xl6OutputPuts("    return result != 0 ? result : xrtValueNull();\n", out);
    xl6OutputPuts("}\n\n", out);

    xl6OutputPuts("static int xl6_query_array_take(xvalue* array, xvalue* item)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    if ( item == 0 ) { return 0; }\n", out);
    xl6OutputPuts("    if ( !xl6_xrt_value_array_append(array, item, true) ) { xrtValueRelease(item); return 0; }\n", out);
    xl6OutputPuts("    return 1;\n", out);
    xl6OutputPuts("}\n\n", out);

    xl6OutputPuts("xvalue* xl6_xrt_query_items(const char* text, size_t size)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    xvalue* result = xrtValueArray();\n", out);
    xl6OutputPuts("    size_t offset = 0u;\n", out);
    xl6OutputPuts("    xl6_query_pair pair;\n", out);
    xl6OutputPuts("    int next;\n", out);
    xl6OutputPuts("    if ( result == 0 ) { return 0; }\n", out);
    xl6OutputPuts("    if ( text == 0 ) { text = \"\"; size = 0; }\n", out);
    xl6OutputPuts("    while ( (next = xrtQueryNext((xl6_query_view){ text, size }, &offset, &pair)) == XL6_QUERY_NEXT_ITEM ) {\n", out);
    xl6OutputPuts("        xvalue* item = xrtValueArray();\n", out);
    xl6OutputPuts("        xvalue* name;\n", out);
    xl6OutputPuts("        xvalue* value;\n", out);
    xl6OutputPuts("        xvalue* hasValue;\n", out);
    xl6OutputPuts("        if ( item == 0 ) { break; }\n", out);
    xl6OutputPuts("        name = xl6_query_decode_xvalue(pair.Key);\n", out);
    xl6OutputPuts("        if ( !xl6_query_array_take(item, name) ) { xrtValueRelease(item); break; }\n", out);
    xl6OutputPuts("        value = (pair.Flags & XL6_QUERY_F_HAS_VALUE) != 0u\n", out);
    xl6OutputPuts("            ? xl6_query_decode_xvalue(pair.Value)\n", out);
    xl6OutputPuts("            : xrtValueNull();\n", out);
    xl6OutputPuts("        if ( !xl6_query_array_take(item, value) ) { xrtValueRelease(item); break; }\n", out);
    xl6OutputPuts("        hasValue = xrtValueBool((pair.Flags & XL6_QUERY_F_HAS_VALUE) != 0u);\n", out);
    xl6OutputPuts("        if ( !xl6_query_array_take(item, hasValue) ) { xrtValueRelease(item); break; }\n", out);
    xl6OutputPuts("        if ( !xl6_query_array_take(result, item) ) { break; }\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    if ( next == XL6_QUERY_NEXT_ERROR ) { xrtValueRelease(result); return 0; }\n", out);
    xl6OutputPuts("    return result;\n", out);
    xl6OutputPuts("}\n\n", out);

    xl6OutputPuts("/* 向已有查询文本追加一个经过 form-urlencoded 编码的字段。 */\n", out);
    xl6OutputPuts("static int xl6_query_append_field(char* output, size_t capacity, size_t* offset, const char* name, size_t nameSize, const char* value, size_t valueSize, bool hasValue)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    size_t encodedSize = 0u;\n", out);
    xl6OutputPuts("    if ( output == 0 || offset == 0 || *offset >= capacity ) { return 0; }\n", out);
    xl6OutputPuts("    if ( *offset != 0u ) {\n", out);
    xl6OutputPuts("        if ( *offset + 1u >= capacity ) { return 0; }\n", out);
    xl6OutputPuts("        output[(*offset)++] = '&';\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    if ( !xrtFormEncode(name, nameSize, output + *offset, capacity - *offset, &encodedSize) ) { return 0; }\n", out);
    xl6OutputPuts("    *offset += encodedSize;\n", out);
    xl6OutputPuts("    if ( hasValue ) {\n", out);
    xl6OutputPuts("        if ( *offset + 1u >= capacity ) { return 0; }\n", out);
    xl6OutputPuts("        output[(*offset)++] = '=';\n", out);
    xl6OutputPuts("        if ( !xrtFormEncode(value, valueSize, output + *offset, capacity - *offset, &encodedSize) ) { return 0; }\n", out);
    xl6OutputPuts("        *offset += encodedSize;\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    output[*offset] = '\\0';\n", out);
    xl6OutputPuts("    return 1;\n", out);
    xl6OutputPuts("}\n\n", out);

    xl6OutputPuts("void* xl6_xrt_query_pair(const char* name, size_t nameSize, const char* value, size_t valueSize)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    char* outText;\n", out);
    xl6OutputPuts("    size_t cap;\n", out);
    xl6OutputPuts("    size_t off = 0;\n", out);
    xl6OutputPuts("    if ( name == 0 ) { name = \"\"; nameSize = 0; }\n", out);
    xl6OutputPuts("    if ( value == 0 ) { value = \"\"; valueSize = 0; }\n", out);
    xl6OutputPuts("    if ( !xl6_query_mul3_add(nameSize, valueSize, 2, &cap) ) { return xl6_query_empty_string(); }\n", out);
    xl6OutputPuts("    outText = (char*)xrtMalloc(cap);\n", out);
    xl6OutputPuts("    if ( outText == 0 ) { return 0; }\n", out);
    xl6OutputPuts("    outText[0] = '\\0';\n", out);
    xl6OutputPuts("    if ( !xl6_query_append_field(outText, cap, &off, name, nameSize, value, valueSize, true) ) {\n", out);
    xl6OutputPuts("        xrtFree(outText);\n", out);
    xl6OutputPuts("        return xl6_query_empty_string();\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    outText[off] = '\\0';\n", out);
    xl6OutputPuts("    return outText;\n", out);
    xl6OutputPuts("}\n\n", out);

    xl6OutputPuts("void* xl6_xrt_query_append(const char* query, size_t querySize, const char* name, size_t nameSize, const char* value, size_t valueSize)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    char* outText;\n", out);
    xl6OutputPuts("    size_t pairCap;\n", out);
    xl6OutputPuts("    size_t cap;\n", out);
    xl6OutputPuts("    size_t off;\n", out);
    xl6OutputPuts("    if ( query == 0 ) { query = \"\"; querySize = 0; }\n", out);
    xl6OutputPuts("    if ( name == 0 ) { name = \"\"; nameSize = 0; }\n", out);
    xl6OutputPuts("    if ( value == 0 ) { value = \"\"; valueSize = 0; }\n", out);
    xl6OutputPuts("    if ( !xl6_query_mul3_add(nameSize, valueSize, 2, &pairCap) ) { return xl6_query_empty_string(); }\n", out);
    xl6OutputPuts("    if ( querySize > ((size_t)-1) - pairCap - 1 ) { return xl6_query_empty_string(); }\n", out);
    xl6OutputPuts("    cap = querySize + pairCap + 1;\n", out);
    xl6OutputPuts("    outText = (char*)xrtMalloc(cap);\n", out);
    xl6OutputPuts("    if ( outText == 0 ) { return 0; }\n", out);
    xl6OutputPuts("    if ( querySize > 0 ) { memcpy(outText, query, querySize); }\n", out);
    xl6OutputPuts("    off = querySize;\n", out);
    xl6OutputPuts("    outText[off] = '\\0';\n", out);
    xl6OutputPuts("    if ( !xl6_query_append_field(outText, cap, &off, name, nameSize, value, valueSize, true) ) {\n", out);
    xl6OutputPuts("        xrtFree(outText);\n", out);
    xl6OutputPuts("        return xl6_query_empty_string();\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    outText[off] = '\\0';\n", out);
    xl6OutputPuts("    return outText;\n", out);
    xl6OutputPuts("}\n\n", out);

    xl6OutputPuts("void* xl6_xrt_query_append_name(const char* query, size_t querySize, const char* name, size_t nameSize)\n", out);
    xl6OutputPuts("{\n", out);
    xl6OutputPuts("    char* outText;\n", out);
    xl6OutputPuts("    size_t pairCap;\n", out);
    xl6OutputPuts("    size_t cap;\n", out);
    xl6OutputPuts("    size_t off;\n", out);
    xl6OutputPuts("    if ( query == 0 ) { query = \"\"; querySize = 0; }\n", out);
    xl6OutputPuts("    if ( name == 0 ) { name = \"\"; nameSize = 0; }\n", out);
    xl6OutputPuts("    if ( !xl6_query_mul3_add(nameSize, 0u, 2u, &pairCap) ) { return xl6_query_empty_string(); }\n", out);
    xl6OutputPuts("    if ( querySize > ((size_t)-1) - pairCap - 1u ) { return xl6_query_empty_string(); }\n", out);
    xl6OutputPuts("    cap = querySize + pairCap + 1u;\n", out);
    xl6OutputPuts("    outText = (char*)xrtMalloc(cap);\n", out);
    xl6OutputPuts("    if ( outText == 0 ) { return 0; }\n", out);
    xl6OutputPuts("    if ( querySize > 0u ) { memcpy(outText, query, querySize); }\n", out);
    xl6OutputPuts("    off = querySize;\n", out);
    xl6OutputPuts("    outText[off] = '\\0';\n", out);
    xl6OutputPuts("    if ( !xl6_query_append_field(outText, cap, &off, name, nameSize, 0, 0u, false) ) {\n", out);
    xl6OutputPuts("        xrtFree(outText);\n", out);
    xl6OutputPuts("        return xl6_query_empty_string();\n", out);
    xl6OutputPuts("    }\n", out);
    xl6OutputPuts("    outText[off] = '\\0';\n", out);
    xl6OutputPuts("    return outText;\n", out);
    xl6OutputPuts("}\n\n", out);
    xl6OutputPuts("#endif\n\n", out);
}
