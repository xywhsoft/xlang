#!/usr/bin/env python3
"""生成标准库函数的静态哈希索引。"""

from __future__ import annotations

import argparse
import re
from pathlib import Path


CAPACITY = 4096
FNV_OFFSET = 1469598103934665603
FNV_PRIME = 1099511628211
MASK64 = (1 << 64) - 1


def hash_key(namespace: str, name: str) -> int:
    value = FNV_OFFSET
    for byte in namespace.encode("utf-8"):
        value = ((value ^ byte) * FNV_PRIME) & MASK64
    value = ((value ^ 0xFF) * FNV_PRIME) & MASK64
    for byte in name.encode("utf-8"):
        value = ((value ^ byte) * FNV_PRIME) & MASK64
    return value


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(__file__).resolve().parent.parent,
    )
    args = parser.parse_args()

    root = args.root.resolve()
    data_path = root / "src" / "stdlib" / "xl6_stdlib_data.c"
    header_path = root / "src" / "stdlib" / "xl6_stdlib_data.h"
    output_path = root / "src" / "stdlib" / "xl6_stdlib_func_index.inc"

    data = data_path.read_text(encoding="utf-8")
    header = header_path.read_text(encoding="utf-8")
    start_text = "const XL6_StdlibFunc xl6StdlibFuncs[] = {"
    start = data.find(start_text)
    if start < 0:
        raise RuntimeError("cannot find xl6StdlibFuncs table")
    end = data.find("\n};", start)
    if end < 0:
        raise RuntimeError("cannot find xl6StdlibFuncs table end")

    entries = re.findall(
        r'(?m)^\s*\{"([^"]*)",\s*"([^"]*)",',
        data[start:end],
    )
    count_match = re.search(
        r"#define\s+XL6_STDLIB_FUNC_COUNT\s+(\d+)u?",
        header,
    )
    if count_match is None:
        raise RuntimeError("cannot find XL6_STDLIB_FUNC_COUNT")
    expected = int(count_match.group(1))
    if len(entries) != expected:
        raise RuntimeError(
            f"stdlib function count mismatch: parsed {len(entries)}, expected {expected}"
        )
    if len(entries) * 2 > CAPACITY:
        raise RuntimeError(f"stdlib function index capacity {CAPACITY} is too small")

    slots = [0] * CAPACITY
    for index, (namespace, name) in enumerate(entries):
        slot = hash_key(namespace, name) % CAPACITY
        while slots[slot] != 0:
            slot = (slot + 1) & (CAPACITY - 1)
        slots[slot] = index + 1

    lines = [
        "/* Generated by the DEMO6 stdlib index generator. Do not edit manually. */",
        f"#if XL6_STDLIB_FUNC_COUNT != {len(entries)}",
        '#error "stdlib function index is stale; regenerate the stdlib index"',
        "#endif",
        "static const unsigned short "
        "xl6StdlibFuncIndex[XL6_STDLIB_FUNC_INDEX_CAPACITY] = {",
    ]
    for offset in range(0, CAPACITY, 16):
        values = ", ".join(str(value) for value in slots[offset : offset + 16])
        lines.append(f"    {values},")
    lines.append("};")
    content = "\n".join(lines) + "\n"
    if not output_path.exists() or output_path.read_text(encoding="utf-8") != content:
        output_path.write_text(content, encoding="utf-8", newline="\n")
    print(
        f"generated {CAPACITY} stdlib index slots for "
        f"{len(entries)} functions -> {output_path}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
