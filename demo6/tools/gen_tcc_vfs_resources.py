#!/usr/bin/env python3
"""根据清单生成 TCC 静态 VFS 资源表。"""

from __future__ import annotations

import argparse
import fnmatch
import subprocess
import tempfile
from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True)
class Resource:
    virtual: str
    source: Path


@dataclass(frozen=True)
class PackedResource:
    virtual: str
    data: bytes
    packed: bytes
    method: str


def normalize_virtual_name(text: str) -> str:
    return text.replace("\\", "/").strip("/").lower()


def c_string(text: str) -> str:
    result: list[str] = []
    for byte in text.encode("utf-8"):
        if byte == ord("\\"):
            result.append("\\\\")
        elif byte == ord('"'):
            result.append('\\"')
        elif 32 <= byte < 127:
            result.append(chr(byte))
        else:
            result.append(f"\\x{byte:02x}")
    return "".join(result)


def resolve_manifest_path(
    text: str,
    root: Path,
    tcc_dist: Path,
    xrt_obj: Path,
) -> Path:
    value = text
    replacements = {
        "%XL6_ROOT%": str(root),
        "%XL6_EMBED_TCC_DIST%": str(tcc_dist),
        "%XL6_EMBED_TCC_DIST_X64%": str(tcc_dist),
        "%XL6_XRT_OBJ%": str(xrt_obj),
    }
    for token, replacement in replacements.items():
        value = value.replace(token, replacement)

    # 清单可能由 Windows 与 POSIX 构建共用，统一采用 Path 可识别的分隔符。
    value = value.replace("\\", "/")
    path = Path(value)
    return (path if path.is_absolute() else root / path).resolve()


def load_resources(
    manifest: Path,
    root: Path,
    tcc_dist: Path,
    xrt_obj: Path,
) -> list[Resource]:
    resources: list[Resource] = []
    seen: set[str] = set()

    def add(virtual_name: str, source: Path) -> None:
        virtual = normalize_virtual_name(virtual_name)
        if virtual in seen:
            return
        if not source.is_file():
            raise RuntimeError(f"missing VFS resource source: {source}")
        seen.add(virtual)
        resources.append(Resource(virtual, source.resolve()))

    for raw_line in manifest.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        parts = [part.strip() for part in line.split("|")]
        if len(parts) < 3:
            raise RuntimeError(f"bad manifest line: {raw_line}")
        kind = parts[0].lower()
        if kind == "file":
            add(
                parts[1],
                resolve_manifest_path(parts[2], root, tcc_dist, xrt_obj),
            )
            continue
        if kind != "dir":
            raise RuntimeError(f"unknown manifest kind: {kind}")

        virtual_prefix = normalize_virtual_name(parts[1])
        source_dir = resolve_manifest_path(parts[2], root, tcc_dist, xrt_obj)
        if not source_dir.is_dir():
            raise RuntimeError(f"missing VFS resource directory: {source_dir}")
        patterns = [
            value.strip()
            for value in (parts[3].split(";") if len(parts) >= 4 else [])
            if value.strip()
        ]
        for source in sorted(path for path in source_dir.rglob("*") if path.is_file()):
            if patterns and not any(
                fnmatch.fnmatch(source.name, pattern) for pattern in patterns
            ):
                continue
            relative = source.relative_to(source_dir).as_posix()
            add(f"{virtual_prefix}/{relative}", source)
    return resources


def pack_resources(
    resources: list[Resource],
    pack_tool: Path,
    level: int,
    no_compress: bool,
) -> list[PackedResource]:
    if not no_compress and not pack_tool.is_file():
        raise RuntimeError(f"missing LZMA pack tool: {pack_tool}")

    packed_resources: list[PackedResource] = []
    for resource in resources:
        data = resource.source.read_bytes()
        packed = data
        method = "TCC_BUILTIN_RESOURCE_STORE"
        if not no_compress and len(data) > 32:
            with tempfile.NamedTemporaryFile(delete=False) as temp:
                temp_path = Path(temp.name)
            try:
                subprocess.run(
                    [str(pack_tool), str(resource.source), str(temp_path), str(level)],
                    check=True,
                )
                candidate = temp_path.read_bytes()
                if len(candidate) < len(data):
                    packed = candidate
                    method = "TCC_BUILTIN_RESOURCE_LZMA"
            finally:
                temp_path.unlink(missing_ok=True)
        packed_resources.append(
            PackedResource(resource.virtual, data, packed, method)
        )
    return packed_resources


def write_output(output: Path, resources: list[PackedResource]) -> None:
    lines = [
        "/* This file is generated by the DEMO6 TCC VFS resource generator. */",
        '#include "tcc_builtin_vfs.h"',
        "",
    ]
    for index, resource in enumerate(resources):
        lines.append(f"static const unsigned char tcc_builtin_res_{index:04d}[] = {{")
        if not resource.packed:
            lines.append("    0x00")
        else:
            for offset in range(0, len(resource.packed), 16):
                values = ", ".join(
                    f"0x{value:02x}"
                    for value in resource.packed[offset : offset + 16]
                )
                lines.append(f"    {values},")
        lines.extend(["};", ""])

    lines.append("const TCCBuiltinResource tcc_builtin_resources[] = {")
    for index, resource in enumerate(resources):
        lines.append(
            f'    {{ "{c_string(resource.virtual)}", '
            f"tcc_builtin_res_{index:04d}, {len(resource.packed)}u, "
            f"{len(resource.data)}u, {resource.method} }},"
        )
    lines.extend(
        [
            "};",
            "",
            "const unsigned int tcc_builtin_resources_count =",
            "    (unsigned int)(sizeof(tcc_builtin_resources) / "
            "sizeof(tcc_builtin_resources[0]));",
        ]
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--tcc-dist", type=Path, required=True)
    parser.add_argument("--xrt-obj", type=Path, required=True)
    parser.add_argument("--pack-tool", type=Path, required=True)
    parser.add_argument("--pack-level", type=int, default=9)
    parser.add_argument("--no-compress", action="store_true")
    args = parser.parse_args()

    root = args.root.resolve()
    manifest = args.manifest
    output = args.output
    tcc_dist = args.tcc_dist
    xrt_obj = args.xrt_obj
    pack_tool = args.pack_tool
    if not manifest.is_absolute():
        manifest = root / manifest
    if not output.is_absolute():
        output = root / output
    if not tcc_dist.is_absolute():
        tcc_dist = root / tcc_dist
    if not xrt_obj.is_absolute():
        xrt_obj = root / xrt_obj
    if not pack_tool.is_absolute():
        pack_tool = root / pack_tool

    resources = load_resources(
        manifest.resolve(),
        root,
        tcc_dist.resolve(),
        xrt_obj.resolve(),
    )
    packed = pack_resources(
        resources,
        pack_tool.resolve(),
        max(0, min(9, args.pack_level)),
        args.no_compress,
    )
    write_output(output.resolve(), packed)
    total = sum(len(item.data) for item in packed)
    packed_total = sum(len(item.packed) for item in packed)
    print(
        f"generated {len(packed)} TCC VFS resources, "
        f"{total} bytes packed to {packed_total} bytes -> {output.resolve()}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
