param(
    [string]$Root = "",
    [string]$StartAt = "",
    [int]$TimeoutSeconds = 30
)

$ErrorActionPreference = "Stop"

if ($Root -eq "") {
    $Root = Split-Path -Parent $PSScriptRoot
}

$xl = Join-Path $Root "release\xl.exe"
$caseRoot = Join-Path $Root "test\cases"
$outputPath = Join-Path $Root "test\extlib_smoke.generated.json"
$reportPath = Join-Path $Root "docs\extlib_smoke.generated.md"

if (!(Test-Path -LiteralPath $xl -PathType Leaf)) { throw "xl.exe is missing: $xl" }
if ($TimeoutSeconds -lt 1) { throw "TimeoutSeconds must be positive" }

$cases = @(Get-ChildItem -LiteralPath $caseRoot -File -Filter "extlib_*.xl" | Sort-Object Name)
$started = $StartAt -eq ""
$results = New-Object System.Collections.Generic.List[object]

foreach ($case in $cases) {
    if (!$started) {
        if ($case.Name -ne $StartAt) { continue }
        $started = $true
    }

    Write-Host "[catalog] $($case.Name)"
    # Native invocation is the reliable way to obtain xl.exe exit codes in
    # Windows PowerShell. A previous Start-Process/redirection version could
    # report an empty ExitCode after the process had already completed.
    $previousErrorAction = $ErrorActionPreference
    $ErrorActionPreference = "Continue"
    $outText = (& $xl run $case.FullName 2>&1 | Out-String)
    $exitCode = $LASTEXITCODE
    $ErrorActionPreference = $previousErrorAction
    $status = if ($exitCode -eq 0) { "pass" } else { "fail" }
    $results.Add([pscustomobject]@{
        case = $case.Name
        status = $status
        exitCode = $exitCode
        output = $outText.Trim()
    }) | Out-Null
}

if (!$started) { throw "Start case not found: $StartAt" }

$report = [pscustomobject]@{
    format = "xlang-extlib-catalog-smoke-1"
    generatedAt = (Get-Date).ToUniversalTime().ToString("o")
    timeoutSeconds = $TimeoutSeconds
    results = $results.ToArray()
}
[System.IO.File]::WriteAllText($outputPath, ($report | ConvertTo-Json -Depth 5), [System.Text.UTF8Encoding]::new($false))

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("# Extension Library Catalog Smoke") | Out-Null
$lines.Add("") | Out-Null
$lines.Add("Generated by tools/smoke_extlib_catalog.ps1. Results show executable test coverage, not release status.") | Out-Null
$lines.Add("") | Out-Null
$lines.Add("| Status | Count |") | Out-Null
$lines.Add("| --- | ---: |") | Out-Null
foreach ($group in @($results | Group-Object status | Sort-Object Name)) {
    $lines.Add(("| `{0}` | {1} |" -f $group.Name, $group.Count)) | Out-Null
}
$lines.Add("") | Out-Null
$lines.Add("| Case | Status | Exit | Output |") | Out-Null
$lines.Add("| --- | --- | ---: | --- |") | Out-Null
foreach ($result in $results) {
    $summary = $result.output.Replace("`r", " ").Replace("`n", " ")
    if ($summary.Length -gt 180) { $summary = $summary.Substring(0, 180) + "..." }
    $summary = $summary.Replace("|", "\\|")
    $lines.Add(("| `{0}` | `{1}` | {2} | {3} |" -f $result.case, $result.status, $result.exitCode, $summary)) | Out-Null
}
[System.IO.File]::WriteAllText($reportPath, [string]::Join("`n", $lines) + "`n", [System.Text.UTF8Encoding]::new($false))

$passed = @($results | Where-Object status -eq "pass").Count
$failed = @($results | Where-Object status -ne "pass").Count
Write-Host "Extension catalog smoke: $passed passed, $failed not passed."
exit $(if ($failed -eq 0) { 0 } else { 1 })
