/*
    生成基于当前 XRT URL ABI 的语言运行时适配层。
    XRT 负责 RFC 3986 语义，XLang 只补充语言字符串所有权和网络 URL 易用约束。
*/
/*
	此文件保留完整 URL 语言桥接实现，等待 xhttp 语言扩展接入时迁移。
	XRT 核心只提供 HTTP target/Host 底座，不再导出 xurl 产品接口。
*/
static void xl6CgenEmitUrlRuntime(XL6_Output* out)
{
    if ( out == NULL ) {
        return;
    }

    xl6OutputPuts(
        "#ifndef XL6_URL_RUNTIME\n"
        "#define XL6_URL_RUNTIME\n"
        "#include <stdint.h>\n"
        "#include <string.h>\n"
        "#define XL6_XURL_HAS_SCHEME 0x00000001u\n"
        "#define XL6_XURL_HAS_AUTHORITY 0x00000002u\n"
        "#define XL6_XURL_HAS_USERINFO 0x00000004u\n"
        "#define XL6_XURL_HAS_HOST 0x00000008u\n"
        "#define XL6_XURL_HAS_PORT 0x00000010u\n"
        "#define XL6_XURL_HAS_QUERY 0x00000020u\n"
        "#define XL6_XURL_HAS_FRAGMENT 0x00000040u\n"
        "#define XL6_XURL_HOST_IP_LITERAL 0x00000080u\n"
        "#define XL6_XURL_PORT_VALUE 0x00000200u\n"
        "#ifndef XL_RUNTIME_H\n"
        "#ifndef XL6_XRT_URL_TYPEDEF\n"
        "#define XL6_XRT_URL_TYPEDEF\n"
        "typedef struct xurl {\n"
        "    uint32_t Flags;\n"
        "    uint16_t Port;\n"
        "    xstrview Scheme;\n"
        "    xstrview Authority;\n"
        "    xstrview UserInfo;\n"
        "    xstrview Host;\n"
        "    xstrview PortText;\n"
        "    xstrview Path;\n"
        "    xstrview Query;\n"
        "    xstrview Fragment;\n"
        "} xurl;\n"
        "#endif\n"
        "#endif\n\n",
        out);

    xl6OutputPuts(
        "#ifndef XL_RUNTIME_H\n"
        "void* xrtMalloc(size_t size);\n"
        "void xrtFree(void* value);\n"
        "bool xrtUrlParse(xstrview text, xurl* url);\n"
        "uint16_t xrtUrlDefaultPort(xstrview scheme);\n"
        "bool xrtUrlPort(const xurl* url, uint16_t* port);\n"
        "bool xrtUrlSchemeIs(const xurl* url, xstrview scheme);\n"
        "bool xrtUrlSecure(const xurl* url);\n"
        "char* xrtUrlBuild(const xurl* url, size_t* size);\n"
        "bool xrtUrlAuthorityWrite(const xurl* url, void* output, size_t capacity, size_t* size);\n"
        "bool xrtUrlHostWrite(const xurl* url, void* output, size_t capacity, size_t* size);\n"
        "bool xrtUrlTargetWrite(const xurl* url, void* output, size_t capacity, size_t* size);\n"
        "char* xrtUrlPathNormalizeBuild(xstrview path, size_t* size);\n"
        "char* xrtUrlResolveBuild(const xurl* base, xstrview reference, size_t* size);\n"
        "#endif\n\n",
        out);

    xl6OutputPuts(
        "typedef bool (*xl6_url_write_fn)(\n"
        "    const xurl* url,\n"
        "    void* output,\n"
        "    size_t capacity,\n"
        "    size_t* size);\n\n\n"
        "/* 构造不依赖零结尾的 URL 文本视图。 */\n"
        "static xstrview xl6_url_view(const char* text, size_t size)\n"
        "{\n"
        "    xstrview view;\n\n"
        "    view.Data = text != 0 ? text : \"\";\n"
        "    view.Size = text != 0 ? size : 0u;\n"
        "    return view;\n"
        "}\n\n\n"
        "/* 分配语言层使用的空字符串。 */\n"
        "static void* xl6_url_empty_string(void)\n"
        "{\n"
        "    char* text = (char*)xrtMalloc(1u);\n\n"
        "    if ( text != 0 ) {\n"
        "        text[0] = 0;\n"
        "    }\n"
        "    return text;\n"
        "}\n\n\n"
        "/* 精确复制一个 URL 组件视图。 */\n"
        "static void* xl6_url_copy_text(xstrview view)\n"
        "{\n"
        "    char* text;\n\n"
        "    if ( view.Size == SIZE_MAX ) {\n"
        "        return 0;\n"
        "    }\n"
        "    text = (char*)xrtMalloc(view.Size + 1u);\n"
        "    if ( text == 0 ) {\n"
        "        return 0;\n"
        "    }\n"
        "    if ( view.Size != 0u ) {\n"
        "        memcpy(text, view.Data, view.Size);\n"
        "    }\n"
        "    text[view.Size] = 0;\n"
        "    return text;\n"
        "}\n\n\n",
        out);

    xl6OutputPuts(
        "/* 网络类 URL 必须拥有非空 host，其余合法 URI-reference 原样保留。 */\n"
        "static bool xl6_url_parse_view(const char* text, size_t size, xurl* url)\n"
        "{\n"
        "    bool network;\n\n"
        "    if ( url == 0 || !xrtUrlParse(xl6_url_view(text, size), url) ) {\n"
        "        return false;\n"
        "    }\n"
        "    network = xrtUrlSchemeIs(url, xl6_url_view(\"http\", 4u)) ||\n"
        "        xrtUrlSchemeIs(url, xl6_url_view(\"https\", 5u)) ||\n"
        "        xrtUrlSchemeIs(url, xl6_url_view(\"ws\", 2u)) ||\n"
        "        xrtUrlSchemeIs(url, xl6_url_view(\"wss\", 3u));\n"
        "    return !network ||\n"
        "        (((url->Flags & XL6_XURL_HAS_AUTHORITY) != 0u) &&\n"
        "         ((url->Flags & XL6_XURL_HAS_HOST) != 0u) &&\n"
        "         (url->Host.Size != 0u));\n"
        "}\n\n\n"
        "/* 使用 XRT 的长度查询契约分配任意 URL writer 输出。 */\n"
        "static void* xl6_url_write_alloc(const xurl* url, xl6_url_write_fn write)\n"
        "{\n"
        "    char* result;\n"
        "    size_t size = 0u;\n\n"
        "    if ( url == 0 || write == 0 || !write(url, 0, 0u, &size) ||\n"
        "         size == SIZE_MAX ) {\n"
        "        return xl6_url_empty_string();\n"
        "    }\n"
        "    result = (char*)xrtMalloc(size + 1u);\n"
        "    if ( result == 0 ) {\n"
        "        return 0;\n"
        "    }\n"
        "    if ( !write(url, result, size, &size) ) {\n"
        "        xrtFree(result);\n"
        "        return xl6_url_empty_string();\n"
        "    }\n"
        "    result[size] = 0;\n"
        "    return result;\n"
        "}\n\n\n",
        out);

    xl6OutputPuts(
        "/* 返回指定 URL 组件的独立字符串。 */\n"
        "void* xl6_xrt_url_part(const char* text, size_t size, int part)\n"
        "{\n"
        "    xurl url;\n"
        "    xstrview view = xl6_url_view(\"\", 0u);\n\n"
        "    if ( !xl6_url_parse_view(text, size, &url) ) {\n"
        "        return xl6_url_empty_string();\n"
        "    }\n"
        "    switch ( part ) {\n"
        "    case 1: view = url.Scheme; break;\n"
        "    case 2: view = url.Authority; break;\n"
        "    case 3: view = url.UserInfo; break;\n"
        "    case 4: view = url.Host; break;\n"
        "    case 5: view = url.Path; break;\n"
        "    case 6: view = url.Query; break;\n"
        "    case 7: view = url.Fragment; break;\n"
        "    case 8: return xl6_url_write_alloc(&url, xrtUrlTargetWrite);\n"
        "    default: break;\n"
        "    }\n"
        "    return xl6_url_copy_text(view);\n"
        "}\n\n\n"
        "/* 查询 URL 是否有效、是否绝对或是否使用安全网络 scheme。 */\n"
        "bool xl6_xrt_url_flag(const char* text, size_t size, int flag)\n"
        "{\n"
        "    xurl url;\n\n"
        "    if ( !xl6_url_parse_view(text, size, &url) ) {\n"
        "        return false;\n"
        "    }\n"
        "    if ( flag == 0 ) {\n"
        "        return true;\n"
        "    }\n"
        "    if ( flag == 1 ) {\n"
        "        return (url.Flags & XL6_XURL_HAS_SCHEME) != 0u;\n"
        "    }\n"
        "    if ( flag == 2 ) {\n"
        "        return xrtUrlSecure(&url);\n"
        "    }\n"
        "    return false;\n"
        "}\n\n\n"
        "/* 返回显式或 scheme 默认端口。 */\n"
        "int xl6_xrt_url_port(const char* text, size_t size)\n"
        "{\n"
        "    xurl url;\n"
        "    uint16_t port = 0u;\n\n"
        "    return xl6_url_parse_view(text, size, &url) && xrtUrlPort(&url, &port)\n"
        "        ? (int)port\n"
        "        : 0;\n"
        "}\n\n\n",
        out);

    xl6OutputPuts(
        "/* 返回已知网络 scheme 的默认端口。 */\n"
        "int xl6_xrt_url_default_port(const char* scheme, size_t size)\n"
        "{\n"
        "    return (int)xrtUrlDefaultPort(xl6_url_view(scheme, size));\n"
        "}\n\n\n"
        "/* 判断 URL 的端口是否为该 scheme 的默认值。 */\n"
        "bool xl6_xrt_url_is_default_port(const char* text, size_t size)\n"
        "{\n"
        "    xurl url;\n\n"
        "    uint16_t port = 0u;\n"
        "    uint16_t defaultPort;\n\n"
        "    if ( !xl6_url_parse_view(text, size, &url) ||\n"
        "         !xrtUrlPort(&url, &port) ) {\n"
        "        return false;\n"
        "    }\n"
        "    defaultPort = xrtUrlDefaultPort(url.Scheme);\n"
        "    return defaultPort != 0u && port == defaultPort;\n"
        "}\n\n\n"
        "/* 构建 HTTP Host header，保留显式端口和 IP literal 方括号。 */\n"
        "void* xl6_xrt_url_host_header(const char* text, size_t size)\n"
        "{\n"
        "    xurl url;\n\n"
        "    if ( !xl6_url_parse_view(text, size, &url) ||\n"
        "         (url.Flags & XL6_XURL_HAS_HOST) == 0u ||\n"
        "         url.Host.Size == 0u ) {\n"
        "        return xl6_url_empty_string();\n"
        "    }\n"
        "    return xl6_url_write_alloc(&url, xrtUrlHostWrite);\n"
        "}\n\n\n",
        out);

    xl6OutputPuts(
        "/* 从结构化组件构建一个绝对网络 URL。 */\n"
        "void* xl6_xrt_url_build(\n"
        "    const char* scheme,\n"
        "    size_t schemeSize,\n"
        "    const char* host,\n"
        "    size_t hostSize,\n"
        "    unsigned int port,\n"
        "    const char* path,\n"
        "    size_t pathSize,\n"
        "    const char* query,\n"
        "    size_t querySize,\n"
        "    const char* fragment,\n"
        "    size_t fragmentSize,\n"
        "    const char* userInfo,\n"
        "    size_t userInfoSize)\n"
        "{\n"
        "    xurl url;\n"
        "    char* result;\n"
        "    size_t resultSize = 0u;\n\n"
        "    if ( scheme == 0 || schemeSize == 0u || host == 0 || hostSize == 0u ||\n"
        "         port > 65535u ) {\n"
        "        return xl6_url_empty_string();\n"
        "    }\n"
        "    memset(&url, 0, sizeof(url));\n"
        "    url.Flags = XL6_XURL_HAS_SCHEME | XL6_XURL_HAS_AUTHORITY |\n"
        "        XL6_XURL_HAS_HOST;\n"
        "    url.Scheme = xl6_url_view(scheme, schemeSize);\n"
        "    url.Host = xl6_url_view(host, hostSize);\n"
        "    url.Path = xl6_url_view(path, pathSize);\n"
        "    url.Query = xl6_url_view(query, querySize);\n"
        "    url.Fragment = xl6_url_view(fragment, fragmentSize);\n"
        "    url.UserInfo = xl6_url_view(userInfo, userInfoSize);\n"
        "    if ( hostSize >= 2u && host[0] == '[' && host[hostSize - 1u] == ']' ) {\n"
        "        url.Host = xl6_url_view(host + 1u, hostSize - 2u);\n"
        "        url.Flags |= XL6_XURL_HOST_IP_LITERAL;\n"
        "    } else if ( memchr(host, ':', hostSize) != 0 ) {\n"
        "        url.Flags |= XL6_XURL_HOST_IP_LITERAL;\n"
        "    }\n"
        "    if ( port != 0u ) {\n"
        "        url.Port = (uint16_t)port;\n"
        "        url.Flags |= XL6_XURL_HAS_PORT | XL6_XURL_PORT_VALUE;\n"
        "    }\n"
        "    if ( querySize != 0u ) {\n"
        "        url.Flags |= XL6_XURL_HAS_QUERY;\n"
        "    }\n"
        "    if ( fragmentSize != 0u ) {\n"
        "        url.Flags |= XL6_XURL_HAS_FRAGMENT;\n"
        "    }\n"
        "    if ( userInfoSize != 0u ) {\n"
        "        url.Flags |= XL6_XURL_HAS_USERINFO;\n"
        "    }\n"
        "    result = xrtUrlBuild(&url, &resultSize);\n"
        "    return result != 0 ? result : xl6_url_empty_string();\n"
        "}\n\n\n",
        out);

    xl6OutputPuts(
        "/* 按 RFC 3986 解析相对引用，不设置固定长度上限。 */\n"
        "void* xl6_xrt_url_resolve(\n"
        "    const char* base,\n"
        "    size_t baseSize,\n"
        "    const char* reference,\n"
        "    size_t referenceSize)\n"
        "{\n"
        "    xurl baseUrl;\n"
        "    char* result;\n"
        "    size_t resultSize = 0u;\n\n"
        "    if ( !xl6_url_parse_view(base, baseSize, &baseUrl) ) {\n"
        "        return xl6_url_empty_string();\n"
        "    }\n"
        "    result = xrtUrlResolveBuild(\n"
        "        &baseUrl,\n"
        "        xl6_url_view(reference, referenceSize),\n"
        "        &resultSize);\n"
        "    return result != 0 ? result : xl6_url_empty_string();\n"
        "}\n\n\n"
        "/* 按 RFC 3986 remove_dot_segments 规范化任意长度 path。 */\n"
        "void* xl6_xrt_url_normalize_path(const char* path, size_t size)\n"
        "{\n"
        "    char* result;\n"
        "    size_t resultSize = 0u;\n\n"
        "    result = xrtUrlPathNormalizeBuild(\n"
        "        xl6_url_view(path, size),\n"
        "        &resultSize);\n"
        "    return result != 0 ? result : xl6_url_empty_string();\n"
        "}\n\n\n"
        "#endif\n\n",
        out);
}
