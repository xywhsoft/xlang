from pathlib import Path
import copy, hashlib, json

R = Path('D:/GIT/x-lang')
D = R / 'dev/release-materials/provenance/xge3-local-publication-20261105'
def read(p): return json.loads(Path(p).read_text(encoding='utf-8-sig'))
def sha(p): return hashlib.sha256(Path(p).read_bytes()).hexdigest()
def ref(p):
    p = Path(p)
    return dict(path=p.relative_to(R).as_posix(), sha256=sha(p), bytes=p.stat().st_size)
def save(p, o): Path(p).write_text(json.dumps(o, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')

old = read(D/'previous-current-delivery.json')
index = R/'dev/release-materials/provenance/current-delivery.json'
assert sha(index) == sha(D/'previous-current-delivery.json')
xmf = R/'dev/release-materials/sources/xlang-development-20261105-88bd73dc-r1.manifest.json'
x = read(xmf)
assert x['complete'] and x['passed'] and x['zipReadbackVerified']
assert not x['unownedLiveSourceRead'] and not x['releaseWritten'] and not x['buildExecuted']
archive = x['archive']
stored = archive.get('parts') or [archive]
for row in stored:
    p = R/row['path']
    assert p.is_file() and sha(p)==row['sha256'] and p.stat().st_size==row['bytes']
    assert p.stat().st_size < 100*1024*1024
nmf = R/'dev/release-materials/sources/xge3-native-20261105-r3-host2/source-manifest.json'
nr = read(R/'dev/release-materials/provenance/xge3-native-source-20261105-r3-host2.json')
assert nr['complete'] and nr['passed']
for row in nr['files']:
    assert sha(R/row['path']) == row['sha256']
na = next(row for row in nr['files'] if row['path'].endswith('.tar.gz'))
n = read(nmf)
nativefiles = {row['path']:row for row in n['files']}
smoke = read(D/'installed-receipt.json')
assert smoke['complete'] and smoke['passed'] and smoke['processSteps']==6
assert sha(D/'installed-results.json') == smoke['report']['sha256']
proof = read(D/'committed-installed-bytes.json')
assert proof['passed'] and proof['targetsVerified']==3291
for path,h in proof['targetSha256'].items(): assert sha(R/path)==h
notice = read(D/'notice-publication.json')
base = read(D/'base-license-publication.json')
for row in notice['files']+base['files']:
    assert sha(R/row['path']) == row['sha256']
assert read(D/'inherited-catalog-assets.json')['passed']
qualification = [
    'xge3-production-profiles-20261105/receipt.json',
    'xge3-final-sdk-20261105/receipt.json',
    'final-source-provider-20261105.json',
    'production-ui-examples-20261105.json',
    'xge3-ide-matched-build-20261105.json',
    'ide-sdk-provenance-preservation-20261105.json',
    'final-lsp-c-interop-20261105.json',
    'native-binding-costs-20261105.json',
]
qrefs = [ref(R/'dev/release-materials/provenance'/p) for p in qualification]
receipt = dict(schema=1, complete=True, passed=True, date='2026-11-05',
    scope='Matched XGE3/XUI3 compiler, public SDK, native extension packages, Windows GUI and language-server local installation; developer materials are outside runtime directories.',
    localInstallationPerformed=True, externalPublishPerformed=False,
    artifactCommit='88bd73dc2b4615b6dcda189eb896aaf028c173f1',
    productionAcceptanceSteps=119, productionExampleProcessSteps=34,
    installedProcessSteps=6, installedHeadlessRuns=4,
    committedInstalledTargets=3291, packageExampleTargets=146,
    windowsKnownLegacyFilesRetired=260, existingXgeNoticesPreserved=9,
    sources=[ref(xmf), ref(nmf)], sourceArchiveFiles=stored+[na],
    qualification=qrefs,
    publicationInputs=[ref(p) for p in sorted(D.iterdir()) if p.is_file() and p.name not in ('receipt.json','index-validation.json')],
    userState='The exact transaction journals exclude user settings, projects, resources and hidden example state. No independent before/after hash claim is made for user state.',
    retainedCatalog='600 existing catalog/assets files match their previous indexed bytes; static API documentation was not regenerated by this package delivery.',
    limits=['Interactive windows, GPU rendering, real OS clipboard/OLE, browser and external network operations were not executed.',
            'Direct declarative calls retain checked lifetime/error costs; the pinned cost report makes no universal zero-overhead claim.',
            'Concurrent unrelated IDE3/native work and old flat-release migration deletions were not staged.'])
assert not (D/'receipt.json').exists()
save(D/'receipt.json', receipt)
publication = ref(D/'receipt.json')

previousmaterial = read(D/'previous-win-material-index.json')
embedded = [row for row in previousmaterial['materials'] if row.get('kind')=='embedded-notice-header']
for platform in ['win_x64','linux_x64']:
    platformroot = R/'release'/platform
    entries=[]
    for row in notice['files']+base['files']:
        prefix='release/'+platform+'/'
        if row['path'].startswith(prefix):
            entries.append(dict(path=row['path'][len(prefix):], sha256=row['sha256'], bytes=row['bytes']))
    if platform=='win_x64':
        # Existing TCC notice is retained in place; Linux received the exact same bytes.
        entries.append(dict(path='notices/tcc/COPYING',sha256=sha(platformroot/'notices/tcc/COPYING'),bytes=(platformroot/'notices/tcc/COPYING').stat().st_size))
        for row in previousmaterial['materials']:
            if row['path'].startswith('data/') and (platformroot/row['path']).is_file(): entries.append(row)
    for row in embedded:
        member='xge3/'+row['source']; material=nativefiles[member]
        entries.append(dict(component=row['component'],kind='embedded-notice-header',
            sourceArchive=na['path'],
            archiveEntry=member, sha256=material['sha256'],bytes=material['bytes']))
    extensions=[p for p in previousmaterial['extensionMaterials'] if (platformroot/p).is_file()]
    if 'notices/xge/extlibs/zstd/LICENSE' not in extensions: extensions.append('notices/xge/extlibs/zstd/LICENSE')
    materialindex=dict(schema=2, date='2026-11-05', platform=platform,
        status='matched-technical-materials-index', materials=entries,
        previousMaterialIndex=ref(D/'previous-win-material-index.json'),
        localPublication=publication,
        developmentMaterials=dict(directory='../../dev/release-materials'),
        sourceAndProvenancePathsRelativeTo='repository root',
        runtimePathsRelativeTo='runtime platform directory',
        sdkMaterials=dict(sourceManifest=nmf.relative_to(R).as_posix(),sha256=sha(nmf),sourceFiles=n['sourceFiles']),
        compilerSources=dict(sourceManifest=xmf.relative_to(R).as_posix(),sha256=sha(xmf),sourceCommit=x['sourceCommit'],qualifiedCoreCommit=x['qualifiedCoreCommit'],archive=archive),
        tccMaterials=dict(sourceArchive=archive,archiveDirectory='lib/tcc/',originalNoticesPreserved=True,relinkReviewComplete=False),
        extensionMaterials=extensions, cServerSources=previousmaterial['cServerSources'],
        remaining=previousmaterial['remaining'],legalDistributionReviewComplete=False)
    save(platformroot/'notices/material-index.json',materialindex)

current=copy.deepcopy(old)
