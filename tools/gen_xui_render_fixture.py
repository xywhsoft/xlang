"""Generate test-only adapters from public Proxy signatures, never private layouts.

The matched native CPU backend has raw resources. Every resource-sensitive
callback is replaced, so it never receives a managed carrier as a raw object.
Optional retained shaping is disabled, with native text fallback exercised.
"""
from pathlib import Path
import argparse,re


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--native-root',type=Path,required=True)
    parser.add_argument('--out',type=Path,required=True)
    args=parser.parse_args()
    header=(args.native_root/'include/xui.h').read_text(encoding='utf-8-sig')
    types={name:(result.strip(),params.strip())for result,name,params in
           re.findall(r'^typedef ([^\n]+?) \(\*(\w+)\)\((.*?)\);',header,re.M|re.S)}
    body=re.search(r'^struct xui_proxy_t \{(.*?)^\};',header,re.M|re.S).group(1)
    fields=re.findall(r'^\s*(xui_\w+_proc) (\w+);',body,re.M)
    disabled={'textShape','drawTextShapeRange','textShapeRangeMeasure','drawTextShapeRangeSpans'}
    resources={'xui_surface':'SURFACE','xui_font':'FONT','xui_draw_context':'DRAW'}
    output=['/* Generated by tools/gen_xui_render_fixture.py. Test adapters only. */']
    assignments=[]
    for typename,field in fields:
        result,params=types[typename]
        parsed=[]
        for param in params.split(','):
            match=re.fullmatch(r'\s*(.*?)\b(\w+)\s*',param)
            assert match,param
            parsed.append((match[1].strip(),match[2]))
        sensitive=any(t in resources or t.rstrip('*').strip()in resources or
                      'xui_text_item_t' in t for t,n in parsed)
        if field in disabled:
            assignments.append(f'    table.{field}=NULL;')
            continue
        if not sensitive:continue
        assignments.append(f'    table.{field}=fixture_{field};')
        output.append(f'static {result} fixture_{field}({params})\n{{')
        argsout=[];created=[]
        for typ,name in parsed:
            if typ in resources:
                argsout.append(f'({typ})unwrap({name},{resources[typ]})')
            elif typ.endswith('*')and typ[:-1].strip()in resources:
                resource=typ[:-1].strip()
                output.append(f'    if(!{name})return XUI_ERROR_INVALID_ARGUMENT;')
                output.append(f'    {resource} raw_{name}=NULL;')
                argsout.append(f'&raw_{name}');created.append((resource,name))
            elif 'xui_text_item_t' in typ:
                assert typ=='const xui_text_item_t*',typ
                output.extend([f'    xui_text_item_t local_{name};',
                    f'    assert(!{name} || ({name}->iSize>=sizeof(*{name}) && !{name}->pShape));',
                    f'    if({name}){{local_{name}=*{name};local_{name}.pFont=(xui_font)unwrap({name}->pFont,FONT);}}'])
                argsout.append(f'{name}? &local_{name}:NULL')
                if field in ('drawText','drawTextSpans','textDraw'):
                    output.append(f'    observe({name});')
            else:argsout.append(name)
        if field in ('surfaceDestroy','fontDestroy','drawEnd'):
            release={'surfaceDestroy':'xuiSurfaceReleaseChecked','fontDestroy':'xuiFontReleaseChecked','drawEnd':'xuiDrawReleaseChecked'}[field]
            resource=next(name for typ,name in parsed if typ in resources)
            output.append(f'    (void)pProxy;'+('return 'if result!='void'else'(void)')+f'{release}({resource});')
        else:
            call=f'backend.tProxy.{field}('+','.join(argsout)+')'
            if created:
                assert len(created)==1 and result=='int'
                resource,name=created[0]
                target='pTarget'if resource=='xui_draw_context'else'NULL'
                output.extend([f'    int status={call};',
                    f'    if(status!=XUI_OK){{assert(!raw_{name});return status;}}',
                    '    void* managed=NULL;',
                    f'    status=wrapResource(pProxy,{resources[resource]},raw_{name},&managed,{target});',
                    f'    *{name}=({resource})managed;return status;'])
            else:output.append('    '+('return 'if result!='void'else'')+call+';')
        output.append('}')
    output.extend(['static void adapt(xui_proxy_t* output)','{','    xui_proxy_t table=backend.tProxy;',*assignments,'    *output=table;','}',''])
    args.out.write_text('\n'.join(output),encoding='utf-8',newline='\n')


if __name__=='__main__':main()
