"""Generate the exact module-filtered native XRT address catalog.

The catalog is included only after the selected native implementation, in that
same translation unit. Repeated module witnesses are conjunctive, never unioned.
The historical producer comment remains byte-identical to existing cohorts.
"""
from pathlib import Path
import argparse
import re


def render_host_catalog(root):
    """Same exact native ownership witness; multiple rows are a conjunction."""
    rows = re.findall(r'XL6_ARTIFACT_NATIVE_SYMBOL\("([^"]+)", (?:"([^"]+)"|NULL)\)',
                      (root / 'src/compile/xl6_artifact_native_symbols.inc').read_text(encoding='utf-8'))
    grouped = {}
    for name, module in rows:
        grouped.setdefault(name, []).append(module)
    lines = ['/* Generated by tools/stage_xge3_packages.py --update-host-catalog. */',
             '/* Exact linkage witnesses; include after the selected implementation. */']
    previous = None
    for name, modules in grouped.items():
        terms = []
        for module in modules:
            if module:
                feature = module.replace('_MODULE_', '_FEATURE_', 1)
                terms.append('defined(' + feature + ')')
        condition = ' && '.join(terms)
        if condition != previous:
            if previous: lines.append('#endif')
            if condition: lines.append('#if ' + condition)
        lines.append('XL6_HOST_XRT_SYMBOL(' + name + ')')
        previous = condition
    if previous: lines.append('#endif')
    return '\n'.join(lines) + '\n'


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root',type=Path,default=Path(__file__).resolve().parents[1])
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args();root=args.root.resolve()
    target=root/'src/runtime/xl6_host_xrt_symbols.h'
    expected=render_host_catalog(root).encode('utf-8')
    if args.check:
        if target.read_bytes()!=expected:raise SystemExit('Stale host XRT catalog')
    else:target.write_bytes(expected)


if __name__=='__main__':main()
