param(
    [string]$Root = (Split-Path -Parent $PSScriptRoot)
)

$ErrorActionPreference = 'Stop'

$dataPath = Join-Path $Root 'src\stdlib\xl6_stdlib_data.c'
$headerPath = Join-Path $Root 'src\stdlib\xl6_stdlib_data.h'
$outputPath = Join-Path $Root 'src\stdlib\xl6_stdlib_func_index.inc'
$capacity = 4096

$data = [System.IO.File]::ReadAllText($dataPath, [System.Text.Encoding]::UTF8)
$header = [System.IO.File]::ReadAllText($headerPath, [System.Text.Encoding]::UTF8)
$constStartText = 'const XL6_StdlibConst xl6StdlibConsts[] = {'
$constStart = $data.IndexOf($constStartText, [System.StringComparison]::Ordinal)
if ($constStart -lt 0) {
    throw 'cannot find xl6StdlibConsts table'
}
$constEnd = $data.IndexOf("`n};", $constStart, [System.StringComparison]::Ordinal)
if ($constEnd -lt 0) {
    throw 'cannot find xl6StdlibConsts table end'
}

$constSection = $data.Substring($constStart, $constEnd - $constStart)
$constCount = [regex]::Matches($constSection, '(?m)^\s*\{"').Count
if ($constCount -eq 0) {
    throw 'stdlib constant table is empty'
}

$startText = 'const XL6_StdlibFunc xl6StdlibFuncs[] = {'
$start = $data.IndexOf($startText, [System.StringComparison]::Ordinal)
if ($start -lt 0) {
    throw 'cannot find xl6StdlibFuncs table'
}
$end = $data.IndexOf("`n};", $start, [System.StringComparison]::Ordinal)
if ($end -lt 0) {
    throw 'cannot find xl6StdlibFuncs table end'
}

$entries = [System.Collections.Generic.List[object]]::new()
$section = $data.Substring($start, $end - $start)
foreach ($match in [regex]::Matches($section, '(?m)^\s*\{"([^"]*)",\s*"([^"]*)",')) {
    $entries.Add([pscustomobject]@{ Namespace = $match.Groups[1].Value; Name = $match.Groups[2].Value })
}

$countMatch = [regex]::Match($header, '#define\s+XL6_STDLIB_FUNC_COUNT\s+(\d+)u?')
if (-not $countMatch.Success) {
    throw 'cannot find XL6_STDLIB_FUNC_COUNT'
}
$constCountMatch = [regex]::Match($header, '#define\s+XL6_STDLIB_CONST_COUNT\s+(\d+)u?')
if (-not $constCountMatch.Success) {
    throw 'cannot find XL6_STDLIB_CONST_COUNT'
}
if ($entries.Count -eq 0 -or $entries.Count -ge 65535) {
    throw "stdlib function count $($entries.Count) is outside the uint16 index range"
}
$updatedHeader = $header.Remove(
    $countMatch.Groups[1].Index,
    $countMatch.Groups[1].Length
).Insert($countMatch.Groups[1].Index, [string]$entries.Count)
$updatedHeader = $updatedHeader.Remove(
    $constCountMatch.Groups[1].Index,
    $constCountMatch.Groups[1].Length
).Insert($constCountMatch.Groups[1].Index, [string]$constCount)
if ($updatedHeader -ne $header) {
    [System.IO.File]::WriteAllText(
        $headerPath,
        $updatedHeader,
        [System.Text.UTF8Encoding]::new($false)
    )
}
if ($entries.Count * 2 -gt $capacity) {
    throw "stdlib function index capacity $capacity is too small"
}

$modulus = [System.Numerics.BigInteger]::One -shl 64
$offset = [System.Numerics.BigInteger]::Parse('1469598103934665603')
$prime = [System.Numerics.BigInteger]::Parse('1099511628211')
$slots = [uint16[]]::new($capacity)
$utf8 = [System.Text.UTF8Encoding]::new($false)

function Add-HashByte([System.Numerics.BigInteger]$Hash, [byte]$Value) {
    $mixed = [System.Numerics.BigInteger]::op_ExclusiveOr($Hash, [System.Numerics.BigInteger]$Value)
    return ($mixed * $prime) % $modulus
}

for ($i = 0; $i -lt $entries.Count; ++$i) {
    $hash = $offset
    foreach ($value in $utf8.GetBytes($entries[$i].Namespace)) {
        $hash = Add-HashByte $hash $value
    }
    $hash = Add-HashByte $hash 0xFF
    foreach ($value in $utf8.GetBytes($entries[$i].Name)) {
        $hash = Add-HashByte $hash $value
    }
    $slot = [int]($hash % $capacity)
    while ($slots[$slot] -ne 0) {
        $slot = ($slot + 1) -band ($capacity - 1)
    }
    $slots[$slot] = [uint16]($i + 1)
}

$builder = [System.Text.StringBuilder]::new()
[void]$builder.AppendLine('/* Generated by the DEMO6 stdlib index generator. Do not edit manually. */')
[void]$builder.AppendLine("#if XL6_STDLIB_FUNC_COUNT != $($entries.Count)")
[void]$builder.AppendLine('#error "stdlib function index is stale; regenerate the stdlib index"')
[void]$builder.AppendLine('#endif')
[void]$builder.AppendLine('static const unsigned short xl6StdlibFuncIndex[XL6_STDLIB_FUNC_INDEX_CAPACITY] = {')
for ($i = 0; $i -lt $capacity; $i += 16) {
    $values = for ($j = 0; $j -lt 16; ++$j) { [string]$slots[$i + $j] }
    [void]$builder.Append('    ')
    [void]$builder.Append(($values -join ', '))
    [void]$builder.AppendLine(',')
}
[void]$builder.AppendLine('};')

$content = $builder.ToString().Replace("`r`n", "`n")
if (-not (Test-Path -LiteralPath $outputPath) -or
    [System.IO.File]::ReadAllText($outputPath) -cne $content) {
    [System.IO.File]::WriteAllText($outputPath, $content, [System.Text.UTF8Encoding]::new($false))
}
Write-Host "generated $capacity stdlib index slots for $($entries.Count) functions and $constCount constants -> $outputPath"
