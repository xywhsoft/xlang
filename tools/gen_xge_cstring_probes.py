"""Generate compile/ABI probes for declared direct borrowed C-string results.

The declaration itself records the reviewed return contract. This generator
does not infer borrowing from a native pointer or certify runtime lifetimes.
"""
from pathlib import Path
import argparse,json,re
from check_xge3_full_surface import source_bindings


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root',type=Path,default=Path(__file__).resolve().parents[1])
    parser.add_argument('--out',type=Path,required=True)
    args=parser.parse_args();root=args.root.resolve();functions,_,_,_,_=source_bindings(root)
    rows=[];source=['// Generated by tools/gen_xge_cstring_probes.py; ABI probes, not runtime acceptance.','import xge','import xui','']
    for symbol,bindings in sorted(functions.items()):
        for binding in bindings:
            line=(root/binding['source']).read_text(encoding='utf-8-sig').splitlines()[binding['line']-1]
            if '@c_result("cstring")'not in line:continue
            match=re.search(r'\b(func|get) (\w+)\(([^)]*)\) as (string\??)\s*$',line)
            assert match,line
            kind,name,arguments,result=match.groups();parts=binding['language'].split('.')
            parameters=[];values=[]
            for parameter in arguments.split(',')if arguments.strip()else[]:
                parameter=parameter.split('=',1)[0].strip();arg=re.fullmatch(r'(c_int|c_uint|int|uint64|c_size)\s+(\w+)',parameter)
                assert arg,parameter;parameters.append(parameter);values.append(arg[2])
            if len(parts)==3:
                parameters.insert(0,parts[0]+'.'+parts[1]+' target');expression='target.'+name
            else:assert len(parts)==2;expression=parts[0]+'.'+name
            if kind=='func':expression+='('+','.join(values)+')'
            else:assert not values
            probe='cstringProbe'+str(len(rows));source+=['// '+symbol,'export func '+probe+'('+','.join(parameters)+') as '+result,' return '+expression,'end','']
            rows.append(dict(probe=probe,symbol=symbol,language=binding['language'],source=binding['source'],line=binding['line']))
    args.out.parent.mkdir(parents=True,exist_ok=True)
    args.out.write_text('\n'.join(source),encoding='utf-8');args.out.with_suffix('.json').write_text(json.dumps(dict(scope=__doc__,rows=rows),indent=2)+'\n',encoding='utf-8');print(len(rows),args.out)


if __name__=='__main__':main()
