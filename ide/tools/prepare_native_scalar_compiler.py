"""Prepare the pinned native-path compiler with the optional scalar query patch."""
import argparse,base64,hashlib,json,shutil
from pathlib import Path
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def prepare(seed,manifest,output):
    seed=Path(seed).resolve();manifest=Path(manifest).resolve();output=Path(output).absolute()
    patches=Path(__file__).resolve().parent.parent/'third_party/compiler_patches/native-c-scalars-v2'
    record=json.loads((patches/'changes.json').read_text(encoding='utf8'))
    assert record['format']=='xlang-ide-private-compiler-patch-1'
    assert sha(manifest)==record['seedSourceManifestSha256']
    rows=json.loads(manifest.read_text(encoding='utf8'))['files']
    assert len(rows)==record['seedSourceFiles'] and not output.exists()
    assert not output.resolve().is_relative_to(seed) and not seed.is_relative_to(output.resolve())
    for row in rows+record['rootBuildScripts']:
        p=seed/row['path'];assert p.resolve().is_relative_to(seed) and sha(p)==row['sha256'],row['path']
    replacements={}
    for row in record['changedFiles']:
        data=(seed/row['path']).read_bytes();assert hashlib.sha256(data).hexdigest()==row['beforeSha256']
        parts=[];cursor=0
        for edit in row['edits']:
            at=edit['offset'];old=base64.b64decode(edit['removeBase64'],validate=True);new=base64.b64decode(edit['insertBase64'],validate=True)
            assert cursor<=at<=len(data) and data[at:at+len(old)]==old
            parts.extend((data[cursor:at],new));cursor=at+len(old)
        result=b''.join(parts+[data[cursor:]])
        assert hashlib.sha256(result).hexdigest()==row['afterSha256'];replacements[row['path']]=result
    # Copy only the validated source inventory and root scripts. Build outputs
    # are generated by build.bat; no previous executables are promoted as new.
    output.mkdir(parents=True)
    expected={row['path']:row['sha256'] for row in rows+record['rootBuildScripts']}
    for name in expected:
        p=output/name;p.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(seed/name,p)
    for name,data in replacements.items():(output/name).write_bytes(data)
    expected.update({row['path']:row['afterSha256'] for row in record['changedFiles']})
    for name,digest in expected.items():assert sha(output/name)==digest,name
    for row in rows+record['rootBuildScripts']:assert sha(seed/row['path'])==row['sha256']
    report={'format':'xlang-ide-prepared-native-scalar-compiler-1','seed':str(seed),'sourceManifest':str(manifest),'sourceManifestSha256':sha(manifest),'patchSha256':sha(patches/'changes.json'),'files':[{'path':n,'sha256':h} for n,h in expected.items()],'prepared':True,'built':False,'formalRelease':False}
    (output/'prepared-native-scalar-source.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf8')
    print('Prepared',len(expected),'verified inputs in',output,flush=True)
    return report
if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__)
    for name in ('seed','manifest','output'):ap.add_argument('--'+name,required=True)
    a=ap.parse_args();prepare(a.seed,a.manifest,a.output)
